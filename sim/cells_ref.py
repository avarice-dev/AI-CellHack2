"""Python reference policies for our own asm cells (cells/*.asm).

sprint(view, mem) mirrors cells/sprint.asm decision for decision and returns
(action, insn, insn_no_taken_jumps) with the exact path counts of the asm (every executed instruction,
including taken jumps and ret; the third value leaves taken jumps out, the indirect `jmp [table]`
counting as a taken jump).  Written independently of cells/gen_sprint.py's tables so the two can be
checked against each other (sim/tests/test_cells_ref.py).
"""

from engine import ACT_REST, ACT_MOVE, ACT_SPLIT, ACT_EAT, ACT_FEED, CELL_FRIEND, CELL_ENEMY, CELL_EMPTY, VIEW_DIR, VIEW_CENTER

DOWN, LEFT, UP, RIGHT = 2, 3, 0, 1
SPRINT_FIGHT_PRIO = (DOWN, LEFT, UP, RIGHT)
SPRINT_SPLIT_PRIO = (DOWN, RIGHT, UP, LEFT)
SPRINT_SPLIT_MIN = 5
SPRINT_THREAT_MIN = 16
SPRINT_LATE_TICK = 2980


def _sprint_bite(enemies):
    if len(enemies) == 3:
        free = [d for d in range(4) if d not in enemies][0]
        return (free + 2) & 3                 # opposite of the one non-enemy side
    for d in SPRINT_FIGHT_PRIO:
        if d in enemies:
            return d


def _sprint_split(c):
    for d in SPRINT_SPLIT_PRIO:
        if c[VIEW_DIR[d]] == CELL_EMPTY:
            return ACT_SPLIT + d
    return ACT_REST                            # split_tbl mask 0


def sprint(view, mem):
    c = view.cells
    enemies = [d for d in range(4) if c[VIEW_DIR[d]] == CELL_ENEMY]
    # movdqu, pcmpeqb, pmovmskb, jmp [tbl] (4) -> mov, ret
    if enemies:
        return ACT_EAT + _sprint_bite(enemies), 6, 5
    e = view.energy
    # slow: cmp, jb (6 so far)
    if e < SPRINT_SPLIT_MIN:
        return ACT_REST, 8, 6                  # jb taken -> mov, ret
    # movdqu x2, pcmpeqb x2, por, pmovmskb, test, jnz (14 so far)
    seen = any(c[i] == CELL_ENEMY for i in range(25) if i != VIEW_CENTER)
    if not seen:
        return _sprint_split(c), 19, 18        # fall into split: movdqu, pcmpeqb, pmovmskb, mov, ret
    # threat (jnz taken): cmp, jae
    if e >= SPRINT_THREAT_MIN:
        return _sprint_split(c), 21, 18
    # cmp dword tick, jae
    if view.tick >= SPRINT_LATE_TICK:
        return _sprint_split(c), 23, 20
    return ACT_REST, 20, 18                    # fall into rest: mov, ret


# ---- Covetous (cells/covetous.asm, generated by cells/gen_covetous.py) ---------------------------------
# Sprint's bite and split choices; bite in 5 (`or al, [bite_tbl+rcx]` / `jnz EXIT_ADDR`); a cell that would
# rest with energy >= feed_min feeds its poorest friend neighbour (ties U, R, D, L) if that one is <= feed_tmax.
COVETOUS_FEED_MIN = 47
COVETOUS_FEED_TMAX = 46
_FEED_ORDER = (UP, RIGHT, DOWN, LEFT)


def _covetous_feed(view, c, n, t, feed_min, tmax):
    """Feed block entered after n instructions with t taken jumps.  Returns (action, insn, alt)."""
    e = view.energy
    n += 2                                     # cmp, jb
    if e < feed_min:
        return ACT_REST, n + 2, n + 2 - (t + 1)
    n += 2                                     # mov r8d, 255 / mov eax, ACT_REST
    best, act = 255, ACT_REST
    en = view.energies
    for d in _FEED_ORDER:
        i = VIEW_DIR[d]
        if c[i] != CELL_FRIEND:
            n += 2                             # cmp, jne (taken)
            t += 1
        elif en[i] >= best:
            n += 5                             # cmp, jne, movzx, cmp, jae (taken)
            t += 1
        else:
            n += 7
            best, act = en[i], ACT_FEED + d
    n += 2                                     # cmp r8d, tmax / ja
    if best > tmax:
        return ACT_REST, n + 2, n + 2 - (t + 1)
    return act, n + 1, n + 1 - t


def make_covetous(feed_min=COVETOUS_FEED_MIN, feed_tmax=COVETOUS_FEED_TMAX):
    def covetous(view, mem):
        c = view.cells
        enemies = [d for d in range(4) if c[VIEW_DIR[d]] == CELL_ENEMY]
        # movdqu, pcmpeqb, pmovmskb, or al, jnz EXIT (taken)
        if enemies:
            return ACT_EAT + _sprint_bite(enemies), 5, 4
        e = view.energy
        if e < SPRINT_SPLIT_MIN:               # cmp, jb (taken) -> mov, ret
            return ACT_REST, 9, 8
        n, t = 15, 0                           # + movdqu x2, pcmpeqb x2, por, pmovmskb, test, jnz
        if any(c[i] == CELL_ENEMY for i in range(25) if i != VIEW_CENTER):
            n, t = 17, 1                       # jnz taken; cmp, jae
            if e < SPRINT_THREAT_MIN:
                n += 2                         # cmp tick, jae
                if view.tick < SPRINT_LATE_TICK:
                    return _covetous_feed(view, c, n, t, feed_min, feed_tmax)
            t += 1                             # one jae taken -> split
        n += 5                                 # movdqu, pcmpeqb, pmovmskb, test, jz
        if not any(c[VIEW_DIR[d]] == CELL_EMPTY for d in range(4)):
            return _covetous_feed(view, c, n, t + 1, feed_min, feed_tmax)
        return _sprint_split(c), n + 2, n + 2 - t
    return covetous


covetous = make_covetous()


# ---- Scourge (cells/scourge.asm, generated by cells/gen_scourge.py) -----------------------------------
# Covetous's bite; then one 16-byte window (view idx 6..21) decides in 11 instructions: a refill of a freed
# front square (empty neighbour with an enemy beside or beyond it, among the squares the window reads) when
# the child gets >= refill_min / 2, else a plain split at e >= threat_min.  Below that: plain split at e >= 5
# if no enemy is anywhere in the 5x5 (or from tick 2980), else hold.  Boxed cells (no empty neighbour) with
# e >= feed_d feed the poorest friend neighbour if it is <= e - feed_margin (capped donors e >= feed_min:
# <= feed_tmax).  Squares 2 and 22 (beyond UP / DOWN) lie outside the window and are not read.
SCOURGE_FREED_BY = {UP: (6, 8), RIGHT: (8, 14, 18), DOWN: (16, 18), LEFT: (6, 10, 16)}
SCOURGE_REFILL_MIN = 12       # parent energy for a refill (child >= R = 6)
SCOURGE_THREAT_MIN = 16       # prey rule: child >= 8
SCOURGE_FEED_D = 16
SCOURGE_FEED_MARGIN = 4


def make_scourge(refill_min=SCOURGE_REFILL_MIN, threat_min=SCOURGE_THREAT_MIN, feed_d=SCOURGE_FEED_D,
                 feed_margin=SCOURGE_FEED_MARGIN, feed_min=COVETOUS_FEED_MIN, feed_tmax=COVETOUS_FEED_TMAX):
    def scourge(view, mem):
        c = view.cells
        enemies = [d for d in range(4) if c[VIEW_DIR[d]] == CELL_ENEMY]
        if enemies:                            # F5: movdqu, pcmpeqb, pmovmskb, or al, jnz EXIT (taken)
            return ACT_EAT + _sprint_bite(enemies), 5, 4
        e = view.energy
        empty = [d for d in SPRINT_SPLIT_PRIO if c[VIEW_DIR[d]] == CELL_EMPTY]
        freed = [d for d in empty if any(c[i] == CELL_ENEMY for i in SCOURGE_FREED_BY[d])]
        # gate 1: movdqu, pcmpeqb, pmovmskb, mov al, cmp sil, jae EXIT (11 when taken)
        if empty and e >= (min(refill_min, threat_min) if freed else threat_min):
            return ACT_SPLIT + (freed or empty)[0], 11, 10
        if not empty:                          # test al, al / jz boxed (taken): 13
            n, t = 15, 2                       # cmp esi, feed_d / jb rest
            if e < feed_d:
                return ACT_REST, n + 2, n + 2 - t
            t = 1
            limit = feed_tmax if e >= feed_min else e - feed_margin
            n = 21                             # lea, mov, cmp, cmovae, mov r8d, mov eax
            best, act = 255, ACT_REST
            en = view.energies
            for d in _FEED_ORDER:
                i = VIEW_DIR[d]
                if c[i] != CELL_FRIEND:
                    n, t = n + 2, t + 1
                elif en[i] >= best:
                    n, t = n + 5, t + 1
                else:
                    n += 7
                    best, act = en[i], ACT_FEED + d
            n += 2                             # cmp r8d, r9d / ja
            if best > limit:
                return ACT_REST, n + 2, n + 2 - (t + 1)
            return act, n + 1, n + 1 - t
        act = ACT_SPLIT + (freed or empty)[0]
        if e < SPRINT_SPLIT_MIN:               # cmp esi, 5 / jb rest (taken) -> mov, ret
            return ACT_REST, 17, 16
        # movdqu x2, pcmpeqb x2, por, pmovmskb, test, jnz: 23
        if not any(c[i] == CELL_ENEMY for i in range(25) if i != VIEW_CENTER):
            return act, 24, 24                 # ret
        if view.tick >= SPRINT_LATE_TICK:      # threat: cmp tick, jae EXIT (taken)
            return act, 25, 23
        return ACT_REST, 27, 26                # fall into rest: mov, ret
    return scourge


scourge = make_scourge()


# ---- Contagion (cells/contagion.asm, generated by cells/gen_contagion.py) -------------------------------
# Scourge's bite and gate 1 unchanged (5 / 11, no memory); feeding floor 12; grab assist (boxed, e >= grab_g,
# no enemy in the 5x5: feed the first friend neighbour U, R, D, L with energy <= 4 and an empty neighbour);
# one scout at tick 0 from a start within `edge` squares of an edge, moving up to `steps` squares along the
# side with the most room.  Memory: [1] flags (bit 0 initialised, bit 1 scout), [2] origin x, [3] origin y,
# [4] bearing, [5] steps left.
CONTAGION_FEED_D = 12
CONTAGION_GRAB_G = 8
CONTAGION_GRAB_TMAX = 4
CONTAGION_EDGE = 10
CONTAGION_STEPS = 10
_RING = {UP: (2, 6, 8), RIGHT: (8, 14, 18), DOWN: (16, 18, 22), LEFT: (6, 10, 16)}


def _feed_block(view, c, e, feed_min, feed_tmax, feed_margin, n, t):
    """Scourge's feed block entered after n instructions with t taken jumps (lea .. mov eax done)."""
    limit = feed_tmax if e >= feed_min else e - feed_margin
    best, act = 255, ACT_REST
    en = view.energies
    for d in _FEED_ORDER:
        i = VIEW_DIR[d]
        if c[i] != CELL_FRIEND:
            n, t = n + 2, t + 1
        elif en[i] >= best:
            n, t = n + 5, t + 1
        else:
            n += 7
            best, act = en[i], ACT_FEED + d
    n += 2                                     # cmp r8d, r9d / ja
    if best > limit:
        return ACT_REST, n + 2, n + 2 - (t + 1)
    return act, n + 1, n + 1 - t


def make_contagion(refill_min=SCOURGE_REFILL_MIN, threat_min=SCOURGE_THREAT_MIN, feed_d=CONTAGION_FEED_D,
                   feed_margin=SCOURGE_FEED_MARGIN, feed_min=COVETOUS_FEED_MIN, feed_tmax=COVETOUS_FEED_TMAX,
                   grab_g=CONTAGION_GRAB_G, edge=CONTAGION_EDGE, steps=CONTAGION_STEPS):
    def contagion(view, mem):
        c = view.cells
        enemies = [d for d in range(4) if c[VIEW_DIR[d]] == CELL_ENEMY]
        if enemies:                            # F5 (5)
            return ACT_EAT + _sprint_bite(enemies), 5, 4
        e = view.energy
        empty = [d for d in SPRINT_SPLIT_PRIO if c[VIEW_DIR[d]] == CELL_EMPTY]
        freed = [d for d in empty if any(c[i] == CELL_ENEMY for i in SCOURGE_FREED_BY[d])]
        if empty and e >= (min(refill_min, threat_min) if freed else threat_min):
            return ACT_SPLIT + (freed or empty)[0], 11, 10      # gate 1 (11)
        seen = any(c[i] == CELL_ENEMY for i in range(25) if i != VIEW_CENTER)
        if not empty:                          # test, jz boxed (taken) = 13
            if e < grab_g:                     # cmp, jb rest (taken), mov, ret
                return ACT_REST, 17, 15
            n, t = 27, 1                       # movdqu x2, pxor x2, pcmpeqb x4, por, pmovmskb, test, jnz
            if seen:
                t += 1                         # jnz feed_d taken
            else:
                n += 4                         # pmovmskb x2, shl, or
                for d, i in ((UP, 7), (RIGHT, 13), (DOWN, 17), (LEFT, 11)):
                    if c[i] != CELL_FRIEND:
                        n, t = n + 2, t + 1
                    elif view.energies[i] > CONTAGION_GRAB_TMAX:
                        n, t = n + 4, t + 1
                    elif not any(c[q] == CELL_EMPTY for q in _RING[d]):
                        n, t = n + 6, t + 1
                    else:
                        return ACT_FEED + d, n + 8, n + 8 - t
            n += 2                             # feed_d: cmp esi, feed_d / jb rest
            if e < feed_d:
                return ACT_REST, n + 2, n + 2 - (t + 1)
            return _feed_block(view, c, e, feed_min, feed_tmax, feed_margin, n + 6, t)
        act = ACT_SPLIT + (freed or empty)[0]
        if e < SPRINT_SPLIT_MIN:               # cmp esi, 5 / jb rest (taken) -> mov, ret
            return ACT_REST, 17, 16
        if seen:                               # 5x5 check, jnz threat (taken) = 23
            if view.tick >= SPRINT_LATE_TICK:  # cmp tick, jae EXIT (taken)
                return act, 25, 23
            mem[1] &= 0xFD                     # hold: and, mov, ret
            return ACT_REST, 28, 27
        if mem[1] == 1:                        # cmp byte [rdx+1], 1 / jne / ret
            return act, 26, 26
        if not mem[1] & 2:                     # special (taken, 25): test, jnz (26, 27): init
            mem[1] = 1
            if view.tick != 0:                 # mov flag, cmp tick, jne .plain (taken), ret
                return act, 31, 29
            x, y = view.x, view.y
            room = {LEFT: x, RIGHT: view.w - x - 1, UP: y, DOWN: view.h - y - 1}
            # mov flag, cmp tick, jne, 4 movzx, 2 sub, 2 dec, mov esi, 3 x (cmp, cmova), cmp edge, ja = 47
            if min(room.values()) > edge:
                return act, 48, 46             # ja .plain (taken), ret
            n, t = 49, 1                       # mov r11d, xor esi
            bear, best = UP, room[UP]
            for d, more in ((RIGHT, 2), (DOWN, 2), (LEFT, 1)):
                n += 2                         # cmp, jbe
                if room[d] > best:
                    n += more
                    bear, best = d, room[d]
                else:
                    t += 1
            mem[1], mem[2], mem[3], mem[4], mem[5] = 3, x & 0xFF, y & 0xFF, bear, steps
            n += 7                             # 5 stores, lea, ret
            return ACT_SPLIT + bear, n, n - t
        # scout (jnz taken, 27): mov cl, mov ch, cmp, je
        n, t = 31, 2
        if (view.x & 0xFF, view.y & 0xFF) == (mem[2], mem[3]):
            mem[1] = 1                         # scout_end: mov, ret
            return act, n + 2, n + 2 - (t + 1)
        n += 2                                 # cmp steps, je
        if mem[5] == 0:
            mem[1] = 1
            return act, n + 2, n + 2 - (t + 1)
        bear = mem[4] & 3
        n += 4                                 # movzx x2, cmp, jne
        if c[VIEW_DIR[bear]] != CELL_EMPTY:
            mem[1] = 1
            return act, n + 2, n + 2 - (t + 1)
        mem[5] -= 1
        return ACT_MOVE + bear, n + 3, n + 3 - t
    return contagion


contagion = make_contagion()
# ---- VEX/AVX-128 variants (designs.md round 5; cells/gen_woe.py, gen_conceit.py, gen_endemic.py) --------------
# Same decisions as the parent; the bite still takes 5.  The VEX compare is non-destructive and takes an unaligned
# memory operand, so one raw view window loaded by the bite is reused later:
#   Woe (of Scourge) and Endemic (of Contagion): the bite reads window 6..21 (bite mask shifted one lane) and gate 1
#     compares that register again (vpcmpeqb xmm1, xmm3, [kRefill]): -1 on every path after the bite.  Endemic's
#     boxed block also builds its empty masks with vpcmpeqb against a zero constant instead of pxor + pcmpeqb: -2 more
#     there (boxed, e >= grab_g).
#   Conceit (of Covetous): the split check compares the bite's raw window 7..22 again: -1 on every path through it.
def _vex_saved(view, kind, grab_g):
    c = view.cells
    if any(c[VIEW_DIR[d]] == CELL_ENEMY for d in range(4)):
        return 0
    e = view.energy
    if kind == 'gate':
        return 1
    if kind == 'endemic':
        boxed = not any(c[VIEW_DIR[d]] == CELL_EMPTY for d in range(4))
        return 3 if boxed and e >= grab_g else 1
    if e < SPRINT_SPLIT_MIN:                   # conceit: rest before the split check
        return 0
    seen = any(c[i] == CELL_ENEMY for i in range(25) if i != VIEW_CENTER)
    if seen and e < SPRINT_THREAT_MIN and view.tick < SPRINT_LATE_TICK:
        return 0                               # holding: straight to the feed block
    return 1


def _vex(parent, kind, grab_g=CONTAGION_GRAB_G):
    def policy(view, mem):
        act, n, t = parent(view, mem)
        d = _vex_saved(view, kind, grab_g)
        return act, n - d, t - d
    return policy


def make_woe(**kw):
    return _vex(make_scourge(**kw), 'gate')


def make_conceit(**kw):
    return _vex(make_covetous(**kw), 'conceit')


def make_endemic(**kw):
    return _vex(make_contagion(**kw), 'endemic', kw.get('grab_g', CONTAGION_GRAB_G))


woe = make_woe()
conceit = make_conceit()
endemic = make_endemic()


# ---- Complacency (cells/complacency.asm, generated by cells/gen_complacency.py; designs.md section 9) -----------
# Scourge plus early free splitting: on Scourge's middle path (no adjacent enemy, an empty neighbour, gate 1 not
# taken, 5 <= e < 16) a cell splits while tick < free_until even with an enemy in the 5x5; from free_until on it is
# Scourge.  The asm checks the tick first on that path (cmp dword [tick], T / jb EXIT_ADDR), so the early split
# takes 17 (Scourge 24 / 25, or a 27 hold) and every later path through the 5x5 check takes Scourge's count + 2.
# free_until >= SPRINT_LATE_TICK: no hold ever, the 5x5 check is dropped (split = 16, a plain ret).
# (Drafted on Woe; rebased on Scourge 2026-11-08: Woe's VEX form is broken on the site, calib-s.)
# diag_hold=True (sim probe): hold only when an enemy is on a diagonal (view 6, 8, 16, 18) instead of anywhere in
# the 5x5, until tick 2980.  Gate 1's mask in ecx already has those four squares (kRefill lanes 0, 2, 10, 12), so
# the asm would be `test ecx, DIAG` / `jnz threat` / `ret` in place of the 5x5 check.
COMPLACENCY_FREE_UNTIL = 3000
_DIAG = (6, 8, 16, 18)


def make_complacency(free_until=COMPLACENCY_FREE_UNTIL, diag_hold=False, **kw):
    parent = make_scourge(**kw)
    refill_min = kw.get('refill_min', SCOURGE_REFILL_MIN)
    threat_min = kw.get('threat_min', SCOURGE_THREAT_MIN)

    def complacency(view, mem):
        act, n, t = parent(view, mem)
        c = view.cells
        if any(c[VIEW_DIR[d]] == CELL_ENEMY for d in range(4)):
            return act, n, t                       # bite
        e = view.energy
        empty = [d for d in SPRINT_SPLIT_PRIO if c[VIEW_DIR[d]] == CELL_EMPTY]
        if not empty or e < SPRINT_SPLIT_MIN:
            return act, n, t                       # boxed / rest e < 5: Scourge's code
        freed = [d for d in empty if any(c[i] == CELL_ENEMY for i in SCOURGE_FREED_BY[d])]
        if e >= (min(refill_min, threat_min) if freed else threat_min):
            return act, n, t                       # gate 1: refill / split (11)
        split = ACT_SPLIT + (freed or empty)[0]
        if diag_hold:                              # 15 + test ecx, DIAG / jnz threat
            if not any(c[i] == CELL_ENEMY for i in _DIAG):
                return split, 18, 18               # ret
            if view.tick >= SPRINT_LATE_TICK:
                return split, 19, 17               # threat: cmp tick, jae EXIT (taken)
            return ACT_REST, 21, 20                # fall into rest: mov, ret
        if free_until >= SPRINT_LATE_TICK:
            return split, 16, 16                   # cmp esi, 5 / jb rest not taken, ret
        if view.tick < free_until:
            return split, 17, 16                   # cmp tick, T / jb EXIT (taken)
        return act, n + 2, t + 2                   # cmp tick, T / jb (not taken) + Scourge's 5x5 path
    return complacency


complacency = make_complacency()
# ---- Schism (cells/schism.asm, generated by cells/gen_schism.py; designs.md 11.1; policy a+f6x in sim/growth.py) --
# Complacency plus one rule on the boxed path: no enemy in the 5x5, no empty neighbour, e >= 6: feed the first friend
# of UP, RIGHT, DOWN, LEFT with an empty neighbour.  Otherwise Complacency's boxed path.  Counts follow the asm.
SCHISM_FEED_MIN = 6
_SCHISM_RING = {0: (6, 8), 1: (8, 14, 18), 2: (16, 18), 3: (6, 10, 16)}     # squares of the 16-byte load
_SCHISM_FAR = {0: 2, 2: 22}                                                 # read on their own


def make_schism(**kw):
    parent = make_complacency(**kw)
    feed_d = kw.get('feed_d', SCOURGE_FEED_D)

    def schism(view, mem):
        act, n0, t0 = parent(view, mem)
        c, e = view.cells, view.energy
        if any(c[VIEW_DIR[d]] in (CELL_ENEMY, CELL_EMPTY) for d in range(4)) or e < SCHISM_FEED_MIN:
            return act, n0, t0                     # not boxed, or e < 6 (cmp esi, 6 / jb rest): Complacency's
        if any(c[i] == CELL_ENEMY for i in range(25)):
            n, taken = 23, 2                       # jz boxed, jnz fallback taken
        else:
            n, taken = 26, 1                       # 5x5 check not taken, then the empty mask (3)
            for d in _FEED_ORDER:
                n += 2                             # cmp friend / jne
                if c[VIEW_DIR[d]] != CELL_FRIEND:
                    taken += 1
                    continue
                n += 2                             # test / jnz
                hit = any(c[i] == CELL_EMPTY for i in _SCHISM_RING[d])
                if not hit and d in _SCHISM_FAR:
                    n += 2                         # cmp far / je
                    hit = c[_SCHISM_FAR[d]] == CELL_EMPTY
                if hit:
                    return ACT_FEED + d, n + 2, n + 2 - (taken + 1)     # feed_x: mov al, ret
        n += 2                                     # fallback: cmp esi, 16 / jb
        if e < feed_d:
            return ACT_REST, n + 2, n + 2 - (taken + 1)                 # jb rest taken, mov, ret
        n += n0 - 15                               # Complacency's block after its own 15 instructions
        return act, n, n - (taken + n0 - t0 - 1)   # its taken jumps, less its jz boxed
    return schism


schism = make_schism()
# ---- Pestilence (cells/pestilence.asm, generated by cells/gen_pestilence.py; designs.md 11.2, change 1 only) -------
# Schism plus move refills: on gate 1 with a freed empty neighbour (refill) and e >= 20, MOVE there instead of split.
# Before gate 1 loads its action: cmp mv_tbl / jae move.  The move takes 13 (mov act, sub, ret); every other path
# after the bite costs 2 more than Schism's (cmp, jae not taken).
PESTILENCE_MOVE_MIN = 20


def make_pestilence(move_min=PESTILENCE_MOVE_MIN, **kw):
    parent = make_schism(**kw)
    refill_min = kw.get('refill_min', SCOURGE_REFILL_MIN)
    threat_min = kw.get('threat_min', SCOURGE_THREAT_MIN)

    def pestilence(view, mem):
        act, n, t = parent(view, mem)
        c, e = view.cells, view.energy
        if any(c[VIEW_DIR[d]] == CELL_ENEMY for d in range(4)):
            return act, n, t                       # bite
        empty = [d for d in SPRINT_SPLIT_PRIO if c[VIEW_DIR[d]] == CELL_EMPTY]
