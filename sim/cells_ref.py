# ---- Bane v2 (cells/bane2.asm, generated by cells/gen_bane2.py; designs.md 11.3, 2026-11-10) -----------------------
# Bane plus a dispersal opening on the middle path (an empty neighbour, below gate 1's energy).  Bite, gate 1 and the
# boxed paths are Bane's.  Memory: [0] bearing, [1] steps left, [4..7] x | y << 16 of the square this cell last
# emitted a child from.  A child copies the memory, so a cell with steps left whose position differs from [4..7] is a
# walker: it MOVEs along the bearing until the next square is not empty or the steps run out, then settles.  A settled
# cell with energy >= 5 and no enemy in the 5x5 splits: its first child from a square goes forward (its own bearing)
# and walks k_long squares; later children go to the next empty square clockwise from the last one and walk k_short
# (k_long before tick t_early).  With an enemy on a diagonal square a walker stops and Bane's prey hold applies
# (v2.2; v2.0 and v2.1 held with an enemy anywhere in the 5x5, which froze the opening near enemy walkers).
BANE2_K_LONG = 8
BANE2_K_SHORT = 2
BANE2_NEAR = (6, 8, 16, 18)        # the diagonal squares (an adjacent enemy is bitten before this)
BANE2_LOCK_OFF = (15, 21, 25, 19)   # view index + 8 of the neighbour UP, RIGHT, DOWN, LEFT
BANE2_T_EARLY = 0             # 0 = off: only a cell's first child from a square walks k_long


def make_bane2(k_long=BANE2_K_LONG, k_short=BANE2_K_SHORT, t_early=BANE2_T_EARLY, rest_tail=None,
               hold='on', hold_min=SPRINT_SPLIT_MIN, **kw):
    """rest_tail (Bane v2.3, make_bane4): None = v2.2's `mov al, ACT_REST / ret` on the three rests that have an
    empty neighbour; else rest_tail(view, mem) -> (instructions, taken jumps) of the tail, which may write mem.
    hold (sim probe, hold-off study 2026-11-13): 'on' = v2.2's prey hold (default).  With an enemy on a diagonal and
    e >= hold_min: 'off' skips the hold (the walker / dispersal logic runs), 'split' splits at once into the freed
    or first empty square.  Below hold_min the v2.2 hold applies, 2 instructions longer under 'split' (asm test)."""
    parent = make_bane(**kw)
    refill_min = kw.get('refill_min', SCOURGE_REFILL_MIN)
    threat_min = kw.get('threat_min', SCOURGE_THREAT_MIN)

    def bane2(view, mem):
        # stored bite (v2.1): movzx lock, cmp view byte, mov al, je EXIT (4).  mem[2] = view index + 8 of the
        # square bitten last time (0 = none: reads an unused zero byte of the view), mem[3] = that action.
        c = view.cells
        if 0 <= mem[2] - 8 < 25 and c[mem[2] - 8] == CELL_ENEMY:
            return mem[3], 4, 3
        act, n, t = core(view, mem)
        if any(c[VIEW_DIR[d]] == CELL_ENEMY for d in range(4)):
            mem[3], mem[2] = act, BANE2_LOCK_OFF[act & 3]      # mov / test / jnz setlock, then 6
            return act, 16, 15
        return act, n + 5, t + 5                   # 4 lock instructions, and mov + test for the old `or`

    def core(view, mem):
        act, n0, t0 = parent(view, mem)
        c, e = view.cells, view.energy
        if any(c[VIEW_DIR[d]] == CELL_ENEMY for d in range(4)):
            return act, n0, t0                     # bite
        empty = [d for d in SPRINT_SPLIT_PRIO if c[VIEW_DIR[d]] == CELL_EMPTY]
        if not empty:
            return act, n0, t0                     # boxed: Bane's block
        freed = [d for d in empty if any(c[i] == CELL_ENEMY for i in SCOURGE_FREED_BY[d])]
        if e >= (min(refill_min, threat_min) if freed else threat_min):
            return act, n0, t0                     # gate 1: refill / split (11)
        split = ACT_SPLIT + (freed or empty)[0]
        n, t = 21, 0                               # 13, then movdqu x2, pcmpeqb x2, por, pmovmskb, test, jnz threat
        near = any(c[i] == CELL_ENEMY for i in BANE2_NEAR)
        if near and hold == 'split' and e >= hold_min:
            # asm (gen_misfortune2): threat: cmp esi, hold_min / jae (taken) / cmp tick, late / jb EXIT (taken) = +4;
            # late: the jb falls through to mov steps, 0 / ret (+6, steps cleared as in the v2.2 late split)
            if view.tick < SPRINT_LATE_TICK:
                return split, n + 4, n + 2
            mem[1] = 0
            return split, n + 6, n + 5
        if near and hold == 'off' and hold_min <= SPRINT_SPLIT_MIN:
            # asm (gen_misfortune2, hold = 'off' from 5): threat: cmp esi, 5 / jae resume (+2); resume = the dispersal logic
            # at `mov ecx, [VIEW_X]` (a walker is NOT stopped).  e < 5: mov steps, 0 / mov al, ACT_REST / ret (the dead
            # cmp / jb / late-split tests are not in the asm)
            n += 2
            if e >= hold_min:
                near = False
                t += 2                             # jnz threat, jae resume (both taken)
            else:
                mem[1] = 0
                return ACT_REST, n + 3, n + 3 - (t + 1)
        if near and hold == 'off' and e >= hold_min:
            near = False                           # probe (hold_min > 5, no asm): no hold, the dispersal logic runs
        if near and hold == 'split':
            n += 2                                 # asm: the cmp esi, hold_min / jae (not taken) in front of every hold path
        if near:                                   # v2.2: the hold needs an enemy in the 3x3
            mem[1] = 0                             # threat (taken): mov steps, cmp esi, jb rest
            n, t = n + 3, t + 1
            if e < SPRINT_SPLIT_MIN:
                if rest_tail:                      # jb rtail_m taken, then the tail
                    tn, tt = rest_tail(view, mem)
                    return ACT_REST, n + tn, n + tn - (t + 1 + tt)
                return ACT_REST, n + 2, n + 2 - (t + 1)        # jb taken, mov al, ret
            n += 2                                 # cmp tick, jae EXIT
            if view.tick >= SPRINT_LATE_TICK:
                return split, n, n - (t + 1)
            if rest_tail:                          # the prey hold falls into the tail
                tn, tt = rest_tail(view, mem)
                return ACT_REST, n + tn, n + tn - (t + tt)
            return ACT_REST, n + 2, n + 2 - t      # the prey hold: mov al, ret
        pos = (view.x & 0xFFFF) | (view.y & 0xFFFF) << 16
        here = int.from_bytes(mem[4:8], 'little') == pos
        n += 3                                     # mov ecx, cmp steps, je settled
        if mem[1] == 0:
            t += 1
        else:
            n += 2                                 # cmp pos, je settled
            if here:
                t += 1
            else:                                  # walker: movzx, and, movzx, cmp, jne walk_end
                bear = mem[0] & 3
                n += 5
                if c[VIEW_DIR[bear]] == CELL_EMPTY:
                    mem[1] = (mem[1] - 1) & 0xFF
                    return ACT_MOVE + bear, n + 3, n + 3 - t   # dec, lea, ret
                mem[1] = 0                         # walk_end (taken): mov steps
                n, t = n + 1, t + 1
        n += 2                                     # settled: cmp esi, 5 / jb rest
        if e < SPRINT_SPLIT_MIN:
            if rest_tail:                          # jb rtail_s taken; movdqu, pcmpeqb, pmovmskb, jmp rtail_m; tail
                tn, tt = rest_tail(view, mem)
                return ACT_REST, n + 4 + tn, n + 4 + tn - (t + 2 + tt)
            return ACT_REST, n + 2, n + 2 - (t + 1)
        bear = mem[0] & 3
        n += 4                                     # movzx, and, cmp pos, je rotate
        far = found = False
        if here:
            t += 1
        else:                                      # first child from this square: forward
            n += 3                                 # movzx, cmp, je emit_long
            if c[VIEW_DIR[bear]] == CELL_EMPTY:
                t += 1
                far = found = True
        if not found:
            for _ in range(3):                     # rotate: inc, and, movzx, cmp, je emit
                bear = (bear + 1) & 3
                n += 5
                if c[VIEW_DIR[bear]] == CELL_EMPTY:
                    t += 1
                    found = True
                    break
            if not found:                          # the fourth square is the empty one: inc, and
                bear = (bear + 1) & 3
                n += 2
            n += 2                                 # emit: cmp tick, jb emit_long
            if view.tick < t_early:
                far = True
                t += 1
            else:
                n, t = n + 2, t + 1                # mov steps, jmp emit_store
        if far:
            n += 1                                 # emit_long: mov steps
        mem[0], mem[1] = bear, (k_long if far else k_short)
        mem[4:8] = pos.to_bytes(4, 'little')
        return ACT_SPLIT + bear, n + 4, n + 4 - t  # mov bearing, mov pos, lea, ret
    bane2.core = core                              # Bane v2.2 without the stored bite (Conviction builds on it)
    return bane2


bane2 = make_bane2()
