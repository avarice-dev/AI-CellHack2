# ---- Bane v2.3 (cells/bane4.asm, generated by cells/gen_bane4.py; briefs/v23-brief-2026-11-13.md) ----------------
# Bane v2.3a plus part A, a stored bite written in advance.  The three rests that have an empty neighbour (threat
# e < 5, the prey hold, settled e < 5, which includes a blocked walker) run a tail before `mov al, ACT_REST / ret`;
# the boxed and feed-fallback rests are unchanged.  The tail stores a bite by one precedence:
#   1. a refill pattern (gate 1's thr_tbl = 12): gate 1's first choice (first refill square in DOWN, RIGHT, UP, LEFT);
#   2. else view idx 22 holds an enemy and DOWN is empty: DOWN;
#   3. else view idx 2 holds an enemy and UP is empty: UP;
#   4. else the stored bite is left unchanged.
# The stored bite is [2] = ACT_EAT + dir, [3] = view index + 8 of that neighbour (Bane v2.3a's layout).
BANE4_IDX_BELOW, BANE4_IDX_ABOVE = 22, 2


def bane4_store(cells):
    """The rest tail's square by the precedence above, as a direction 0..3, or None."""
    empty = [d for d in SPRINT_SPLIT_PRIO if cells[VIEW_DIR[d]] == CELL_EMPTY]
    freed = [d for d in empty if any(cells[i] == CELL_ENEMY for i in SCOURGE_FREED_BY[d])]
    if freed:
        return freed[0]
    if cells[BANE4_IDX_BELOW] == CELL_ENEMY and cells[VIEW_DIR[DOWN]] == CELL_EMPTY:
        return DOWN
    if cells[BANE4_IDX_ABOVE] == CELL_ENEMY and cells[VIEW_DIR[UP]] == CELL_EMPTY:
        return UP
    return None


def bane4_tail(view, mem):
    """rtail_m: (instructions, taken jumps) of the tail; writes the stored bite."""
    c = view.cells
    d = bane4_store(c)
    empty = [k for k in SPRINT_SPLIT_PRIO if c[VIEW_DIR[k]] == CELL_EMPTY]
    if any(any(c[i] == CELL_ENEMY for i in SCOURGE_FREED_BY[k]) for k in empty):
        mem[2], mem[3] = ACT_EAT + d, BANE2_LOCK_OFF[d]
        return 8, 0                                # cmp thr, jne, movzx, and, mov ax, mov [2] ax, mov al, ret
    n, t = 2, 1                                    # cmp thr, jne .vert (taken)
    if c[BANE4_IDX_BELOW] == CELL_ENEMY:
        n += 2                                     # cmp idx 22, jne
        if c[VIEW_DIR[DOWN]] == CELL_EMPTY:
            mem[2], mem[3] = ACT_EAT + DOWN, BANE2_LOCK_OFF[DOWN]
            return n + 2 + 3, t                    # cmp DOWN, jne; mov word, mov al, ret
        n, t = n + 2, t + 1                        # cmp DOWN, jne .up (taken)
    else:
        n, t = n + 2, t + 1                        # cmp idx 22, jne .up (taken)
    if c[BANE4_IDX_ABOVE] == CELL_ENEMY:
        n += 2                                     # cmp idx 2, jne
        if c[VIEW_DIR[UP]] == CELL_EMPTY:
            mem[2], mem[3] = ACT_EAT + UP, BANE2_LOCK_OFF[UP]
            return n + 2 + 3, t                    # cmp UP, jne; mov word, then .rest: mov al, ret
        n, t = n + 2, t + 1                        # cmp UP, jne .rest (taken)
    else:
        n, t = n + 2, t + 1                        # cmp idx 2, jne .rest (taken)
    return n + 2, t                                # .rest: mov al, ret


def make_bane4(**kw):
    core = make_bane2(rest_tail=bane4_tail, **kw).core

    def bane4(view, mem):
        c = view.cells
        if 0 <= mem[3] - 8 < 25 and c[mem[3] - 8] == CELL_ENEMY:
            return mem[2], 4, 3
        act, n, t = core(view, mem)
        if any(c[VIEW_DIR[d]] == CELL_ENEMY for d in range(4)):
            mem[2], mem[3] = act, BANE2_LOCK_OFF[act & 3]
            return act, 12, 11
        return act, n + 5, t + 5
    bane4.core = core
    return bane4


