# ---- Dogma (cells/dogma.asm, generated by cells/gen_dogma.py; spec reviews/dogma-clean-sheet-review-2026-11-14.md s6 + reviews/final-round-2026-11-13-14.md) ----
# C3b counter bite (mem [8..15] = 1 << k, shr per call), 15-insn arm, Scourge gate 1, diagonal enemy stop, first 8/2
# walker, +2-lane rotate pick, boxed t >= 100 feed with a quiet / front cap.  Written independently of gen_dogma's
# tables.  Returns (action, insn, insn without taken jumps); mem is updated like the asm.
DOGMA_K_CAP = 16
DOGMA_K12 = 1
DOGMA_QUIET_FEED_CAP = 24
DOGMA_FRONT_FEED_CAP = 48
DOGMA_T_FEED_MIN = 100
DOGMA_PLUS2 = (2, 14, 22, 10)        # the squares beyond UP, RIGHT, DOWN, LEFT


def dogma_kmask(te, k_cap=DOGMA_K_CAP, k12=DOGMA_K12):
    if te == 0:
        return 0
    if te <= 2:
        return (1 << k12) if k12 else 0
    return 1 << min(k_cap, te // 2 + 2)


def dogma_pick(c, start):
    ortho = [c[VIEW_DIR[d]] == CELL_EMPTY for d in range(4)]
    plus2 = [c[DOGMA_PLUS2[d]] == CELL_EMPTY for d in range(4)]
    order = [(start + k) & 3 for k in range(4)]
    for d in order:
        if ortho[d] and plus2[d]:
            return d
    for d in order:
        if ortho[d]:
            return d
    return start


def make_dogma(k_cap=DOGMA_K_CAP, k12=DOGMA_K12, quiet_cap=DOGMA_QUIET_FEED_CAP):
    def dogma(view, mem):
        c, e = view.cells, view.energy
        mask = int.from_bytes(mem[8:16], 'little') >> 1
        mem[8:16] = mask.to_bytes(8, 'little')
        if mask:
            return mem[16], 3, 2                         # shr, mov, jnz (taken)
        enemies = [d for d in range(4) if c[VIEW_DIR[d]] == CELL_ENEMY]
        if enemies:
            d = _sprint_bite(enemies)
            mem[16] = ACT_EAT + d
            mem[8:16] = dogma_kmask(view.energies[VIEW_DIR[d]], k_cap, k12).to_bytes(8, 'little')
            return ACT_EAT + d, 15, 13                   # jnz arm, jmp [arm_tbl] taken
        empty = [d for d in SPRINT_SPLIT_PRIO if c[VIEW_DIR[d]] == CELL_EMPTY]
        freed = [d for d in empty if any(c[i] == CELL_ENEMY for i in SCOURGE_FREED_BY[d])]
        act = ACT_SPLIT + (freed or empty)[0] if empty else 0
        if empty and e >= (SCOURGE_REFILL_MIN if freed else SCOURGE_THREAT_MIN):
            return act, 15, 14                           # gate 1: jae taken
        if not empty:                                    # test, jz boxed (taken): 17
            n, t = 17, 1
            if view.tick < DOGMA_T_FEED_MIN:
                return ACT_REST, n + 4, n + 4 - (t + 1)
            if e < 16:
                return ACT_REST, n + 6, n + 6 - (t + 1)
            n += 4 + 8                                   # tick cmp / jb, esi cmp / jb, 8 for the 5x5 scan
            front = any(c[i] == CELL_ENEMY for i in range(25) if i != VIEW_CENTER)
            if front:
                n, t = n + 4, t + 1                      # jnz taken; lea, mov, cmp, cmovae
                limit = DOGMA_FRONT_FEED_CAP if e >= 49 else e - 4
            else:
                n, t = n + 5, t + 1                      # lea, mov, cmp, cmovae, jmp (taken)
                limit = quiet_cap if e >= quiet_cap + 4 else e - 4
            n += 2                                       # mov r8d, mov eax
            best, act = 255, ACT_REST
            en = view.energies
            for d in _FEED_ORDER:
                i = VIEW_DIR[d]
                if c[i] != CELL_FRIEND:
                    n, t = n + 2, t + 1
                elif en[i] >= best:
                    n, t = n + 5, t + 1
                else:
                    n += 7
                    best, act = en[i], ACT_FEED + d
            n += 2                                       # cmp r8d, r9d / ja
            if best > limit:
                return ACT_REST, n + 2, n + 2 - (t + 1)
            return act, n + 1, n + 1 - t
        n, t = 17, 0
        near = any(c[i] == CELL_ENEMY for i in BANE2_NEAR)
        n += 8
        if near:                                         # threat: mov byte, cmp, jae
            mem[1] = 0
            if e >= SPRINT_SPLIT_MIN:
                return act, 28, 26                       # jnz threat, jae taken
            return ACT_REST, 30, 29
        pos = ((view.x & 0xFFFF) | (view.y & 0xFFFF) << 16) + 1 & 0xFFFFFFFF
        last = int.from_bytes(mem[4:8], 'little')
        n += 4                                           # mov ecx, inc, cmp steps, je
        if mem[1] == 0:
            n, t = n, t + 1
        else:
            n += 2                                       # cmp pos, je
            if pos == last:
                t += 1
            else:
                n += 5                                   # movzx, and, movzx, cmp, jne
                b = mem[0] & 3
                if c[VIEW_DIR[b]] != CELL_EMPTY:
                    n, t = n + 1, t + 1                  # jne taken; walk_end: mov byte
                    mem[1] = 0
                else:
                    mem[1] -= 1
                    return ACT_MOVE + b, n + 3, n + 3    # dec, lea, ret = 39 (no taken jump)
        n += 2                                           # settled: cmp esi, 5 / jb
        if e < SPRINT_SPLIT_MIN:
            return ACT_REST, n + 2, n + 2 - (t + 1)
        b = mem[0] & 3
        n += 4                                           # movzx, and, cmp, je
        rot = pos == last
        if rot:
            t += 1
        else:
            n += 3                                       # movzx, cmp, jne
            if c[VIEW_DIR[b]] != CELL_EMPTY:
                rot = True
                t += 1
        if not rot:
            mem[1], mem[0] = K_LONG_REF, b
            mem[4:8] = pos.to_bytes(4, 'little')
            return ACT_SPLIT + b, n + 5, n + 5 - t
        d = dogma_pick(c, (b + 1) & 3)
        mem[1], mem[0] = K_SHORT_REF, d
        mem[4:8] = pos.to_bytes(4, 'little')
        return ACT_SPLIT + d, n + 19, n + 19 - t
    return dogma


