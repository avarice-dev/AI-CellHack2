# ---- Misfortune (planned, no asm yet; briefs/misfortune-spec-2026-11-13.md) --------------------------------------
# Whoever bites it is bitten first on the next tick: a 2-instruction chain bite read from a slot table indexed by the
# cell's own energy.  Memory: [0] bearing, [1] steps, [4..7] position (Bane v2.2), [8] = e0 of the last arming,
# slot(e) = byte 13 + e (byte 63 = slot 50); bytes 2-3 and 9-12 unused.  Entry assumptions: rax = 0, xmm0 = 0,
# esi = own energy.  The listing behind every count is in briefs/misfortune-build-review-2026-11-13.md.
#   entry   or al, [abs MEM + 13 + rsi] / jnz EXIT_ADDR                     armed bite: 2 (1 without taken jumps)
#   prefix  movzx ecx, byte [abs MEM + 8] / movdqu [abs MEM + 9 + rcx], xmm0 (zeroes the last armed window)
#   then Bane v2.2's paths (make_bane2().core, whose scan ends `or al, [bite_tbl + rcx]` / `jnz`): core + 4, which is
#   Bane v2.3a's count - 1 on every slow path (v2.3a loads action and square with mov ax / test al instead of `or`).
# Arming (an enemy beside the cell, scan bite toward d at energy e0): byte 8 = e0, one 16-byte pattern store to
# bytes 9 + e0 .. 24 + e0 (slots e0 - 4 .. e0 + 11): EAT + d on the slots of e0's parity up to e0 + 10, zero on the
# rest; exact=1 keeps only the slots up to e0 + 2k (k = (te + 1) // 2 - 1 more bites kill the target at the scan,
# te its energy; k = 0 arms nothing); then slot 50: cap A stores (slot 48 | slot 49) & (e0 >= 40 ? 0xFF : 0), i.e. it
# arms slot 50 when the run reaches the cap, cap B and N store 0.  First bite: 16 (exact=0) / 19 (exact=1), cap A + 3.
# Boxed cap rules, ahead of Bane's boxed rules (edge friend = a friend on one of my four edges; its edges are the three
# other squares around it, all inside the 5x5 view):
#   A: EAT the first edge friend (U, R, D, L) at 47+ with an empty edge and no enemy on its edges (release);
#   B: EAT the first edge friend at 48+ with an enemy on its edges (hold it at 48), else FEED the first edge friend
#      at 47+ with an empty edge and no enemy on its edges (lift it out at 50); the feed needs my energy >= 6;
#   N: neither.  A cap-rule action is padded to MISFORTUNE_PULL_N instructions, more than any path the pulled cell
#   can be on, so a pull never runs before (and so never stuns) the friend it pulls.  A missed cap rule adds its tests
#   (6 per edge for A and B's eat pass, 8 per edge for B's feed pass) to Bane's boxed count.
MISFORTUNE_SLOT0 = 13
MISFORTUNE_E0 = 8
MISFORTUNE_LOW, MISFORTUNE_HIGH = 4, 10      # armed slots lie in e0 - 4 .. e0 + 10
MISFORTUNE_CAP_A_MIN = 40                    # slot 50 is inside e0 - 4 .. e0 + 10 only from e0 = 40
MISFORTUNE_RELEASE_MIN = 47
MISFORTUNE_HOLD_MIN = 48
MISFORTUNE_FEED_MIN = SCHISM_FEED_MIN
MISFORTUNE_PREFIX_N = 4                      # entry 2 + prefix 2
MISFORTUNE_BITE_N = {(0, 'A'): 19, (0, 'B'): 16, (0, 'N'): 16, (1, 'A'): 22, (1, 'B'): 19, (1, 'N'): 19}
MISFORTUNE_PULL_N = 80
MISFORTUNE_FEED_PAD = 6                      # asm: times 6 xor r11d, r11d on feed_up/right/down/left and the fallback ret
MISFORTUNE_RING = _RING


def misfortune_prefix(mem):
    """The slow-path prefix: zero bytes 9 + [8] .. 24 + [8] (bytes past 63 are scratch)."""
    b = mem[MISFORTUNE_E0]
    hi = min(64, 25 + b)
    if hi > 9 + b:
        mem[9 + b:hi] = bytes(hi - (9 + b))


def misfortune_pattern(e0, d, te, exact, cap):
    """{memory byte: value} written by the arming path (the 16-byte store, then slot 50).  Bytes > 63 dropped."""
    act = ACT_EAT + d
    top = e0 + MISFORTUNE_HIGH
    if exact:
        k = (te + 1) // 2 - 1
        top = min(top, e0 + 2 * k) if k > 0 else e0 - MISFORTUNE_LOW - 1
    out = {}
    for s in range(e0 - MISFORTUNE_LOW, e0 + MISFORTUNE_HIGH + 2):     # 16 slots: e0 - 4 .. e0 + 11
        out[MISFORTUNE_SLOT0 + s] = act if ((s - e0) % 2 == 0 and s <= top) else 0
    reach = out.get(MISFORTUNE_SLOT0 + 48, 0) | out.get(MISFORTUNE_SLOT0 + 49, 0)
    out[MISFORTUNE_SLOT0 + 50] = reach if (cap == 'A' and e0 >= MISFORTUNE_CAP_A_MIN) else 0
    return {b: v for b, v in out.items() if b < 64}


MISFORTUNE2_MIN = 12                           # checked refill: own energy >= 12 (the parent stays strong)
MISFORTUNE2_BYTE = 2                           # byte 2 = SPLIT + d of the last bite (0 = none); free in Misfortune
MISFORTUNE2_FIRE_N = 13                        # prefix 4 + or, jz, movzx, cmp, jnz, cmp, jb, mov, ret
# Asm count of the checked refill (assumed layout: byte 2 = action SPLIT + d, byte 3 = view index of that square,
# written as one word by `mov ax, [tbl + rcx*2]` / `mov [mem+2], ax` = +2 on the biting path):
#   after the prefix (entry 2 + prefix 2): or al, [mem+2] / jz normal (none: +2, jz taken) / movzx edx, [mem+3] /
#   cmp byte [view + rdx], 0 / jnz clear (square taken) / cmp esi, 12 / jb clear / mov byte [mem+2], 0 / ret (fires: 13
#   in all, no taken jump).  clear: mov byte [mem+2], 0 / xor eax, eax, then the normal path (square taken: +7;
#   e < 12: +9).  The check reads the snapshot, so a SPLIT never goes into an occupied square.


def misfortune_cap_rule(view, cap):
    """Boxed cap rules: (action or None, instructions of the tests run, taken jumps among them)."""
    if cap == 'N':
        return None, 0, 0
    c, en, e = view.cells, view.energies, view.energy
    tested = taken = 0
    passes = (('release', 6),) if cap == 'A' else (('hold', 6), ('lift', 8))
    for kind, cost in passes:
        for d in _FEED_ORDER:
            tested += cost
            i = VIEW_DIR[d]
            if c[i] == CELL_FRIEND:
                ring = [c[q] for q in MISFORTUNE_RING[d]]
                enemy, empty = CELL_ENEMY in ring, CELL_EMPTY in ring
                if kind == 'release' and en[i] >= MISFORTUNE_RELEASE_MIN and empty and not enemy:
                    return ACT_EAT + d, tested, taken
                if kind == 'hold' and en[i] >= MISFORTUNE_HOLD_MIN and enemy:
                    return ACT_EAT + d, tested, taken
                if kind == 'lift' and e >= MISFORTUNE_FEED_MIN and en[i] >= MISFORTUNE_RELEASE_MIN and empty \
                        and not enemy:
                    return ACT_FEED + d, tested, taken
            taken += 1
    return None, tested, taken


# Armed-children block `child` of the asm (gen_misfortune2): instructions from its label to the exit (counts in make_misfortune).
ARMCHILD_N_MOD = 3         # e & 3 != 1: lea, test, jnz EXIT (taken)
ARMCHILD_N_NONE = 10       # e & 3 == 1, no enemy beside the child: + 7 (window scan, bite_tbl, test, jz EXIT taken)
ARMCHILD_N_ARM = 16        # an enemy beside the child: arm (shr, mov [8], shl, movdqu, movdqu store, ret)
_CHILD_OFF = (-5, 1, 5, -1)  # view index step to the neighbour UP, RIGHT, DOWN, LEFT of a square


def make_misfortune(cap='B', exact=1, refill=None, fire_min=None, armed_children=False, **kw):
    refill_min = kw.get('refill_min', SCOURGE_REFILL_MIN)
    threat_min = kw.get('threat_min', SCOURGE_THREAT_MIN)
    hold, hold_min = kw.get('hold', 'on'), kw.get('hold_min', SPRINT_SPLIT_MIN)
    if cap not in ('A', 'B', 'N'):
        raise ValueError("cap must be 'A', 'B' or 'N'")
    if exact not in (0, 1):
        raise ValueError('exact must be 0 or 1')
    if refill not in (None, 'checked'):
        raise ValueError("refill must be None or 'checked'")
    core = make_bane2(**kw).core
    bite_n = MISFORTUNE_BITE_N[(exact, cap)]

    def misfortune(view, mem):
        e = view.energy
        if armed_children:
            misfortune.last = None                 # (near enemy beside the child, armed) of a split call
        a = mem[MISFORTUNE_SLOT0 + e] if 0 <= e <= 50 else 0
        if a:
            return a, 2, 1                         # or al, [slot] / jnz EXIT (taken)
        misfortune_prefix(mem)
        c = view.cells
        ex_n = ex_t = 0                            # checked-refill extras on the paths that do not fire
        ex_b = 0                                   # ... on the biting path (the clear is skipped there: the arm rewrites byte 2)
        if refill:
            st = mem[MISFORTUNE2_BYTE]
            if not st:
                ex_n = ex_b = 2                    # or al, [mem+2] / jz normal (taken)
                ex_t = 1
            else:
                mem[MISFORTUNE2_BYTE] = 0            # fired or cleared; a child copies the cleared byte
                if c[VIEW_DIR[st & 3]] == CELL_EMPTY and e >= (MISFORTUNE2_MIN if fire_min is None else fire_min):
                    return st, MISFORTUNE2_FIRE_N, MISFORTUNE2_FIRE_N
                taken = c[VIEW_DIR[st & 3]] != CELL_EMPTY
                ex_b, ex_t = (7, 1) if taken else (9, 1)     # bite: or, jz, movzx, cmp, jnz [cmp, jb], xor, dup scan
                ex_n = ex_b + 1                              # no bite: + mov [2], 0 and jmp slow after the dup scan
        act, n, t = core(view, mem)
        if any(c[VIEW_DIR[d]] == CELL_ENEMY for d in range(4)):
            d = act & 3
            mem[MISFORTUNE_E0] = e
            te = view.energies[VIEW_DIR[d]] & 63
            pat = misfortune_pattern(e, d, te, exact, cap)
            for k, v in pat.items():
                mem[k] = v
            if refill:
                mem[MISFORTUNE2_BYTE] = ACT_SPLIT + d
                mem[MISFORTUNE2_BYTE + 1] = 32 + VIEW_DIR[d]   # view offset of the square (VIEW_CELLS = 32)
                add = bite_n + ex_b + (1 if not st else 0)   # arm: the table dword + mov [2], dx + shr = +1
                return act, add, add - 1 - ex_t
            return act, bite_n, bite_n - 1         # jnz arm taken
        n, t = n + MISFORTUNE_PREFIX_N + ex_n, t + MISFORTUNE_PREFIX_N + ex_n - ex_t
        if armed_children and act & 0xF0 == ACT_SPLIT:
            # armed child: the engine gives the child e // 2 and the parent the rest, and copies the memory after this call.
            # e = 1 mod 4: child c = (e - 1) // 2 is even, the parent after the split (c + 1) and the parent after a FAILED
            # split (target taken at execution: it keeps e = 2c + 1) are both odd.  The child's slots sit on even energies
            # (c - 4 .. c + 10, step 2), so the parent never reads one at its next call, whose prefix zeroes the window at
            # byte 8 = c.  The child's own copy stays armed.  (e = 3 mod 4 would put the slots on odd energies.)
            # asm (gen_misfortune2, block `child`): gate 1 reaches it by `jae child` (already in n); the emit paths fall into it
            # in place of their `ret` (-1).  lea edx, [rsi + 3] / test dl, 3 / jnz EXIT (e & 3 != 1): 3.  Else
            # movzx edx, [cbase_tbl + al] / movdqu xmm0 (the child's 4 neighbours, window s - 5) / pcmpeqb / pmovmskb /
            # movzx edx, [bite_tbl + rcx] / test / jz EXIT (no enemy beside the child): 10.  Else shr esi, 1 / mov [8], sil /
            # shl edx, 4 / movdqu xmm1, [cpat_tbl] / movdqu [esi + 9 + MEM], xmm1 / ret: 16.  Slot 50 (byte 63) is not
            # written (cap B keeps it 0, and the child's slots end at byte 49).
            s_ = VIEW_DIR[act & 3]
            near = {d for d in range(4) if 0 <= s_ + _CHILD_OFF[d] < 25 and c[s_ + _CHILD_OFF[d]] == CELL_ENEMY}
            empty = [d for d in SPRINT_SPLIT_PRIO if c[VIEW_DIR[d]] == CELL_EMPTY]
            freed = [d for d in empty if any(c[i] == CELL_ENEMY for i in SCOURGE_FREED_BY[d])]
            gate1 = e >= (min(refill_min, threat_min) if freed else threat_min)
            armed, taken_c = False, 1
            allodd = armed_children == 'allodd'           # variant (no asm yet): arm on every odd e, k by energy
            if (e & 1 == 0) if allodd else (e & 3 != 1):
                cn = ARMCHILD_N_MOD - allodd
            elif not near:
                cn = ARMCHILD_N_NONE - allodd
            else:
                cn = ARMCHILD_N_ARM + allodd
                child = e // 2
                if allodd and e & 3 == 3 and e < 23:
                    kk = (e - 3) // 4                      # c + 2k <= e - 2: a failed split (parent keeps e) stays above the slots
                    pat = misfortune_pattern(child, _sprint_bite(near), 2 * kk + 1, 1, cap)
                else:
                    pat = misfortune_pattern(child, _sprint_bite(near), 0, 0, cap)
                for k_, v_ in pat.items():
                    if k_ != MISFORTUNE_SLOT0 + 50:
                        mem[k_] = v_
                mem[MISFORTUNE_E0] = child
                armed, taken_c = True, 0
            misfortune.last = (bool(near), armed)
            base_n, base_t = (n, t) if gate1 else (n - 1, t)
            n, t = base_n + cn, base_t + cn - taken_c
        if any(c[VIEW_DIR[d]] == CELL_EMPTY for d in range(4)):
            return act, n, t
        rule, tested, taken = misfortune_cap_rule(view, cap)
        if rule is not None:
            pull = MISFORTUNE_PULL_N + (ex_n - 2 if refill else 0)    # asm pad is fixed: 80 when ex_n = 2
            return rule, pull, pull - taken - 1
        if armed_children and act & 0xF0 == ACT_FEED:   # Schism's boxed feed (feed_X / fallback): padded, runs after every armed-child split
            return act, n + tested + MISFORTUNE_FEED_PAD, t + tested - taken + MISFORTUNE_FEED_PAD
        return act, n + tested, t + tested - taken
    misfortune.core = core
    misfortune.cap, misfortune.exact = cap, exact
    misfortune.refill = refill
    return misfortune


