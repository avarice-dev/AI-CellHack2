# ---- Depravity (cells/depravity.asm, generated by cells/gen_depravity.py; spec reviews/final-round-2026-11-13-14.md section 4) ----------
# Misfortune v2's arm_tbl core with cap B (boxed paths = make_misfortune's): armed bite 2, arm 17, gate 1 15, hold_split from e >= 8 (29), walker as
# Bane v2.2 (+4 prefix).  k = 0 (te <= 2) arms slots e0 - 4, e0 - 2, e0.  The settled split is "first 8/2 dir-open"
# (tools/search/opening_search.py): among the empty neighbours the one with the fewest friends on its side plus a
# non-empty square beyond it, ties in rotation order (start = bearing for a first child, bearing + 1 otherwise);
# steps = 8 for a first child that goes forward, else 2.  Boxed: Misfortune v2's cap B rule from tick 0 (no T_FEED gate).
# Counts follow the asm instruction by instruction.
DEPRAVITY_HOLD_MIN = 8
DEPRAVITY_SIDE = {UP: (0, 1, 2, 3, 4, 6, 8), RIGHT: (4, 9, 14, 19, 24, 8, 18), DOWN: (20, 21, 22, 23, 24, 16, 18),
                  LEFT: (0, 5, 10, 15, 20, 6, 16)}
DEPRAVITY_BEYOND = (2, 14, 22, 10)
DEPRAVITY_POP_N = (6, 14, 7, 12)        # instructions computing popcount(F & side mask) per direction (gen_depravity.pop_ops)


def depravity_pattern(e0, d, te):
    """{memory byte: value} of the arm: 16 slots e0 - 4 .. e0 + 11, EAT + d on even offsets up to 2k (k = 0: up to e0), slot 50 = 0."""
    k = max(0, min(5, ((te & 63) + 1) // 2 - 1))
    out = {13 + s: (ACT_EAT + d if ((s - e0) % 2 == 0 and s - e0 <= 2 * k) else 0) for s in range(e0 - 4, e0 + 12)}
    out[63] = 0
    return {b: v for b, v in out.items() if b < 64}


def make_depravity(cap='B'):
    core = make_bane2(hold='split', hold_min=DEPRAVITY_HOLD_MIN).core

    def depravity(view, mem):
        e, c = view.energy, view.cells
        a = mem[MISFORTUNE_SLOT0 + e] if 0 <= e <= 50 else 0
        if a:
            return a, 2, 1
        misfortune_prefix(mem)
        scratch = bytearray(mem)
        act, n, t = core(view, scratch)
        if any(c[VIEW_DIR[d]] == CELL_ENEMY for d in range(4)):
            d = act & 3
            mem[MISFORTUNE_E0] = e & 0xFF
            for b, v in depravity_pattern(e, d, view.energies[VIEW_DIR[d]]).items():
                mem[b] = v
            return act, 17, 16                     # arm_tbl stubs: 9 + mov, jmp + 6
        empty = [d for d in SPRINT_SPLIT_PRIO if c[VIEW_DIR[d]] == CELL_EMPTY]
        if not empty:
            act, n, t = core(view, mem)             # real memory, as make_misfortune does
            n, t = n + MISFORTUNE_PREFIX_N, t + MISFORTUNE_PREFIX_N
            rule, tested, taken = misfortune_cap_rule(view, cap)
            if rule is not None:
                return rule, MISFORTUNE_PULL_N, MISFORTUNE_PULL_N - taken - 1
            return act, n + tested, t + tested - taken
        freed = [d for d in empty if any(c[i] == CELL_ENEMY for i in SCOURGE_FREED_BY[d])]
        gate1 = e >= (min(SCOURGE_REFILL_MIN, SCOURGE_THREAT_MIN) if freed else SCOURGE_THREAT_MIN)
        near = any(c[i] == CELL_ENEMY for i in BANE2_NEAR)
        if gate1 or near or act & 0xF0 != ACT_SPLIT:
            act, n, t = core(view, mem)          # now on the real memory (hold_split late, walker steps)
            return act, n + 4, t + 4
        # settled dir-open: entry count to `settled:` then the asm's instruction counts
        pos = (view.x & 0xFFFF) | (view.y & 0xFFFF) << 16
        here = int.from_bytes(mem[4:8], 'little') == pos
        n = 25 + 1 + 2                             # gate 1 + diagonal scan (not taken), mov ecx, cmp steps / je
        if mem[1] != 0:
            n += 2                                 # cmp pos / je
            if not here:
                n += 5                             # movzx, and, movzx, cmp, jne
                n += 1                             # blocked (a free square would have moved): walk_end mov
                mem[1] = 0
        n += 2                                     # settled: cmp esi, 5 / jb rest
        if e < SPRINT_SPLIT_MIN:
            return ACT_REST, n + 2, n + 2
        F = sum(1 << i for i in range(25) if c[i] == CELL_FRIEND)
        b = mem[0] & 3
        s = b + (1 if here else 0)
        n += 8 + 4 + 2 + (1 if here else 0) + 1    # F, 4 - bearing, cmp / jne [dec], mov r11d
        best, rot0 = 255, False
        for d in range(4):
            if c[VIEW_DIR[d]] != CELL_EMPTY:
                n += 2
                continue
            pop = bin(F & sum(1 << i for i in DEPRAVITY_SIDE[d])).count('1')
            beyond = c[DEPRAVITY_BEYOND[d]] != CELL_EMPTY
            n += 2 + DEPRAVITY_POP_N[d] + (3 if beyond else 2) + 5
            key = (pop + beyond) * 4 + ((d - s) & 3)
            best = min(best, key)
        d = (best & 3) + s & 3
        n += 2                                     # test r11b, 3 / jnz
        if best & 3 or here:
            n += (1 if best & 3 else 3)            # sd_short: mov (rot != 0), or cmp / je / mov
            steps = 2
        else:
            n += 4                                 # cmp / je (not taken), mov, jmp
            steps = 8
        n += 7                                     # and, sub, and, mov, mov, lea, ret
        mem[0], mem[1] = d, steps
        mem[4:8] = pos.to_bytes(4, 'little')
        return ACT_SPLIT + d, n, n - 3
    depravity.core = core
    return depravity


