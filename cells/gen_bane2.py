"""Generate cells/bane2.asm (Bane v2: Bane plus a dispersal opening).  Tables are never written by hand.

    python cells/gen_bane2.py     # writes cells/bane2.asm next to this file

Bane v2 is Bane (cells/gen_bane.py: F5 bite, refill, prey hold, Schism's boxed feeding) with a new middle path
(designs.md 11.3, 2026-11-10): a cell that has an empty neighbour, is below gate 1's energy and sees no enemy in the
5x5 no longer splits in a fixed order.  Its children walk away before they settle, so the colony grows as a spread of
small groups (every cell keeps empty neighbours) and not as one boxed-in blob.

Memory (first use of the cell memory in this family; addressed as [abs CELLMEM_BASE + n], rdx is not used):
  [0] bearing (0..3)   [1] steps left   [4..7] VIEW_X | VIEW_Y << 16 of the square this cell last split from.
A child copies its parent's memory.  A cell with steps left whose own position differs from [4..7] is a walker.
  - Walker: MOVE along the bearing while the next square is empty and steps are left; otherwise settle (steps = 0).
  - Settled, energy >= 5: the first child from a square goes forward (the cell's own bearing) and gets K_LONG steps;
    later children go to the next empty square clockwise from the last one and get K_SHORT steps (K_LONG before tick
    T_EARLY).  The cell writes bearing, steps and its own position, then splits.
  - An enemy on a diagonal square (view 6, 8, 16, 18): steps = 0 (a walker stops) and Bane's prey hold applies.
    (v2.2.  Before, any enemy in the 5x5 did this, and enemy walkers passing two squares away froze the opening.)
The bite, gate 1 and the boxed block are Bane's source lines, unchanged.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_sprint as G  # noqa: E402
import gen_scourge as S  # noqa: E402
import gen_schism as H  # noqa: E402
import gen_bane as B  # noqa: E402

K_LONG = 8              # steps of a cell's first child from a square (forward)
K_SHORT = 2             # steps of its later children
T_EARLY = 0             # before this tick every child gets K_LONG (0 = off)
MEM_BEAR, MEM_STEPS, MEM_POS = 0, 1, 4
MEM_LOCK, MEM_LOCKACT = 2, 3   # stored bite (v2.1): view offset - LOCK_BASE of the bitten square, and the action
LOCK_BASE = 24          # view byte 24 is unused (always 0): lock 0 never matches CELL_ENEMY
DIR_IDX = (7, 13, 17, 11)   # view index of the neighbour UP, RIGHT, DOWN, LEFT
LOCK_OFF = tuple(32 + i - LOCK_BASE for i in DIR_IDX)   # VIEW_CELLS = 32

BITE_FROM = ("\tor\t\tal, [abs bite_tbl + rcx]\t; rax = 0 at entry: al = eat action, ZF = no enemy\n"
             "\tjnz\t\tEXIT_ADDR\t\t\t; bite: leave through the return address\n")
BITE_TO = ("\tmov\t\tal, [abs bite_tbl + rcx]\t; eat action, 0 = no enemy\n"
           "\ttest\t\tal, al\n"
           "\tjnz\t\tsetlock\t\t\t\t; bite, and store it for the next tick\n")
LOCK = ("\tmovzx\t\tecx, byte [abs CELLMEM_BASE + %(lock)d]\t; stored bite: view offset of the square (0 = none)\n"
        "\tcmp\t\tbyte [rdi + rcx + %(lbase)d], CELL_ENEMY\n"
        "\tmov\t\tal, [abs CELLMEM_BASE + %(lockact)d]\n"
        "\tje\t\tEXIT_ADDR\t\t\t; the enemy is still there: bite in 4 instructions\n")
SETLOCK = ("setlock:\n"
           "\tmov\t\t[abs CELLMEM_BASE + %(lockact)d], al\n"
           "\tmovzx\t\tecx, al\n"
           "\tand\t\tecx, 3\n"
           "\tmov\t\tcl, [abs lock_off + rcx]\n"
           "\tmov\t\t[abs CELLMEM_BASE + %(lock)d], cl\n"
           "\tret\n")

HEADER = """\
; Bane v2: Bane with a dispersal opening, for CellHack2.  GENERATED by cells/gen_bane2.py -- do not edit by hand.
; Written with AI help.
;
; Paste this whole file into the site.  It has no org/bits/section/%%include on purpose: the server
; prepends `bits 64 / org CODE_BASE / default rel / <cellhack.inc>` and runs `nasm -f bin`.
; CPU target: plain qemu64 (SSE2 only used; no VEX).  No loops, no stack use.  Relies on: rax = 0 at entry
; (registers are reset before every call).  The cell memory is addressed as [abs CELLMEM_BASE + n].
;
; Memory: [%(bear)d] bearing 0..3, [%(steps)d] steps left, [%(lock)d] and [%(lockact)d] the stored bite, [%(pos)d..%(pos3)d] x | y << 16 of the square this cell last split from.
; A child copies the memory; a cell with steps left that is not on that square is a walker.
;
; Behaviour
;   0. Stored bite: the square I bit last time still holds an enemy: bite it again (4 instructions, no view scan).
;   1. Otherwise an enemy next to me: bite it and store the bite (memory [%(lock)d] square, [%(lockact)d] action): 16.
;   2. Refill: an empty neighbour with an enemy beside or beyond it: split into it when energy >= %(rmin)d.
;      Any other empty neighbour: split when energy >= %(tmin)d (first of DOWN, RIGHT, UP, LEFT).
;   3. An empty neighbour, below those energies, an enemy on a diagonal square: stop walking; rest (the prey hold;
;      from tick %(late)d: split when energy >= %(smin)d).
;   4. An empty neighbour, no enemy on a diagonal square (enemies two squares away do not stop growth):
;      walker: MOVE along the bearing while that square is empty and steps are left; otherwise settle.
;      settled, energy >= %(smin)d: split.  The first child from this square goes forward (my bearing) and walks %(klong)d
;      squares; later children go to the next empty square clockwise from the last one and walk %(kshort)d
;      (%(klong)d before tick %(tearly)d).  Energy < %(smin)d: rest.
;   5. No empty neighbour: Bane's boxed block (feed a friend that has an empty neighbour, or the poorest friend).
;
; Instruction counts per path (every executed instruction, including taken jumps and ret):
;   stored bite 4, first bite 16, refill 16, split e >= %(tmin)d 16, boxed block: Bane's + 5
;   enemy on a diagonal: rest e < %(smin)d 31, late split 31, hold 33
;   walker move 39; walker blocked, e < %(smin)d 41
;   settled, e < %(smin)d: rest 33 (35 for a cell with steps left on its own square)
;   first child forward 43; other children 47 to 66
"""

MIDDLE = """\
	movdqu		xmm1, [rdi + VIEW_CELLS]	; view idx 0..15
	movdqu		xmm2, [rdi + VIEW_CELLS + 9]	; view idx 9..24
	pcmpeqb		xmm1, [kNearLo]			; enemy at view idx 6 or 8
	pcmpeqb		xmm2, [kNearHi]			; enemy at view idx 16 or 18
	por		xmm1, xmm2
	pmovmskb	r8d, xmm1
	test		r8d, r8d
	jnz		threat				; an enemy on a diagonal square (26 so far)
	mov		ecx, [rdi + VIEW_X]		; x | y << 16
	cmp		byte [abs CELLMEM_BASE + %(steps)d], 0
	je		settled
	cmp		ecx, [abs CELLMEM_BASE + %(pos)d]
	je		settled				; on the square I split from: not a walker
	movzx		r9d, byte [abs CELLMEM_BASE + %(bear)d]
	and		r9d, 3
	movzx		r10d, byte [abs dir_idx + r9]
	cmp		byte [rdi + VIEW_CELLS + r10], CELL_EMPTY
	jne		walk_end			; blocked
	dec		byte [abs CELLMEM_BASE + %(steps)d]
	lea		eax, [r9 + ACT_MOVE]
	ret					; walker move: 39
walk_end:
	mov		byte [abs CELLMEM_BASE + %(steps)d], 0
settled:
	cmp		esi, %(smin)d
	jb		rest
	movzx		r9d, byte [abs CELLMEM_BASE + %(bear)d]
	and		r9d, 3
	cmp		ecx, [abs CELLMEM_BASE + %(pos)d]
	je		rotate				; not the first child from this square
	movzx		r10d, byte [abs dir_idx + r9]
	cmp		byte [rdi + VIEW_CELLS + r10], CELL_EMPTY
	je		emit_long			; first child: forward
rotate:
%(probes)s	inc		r9d				; the fourth square is the empty one
	and		r9d, 3
emit:
	cmp		dword [rdi + VIEW_TICK], %(tearly)d
	jb		emit_long
	mov		byte [abs CELLMEM_BASE + %(steps)d], %(kshort)d
	jmp		emit_store
emit_long:
	mov		byte [abs CELLMEM_BASE + %(steps)d], %(klong)d
emit_store:
	mov		[abs CELLMEM_BASE + %(bear)d], r9b
	mov		[abs CELLMEM_BASE + %(pos)d], ecx
	lea		eax, [r9 + ACT_SPLIT]
	ret
threat:
	mov		byte [abs CELLMEM_BASE + %(steps)d], 0	; a walker stops here
	cmp		esi, %(smin)d
	jb		rest
	cmp		dword [rdi + VIEW_TICK], %(late)d
	jae		EXIT_ADDR			; late: split anyway (al = gate 1's split)
rest:
	mov		al, ACT_REST
	ret
"""

PROBE = """\
	inc		r9d				; next square clockwise
	and		r9d, 3
	movzx		r10d, byte [abs dir_idx + r9]
	cmp		byte [rdi + VIEW_CELLS + r10], CELL_EMPTY
	je		emit
"""

MID_FROM = '\tjz\t\tboxed\n'
MID_TO = 'boxed:\n'


def params(k_long=K_LONG, k_short=K_SHORT, t_early=T_EARLY):
    return {'smin': G.SPLIT_MIN, 'tmin': S.THREAT_MIN, 'rmin': S.REFILL_MIN, 'late': G.LATE_TICK,
            'klong': k_long, 'kshort': k_short, 'tearly': t_early, 'bear': MEM_BEAR, 'steps': MEM_STEPS,
            'pos': MEM_POS, 'pos3': MEM_POS + 3, 'probes': PROBE * 3, 'lock': MEM_LOCK, 'lockact': MEM_LOCKACT,
            'lbase': LOCK_BASE}


def code(body, p):
    """Bane's code with the new middle path and the dir_idx table."""
    assert body.count(MID_FROM) == 1 and body.count(MID_TO) == 1
    a = body.index(MID_FROM) + len(MID_FROM)
    b = body.index(MID_TO)
    body = body[:a] + MIDDLE % p + SETLOCK % p + body[b:]
    assert body.count(BITE_FROM) == 1 and body.count('\nstart:\n') == 1
    body = body.replace(BITE_FROM, BITE_TO).replace('\nstart:\n', '\nstart:\n' + LOCK % p)
    body = body.replace('slow:\t\t\t\t\t\t; 5 instructions so far', 'slow:\t\t\t\t\t\t; 10 instructions so far')
    k = body.index('kTwoHi:')
    k = body.index('\n', k) + 1
    near = ('kNearLo:\tdb %s\t; idx 0..15: 2 at 6 and 8\n' % G.lanes16(0xFF, l6=2, l8=2)
            + 'kNearHi:\tdb %s\t; idx 9..24: 2 at 16 and 18\n' % G.lanes16(0xFF, l7=2, l9=2))
    return body[:k] + near + 'dir_idx:\tdb %s\t; view index of the neighbour UP, RIGHT, DOWN, LEFT\n' % ', '.join(
        '%d' % i for i in DIR_IDX) + 'lock_off:\tdb %s\t; stored-bite offset for UP, RIGHT, DOWN, LEFT\n' % ', '.join(
        '%d' % i for i in LOCK_OFF) + body[k:]


def generate(k_long=K_LONG, k_short=K_SHORT, t_early=T_EARLY):
    src = B.generate()
    k = src.index('\nstart:\n')
    p = params(k_long, k_short, t_early)
    return HEADER % p + code(src[k:], p)


if __name__ == '__main__':
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'bane2.asm')
    src = generate()
    with open(out, 'w', newline='\n') as f:
        f.write(src)
    print('wrote %s (%d bytes source)' % (out, len(src.encode())))
