"""Generate cells/sprint.asm (the "Sprint" ladder cell).  Tables are never written by hand.

    python cells/gen_sprint.py          # writes cells/sprint.asm next to this file

The output has no org/bits/section/%include: the server prepends
`bits 64 / org CODE_BASE / default rel / <cellhack.inc>` and assembles with `nasm -f bin`.

Mask layout (pmovmskb of a 16-byte window starting at view index 7 = VIEW_UP):
    lane 0 = idx 7 UP, lane 4 = idx 11 LEFT, lane 5 = idx 12 self, lane 6 = idx 13 RIGHT,
    lane 10 = idx 17 DOWN.  Only lanes 0, 4, 6, 10 can ever be set (every other lane is compared
    against 0xFF, which no view cell type holds), so masks are 0..0x451 (1106 entries).

The functions fight_table() and split_table() are also imported by sim/tests/test_cells_ref.py, which
checks them against the independent Python reference sim/cells_ref.py.
"""

import os

DIR_UP, DIR_RIGHT, DIR_DOWN, DIR_LEFT = 0, 1, 2, 3
DIR_NAMES = ('up', 'right', 'down', 'left')
LANE = {DIR_UP: 0, DIR_LEFT: 4, DIR_RIGHT: 6, DIR_DOWN: 10}   # mask bit of each direction
N_MASKS = 0x451 + 1                                           # 1106
ACT_REST, ACT_SPLIT, ACT_EAT = 0x01, 0x20, 0x30

FIGHT_PRIO = (DIR_DOWN, DIR_LEFT, DIR_UP, DIR_RIGHT)   # multi-enemy bite order
SPLIT_PRIO = (DIR_DOWN, DIR_RIGHT, DIR_UP, DIR_LEFT)   # split order (home corner unknown: fixed)
OPPOSITE = {DIR_UP: DIR_DOWN, DIR_DOWN: DIR_UP, DIR_LEFT: DIR_RIGHT, DIR_RIGHT: DIR_LEFT}

SPLIT_MIN = 5
THREAT_MIN = 16      # split threshold while an enemy is anywhere in the 5x5 view
LATE_TICK = 2980     # from this tick on the threshold is SPLIT_MIN regardless of enemies


def mask_of(dirs):
    m = 0
    for d in dirs:
        m |= 1 << LANE[d]
    return m


def subsets():
    for bits in range(16):
        yield [d for d in range(4) if bits >> d & 1]


def fight_dir(enemies):
    """Direction to bite for a non-empty list of adjacent enemy directions."""
    if len(enemies) == 3:
        (free,) = [d for d in range(4) if d not in enemies]
        return OPPOSITE[free]
    for d in FIGHT_PRIO:
        if d in enemies:
            return d
    raise ValueError('no enemy')


def fight_table():
    """{mask: dir} for every reachable non-zero mask.  Mask 0 is the slow path; the rest is the stub."""
    return {mask_of(s): fight_dir(s) for s in subsets() if s}


def split_table():
    """{mask: action byte} for every reachable mask (bits = empty adjacent squares)."""
    t = {}
    for s in subsets():
        act = ACT_REST
        for d in SPLIT_PRIO:
            if d in s:
                act = ACT_SPLIT + d
                break
        t[mask_of(s)] = act
    return t


def emit_runs(entries, filler, directive):
    """Lines for a table of N_MASKS entries: explicit entries, gaps as `times n <directive> filler`."""
    out, pos = [], 0
    for m in sorted(entries):
        if m > pos:
            out.append('\ttimes %d %s %s' % (m - pos, directive, filler))
        out.append('\t%s %s\t\t; mask 0x%03x' % (directive, entries[m], m))
        pos = m + 1
    if pos < N_MASKS:
        out.append('\ttimes %d %s %s' % (N_MASKS - pos, directive, filler))
    return out


def lanes16(default, **lanes):
    b = [default] * 16
    for k, v in lanes.items():
        b[int(k[1:])] = v
    return ', '.join('0x%02x' % x for x in b)


HEADER = """\
; Sprint: a small ladder cell for CellHack2.  GENERATED by cells/gen_sprint.py -- do not edit by hand.
; Written with AI help.
;
; Paste this whole file into the site.  It has no org/bits/section/%%include on purpose: the server
; prepends `bits 64 / org CODE_BASE / default rel / <cellhack.inc>` and runs `nasm -f bin`.
; CPU target: plain qemu64 (SSE2 only used).  No memory writes, no loops, no stack use.
;
; Behaviour
;   1. An enemy next to me: bite it.  One enemy: that one.  Two or four: first of DOWN, LEFT, UP, RIGHT.
;      Exactly three: the one opposite the single non-enemy side.
;   2. Otherwise split when energy >= threshold, else rest.  Threshold = %(smin)d, but %(tmin)d while an enemy
;      is anywhere in the 5x5 view, and %(smin)d again from tick %(late)d on.  The split goes to the first
;      empty adjacent square of DOWN, RIGHT, UP, LEFT; with none empty it rests.
;      (Evaluated as: e < %(smin)d rest; no enemy in view split; e >= %(tmin)d split; tick >= %(late)d split;
;      else rest.  Same decisions as the threshold rule, fewer instructions on the common paths.)
;
; Instruction counts per path (every executed instruction, including taken jumps and ret;
; in brackets the same path with taken jumps not counted -- the indirect jmp counts as a taken jump):
;   bite (any adjacent enemy)                               6  (5)
;   rest, e < %(smin)d                                          8  (6)
;   split/rest-by-table, no enemy in view, e >= %(smin)d         19 (18)
;   rest, enemy in view, %(smin)d <= e < %(tmin)d, tick < %(late)d          20 (18)
;   split/rest-by-table, enemy in view, e >= %(tmin)d          21 (18)
;   split/rest-by-table, enemy in view, %(smin)d <= e < %(tmin)d, late  23 (20)
"""

CODE = """\

start:
	movdqu		xmm0, [rdi + VIEW_CELLS + VIEW_UP]	; view idx 7..22
	pcmpeqb		xmm0, [kEnemy]
	pmovmskb	eax, xmm0			; bits 0 UP, 4 LEFT, 6 RIGHT, 10 DOWN
	jmp		[abs fight_tbl + rax*8]		; mask 0 -> slow

eat_up:
	mov		al, ACT_EAT + DIR_UP
	ret
eat_right:
	mov		al, ACT_EAT + DIR_RIGHT
	ret
eat_down:
	mov		al, ACT_EAT + DIR_DOWN
	ret
eat_left:
	mov		al, ACT_EAT + DIR_LEFT
	ret

slow:						; 4 instructions so far
	cmp		esi, SPLIT_MIN
	jb		rest
	movdqu		xmm1, [rdi + VIEW_CELLS]	; view idx 0..15
	movdqu		xmm2, [rdi + VIEW_CELLS + 9]	; view idx 9..24
	pcmpeqb		xmm1, [kTwoLo]			; lane 12 (self) never matches
	pcmpeqb		xmm2, [kTwoHi]			; lane 3 (self) never matches
	por		xmm1, xmm2
	pmovmskb	eax, xmm1
	test		eax, eax
	jnz		threat
split:
	movdqu		xmm0, [rdi + VIEW_CELLS + VIEW_UP]
	pcmpeqb		xmm0, [kEmpty]
	pmovmskb	eax, xmm0			; bits set = empty adjacent squares
	mov		al, [abs split_tbl + rax]	; mask 0 -> ACT_REST
	ret
threat:
	cmp		esi, %(tmin)d
	jae		split
	cmp		dword [rdi + VIEW_TICK], %(late)d
	jae		split
rest:
	mov		al, ACT_REST
	ret
stub:						; unreachable fight_tbl entries
	xor		eax, eax
	ret

; ---- constants (legacy-SSE memory operands must be 16-byte aligned)
	align 16
kEnemy:	db %(kenemy)s	; 2 at UP/LEFT/RIGHT/DOWN lanes
kEmpty:	db %(kempty)s	; 0 at UP/LEFT/RIGHT/DOWN lanes
kTwoLo:	db %(ktwolo)s	; idx 0..15, self (lane 12) excluded
kTwoHi:	db %(ktwohi)s	; idx 9..24, self (lane 3) excluded

; ---- fight_tbl: %(n)d qwords, index = adjacent-enemy mask
	align 8
fight_tbl:
"""


def generate():
    p = {'smin': SPLIT_MIN, 'tmin': THREAT_MIN, 'late': LATE_TICK, 'n': N_MASKS,
         'kenemy': lanes16(0xFF, l0=2, l4=2, l6=2, l10=2),
         'kempty': lanes16(0xFF, l0=0, l4=0, l6=0, l10=0),
         'ktwolo': lanes16(2, l12=0xFF),
         'ktwohi': lanes16(2, l3=0xFF)}
    lines = [HEADER % p + CODE % p]
    fe = {0: 'slow'}
    for m, d in fight_table().items():
        fe[m] = 'eat_' + DIR_NAMES[d]
    lines += emit_runs(fe, 'stub', 'dq')
    lines.append('fight_tbl_end:')
    lines.append('')
    lines.append('; ---- split_tbl: %d bytes, index = empty-adjacent mask' % N_MASKS)
    lines.append('split_tbl:')
    lines += emit_runs({m: '0x%02x' % a for m, a in split_table().items()}, '0x%02x' % ACT_REST, 'db')
    lines.append('split_tbl_end:')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'sprint.asm')
    src = generate()
    with open(out, 'w', newline='\n') as f:
        f.write(src)
    print('wrote %s (%d bytes source)' % (out, len(src.encode())))
