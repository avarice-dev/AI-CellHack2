"""Generate cells/covetous.asm (the "Covetous" ladder cell).  Tables are never written by hand.

    python cells/gen_covetous.py        # writes cells/covetous.asm next to this file

Covetous = Sprint (cells/gen_sprint.py) with two changes:
  1. Bite in 5 instructions in every direction: rax = 0 at entry, so `or al, [bite_tbl + rcx]` loads the
     eat action for the adjacent-enemy mask AND sets ZF (mask without an enemy -> table byte 0 -> ZF=1),
     and the bite leaves with `jnz EXIT_ADDR`: a taken jump straight to the return address, which is
     where `ret` would land, so the ret is saved.  rsp is left 8 lower than after a ret; the stack is
     reset before every call.
  2. Cap feeding: a cell with no adjacent enemy that would otherwise rest (no empty neighbour, or holding
     its split because an enemy is in view) and has energy >= FEED_MIN (47, near the cap of 50 where
     resting gains nothing) feeds its poorest friend neighbour, only if that friend is <= FEED_TMAX (46).
     The poorest neighbour stands in for "nearer the enemy": front cells are the ones drained by bites.

Same mask layout as Sprint: pmovmskb of the 16-byte window at view index 7; lanes 0 UP, 4 LEFT, 6 RIGHT,
10 DOWN; masks 0..0x451.  fight_table()/split_table() are Sprint's (same bite and split choices).
bite_table() is imported by sim/tests/test_cells_ref.py and checked against sim/cells_ref.py.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_sprint as G  # noqa: E402

FEED_MIN = 47
FEED_TMAX = 46
ACT_FEED = 0x40
FEED_ORDER = ((G.DIR_UP, 7), (G.DIR_RIGHT, 13), (G.DIR_DOWN, 17), (G.DIR_LEFT, 11))  # ties: first wins


def bite_table():
    """{mask: eat action byte} for every reachable non-zero mask; every other byte of the table is 0."""
    return {m: G.ACT_EAT + d for m, d in G.fight_table().items()}


HEADER = """\
; Covetous: a small ladder cell for CellHack2.  GENERATED by cells/gen_covetous.py -- do not edit by hand.
; Written with AI help.
;
; Paste this whole file into the site.  It has no org/bits/section/%%include on purpose: the server
; prepends `bits 64 / org CODE_BASE / default rel / <cellhack.inc>` and runs `nasm -f bin`.
; CPU target: plain qemu64 (SSE2 only used).  No memory writes, no loops, no stack use.
; Relies on: rax = 0 at entry (registers are reset before every call).  The bite path leaves with
; `jnz EXIT_ADDR` (a jump to the address `ret` would return to) instead of `ret`.
;
; Behaviour
;   1. An enemy next to me: bite it.  One enemy: that one.  Two or four: first of DOWN, LEFT, UP, RIGHT.
;      Exactly three: the one opposite the single non-enemy side.  (Same choices as Sprint.)
;   2. Otherwise split when energy >= threshold.  Threshold = %(smin)d, but %(tmin)d while an enemy is anywhere
;      in the 5x5 view, and %(smin)d again from tick %(late)d on.  The split goes to the first empty adjacent
;      square of DOWN, RIGHT, UP, LEFT.
;   3. When not splitting (no empty neighbour, or holding for the threshold) and energy >= %(fmin)d: feed the
;      poorest friend neighbour (ties UP, RIGHT, DOWN, LEFT) if its energy <= %(tmax)d.
;   4. Otherwise rest.
;
; Instruction counts per path (every executed instruction, including taken jumps and ret;
; in brackets the same path with taken jumps not counted):
;   bite (any adjacent enemy)                                     5  (4)
;   rest, e < %(smin)d                                                9  (8)
;   split, no enemy in view, e >= %(smin)d                              22 (22)
;   split, enemy in view, e >= %(tmin)d                                 24 (22)
;   split, enemy in view, %(smin)d <= e < %(tmin)d, tick >= %(late)d               26 (24)
;   feed block entered at F (F = 20 no enemy in view / no empty; 19 holding in view, tick < %(late)d;
;     22 enemy in view, e >= %(tmin)d, no empty; 24 same but late with e < %(tmin)d):
;     rest, e < %(fmin)d                                               F + 4
;     otherwise F + 4 + sum over UP, RIGHT, DOWN, LEFT of: 2 not a friend / 5 friend, not poorer than
;     the poorest so far / 7 new poorest; then feed +3, rest (no friend, or poorest > %(tmax)d) +4.
;     Longest: 24 + 4 + 28 + 4 = 60, far below INSN_BUDGET.
"""

CODE = """\

start:
	movdqu		xmm0, [rdi + VIEW_CELLS + VIEW_UP]	; view idx 7..22
	pcmpeqb		xmm0, [kEnemy]
	pmovmskb	ecx, xmm0			; bits 0 UP, 4 LEFT, 6 RIGHT, 10 DOWN
	or		al, [abs bite_tbl + rcx]	; rax = 0 at entry: al = eat action, ZF = no enemy
	jnz		EXIT_ADDR			; bite: leave through the return address

slow:						; 5 instructions so far
	cmp		esi, SPLIT_MIN
	jb		rest
	movdqu		xmm1, [rdi + VIEW_CELLS]	; view idx 0..15
	movdqu		xmm2, [rdi + VIEW_CELLS + 9]	; view idx 9..24
	pcmpeqb		xmm1, [kTwoLo]			; lane 12 (self) never matches
	pcmpeqb		xmm2, [kTwoHi]			; lane 3 (self) never matches
	por		xmm1, xmm2
	pmovmskb	eax, xmm1
	test		eax, eax
	jnz		threat
split:
	movdqu		xmm0, [rdi + VIEW_CELLS + VIEW_UP]
	pcmpeqb		xmm0, [kEmpty]
	pmovmskb	eax, xmm0			; bits set = empty adjacent squares
	test		eax, eax
	jz		feed
	mov		al, [abs split_tbl + rax]	; non-zero mask -> a split
	ret
threat:
	cmp		esi, %(tmin)d
	jae		split
	cmp		dword [rdi + VIEW_TICK], %(late)d
	jae		split
feed:
	cmp		esi, %(fmin)d
	jb		rest
	mov		r8d, 255			; poorest friend energy so far
	mov		eax, ACT_REST
%(feedblock)s
	cmp		r8d, %(tmax)d
	ja		rest				; no friend (255), or the poorest is near the cap too
	ret					; al = ACT_FEED + direction
rest:
	mov		al, ACT_REST
	ret

; ---- constants (legacy-SSE memory operands must be 16-byte aligned)
	align 16
kEnemy:	db %(kenemy)s	; 2 at UP/LEFT/RIGHT/DOWN lanes
kEmpty:	db %(kempty)s	; 0 at UP/LEFT/RIGHT/DOWN lanes
kTwoLo:	db %(ktwolo)s	; idx 0..15, self (lane 12) excluded
kTwoHi:	db %(ktwohi)s	; idx 9..24, self (lane 3) excluded

; ---- bite_tbl: %(n)d bytes, index = adjacent-enemy mask; 0 = no enemy (falls to slow)
bite_tbl:
"""

FEED_DIR = """\
	cmp		byte [rdi + VIEW_CELLS + %(idx)d], CELL_FRIEND	; %(name)s
	jne		.n_%(name)s
	movzx		ecx, byte [rdi + VIEW_ENERGIES + %(idx)d]
	cmp		ecx, r8d
	jae		.n_%(name)s
	mov		r8d, ecx
	mov		al, ACT_FEED + DIR_%(uname)s
.n_%(name)s:"""


def generate(feed_min=FEED_MIN, feed_tmax=FEED_TMAX):
    fb = '\n'.join(FEED_DIR % {'idx': i, 'name': G.DIR_NAMES[d], 'uname': G.DIR_NAMES[d].upper()}
                   for d, i in FEED_ORDER)
    p = {'smin': G.SPLIT_MIN, 'tmin': G.THREAT_MIN, 'late': G.LATE_TICK, 'n': G.N_MASKS,
         'fmin': feed_min, 'tmax': feed_tmax, 'feedblock': fb,
         'kenemy': G.lanes16(0xFF, l0=2, l4=2, l6=2, l10=2),
         'kempty': G.lanes16(0xFF, l0=0, l4=0, l6=0, l10=0),
         'ktwolo': G.lanes16(2, l12=0xFF),
         'ktwohi': G.lanes16(2, l3=0xFF)}
    lines = [HEADER % p + CODE % p]
    lines += G.emit_runs({m: '0x%02x' % a for m, a in bite_table().items()}, '0x00', 'db')
    lines.append('bite_tbl_end:')
    lines.append('')
    lines.append('; ---- split_tbl: %d bytes, index = empty-adjacent mask (mask 0 never looked up)' % G.N_MASKS)
    lines.append('split_tbl:')
    lines += G.emit_runs({m: '0x%02x' % a for m, a in G.split_table().items()}, '0x%02x' % G.ACT_REST, 'db')
    lines.append('split_tbl_end:')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'covetous.asm')
    src = generate()
    with open(out, 'w', newline='\n') as f:
        f.write(src)
    print('wrote %s (%d bytes source)' % (out, len(src.encode())))
