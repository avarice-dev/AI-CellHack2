"""Generate cells/complacency.asm (the "Complacency" cell: Scourge plus early free splitting).  Tables are never
written by hand.

    python cells/gen_complacency.py     # writes cells/complacency.asm next to this file

Complacency is Scourge (cells/gen_scourge.py, legacy SSE2 only) plus exactly one bet (designs.md round 6, from
pull 3's land-grab finding, data/scourge-losses-2026-11-08.md): no prey hold in the early game.  On Scourge's middle
path (no adjacent enemy, an empty neighbour, gate 1 not taken, 5 <= e < 16) Scourge rests while an enemy is anywhere
in the 5x5 view, until tick 2980.  Complacency splits there while tick < FREE_UNTIL, enemy in view or not; from
FREE_UNTIL on it is Scourge.  The tick is checked first on that path (`cmp dword [tick], T` / `jb EXIT_ADDR`; al
already holds the split from act_tbl), so an early split takes 17 instead of 24/25 and every later path through the
5x5 check costs Scourge + 2.  With FREE_UNTIL >= 2980 (never hold) the 5x5 check is dead code and is left out: the
split is a plain `ret` (16).  Bite, gate 1 (refill / split e >= 16), the e < 5 rest, boxed and feed paths are
Scourge's, instruction for instruction.
(First drafted on Woe, the VEX variant; rebased on Scourge 2026-11-08 after calib-s showed the site's QEMU ignores
a VEX op's first source, so Woe is broken on the site.)
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_sprint as G  # noqa: E402
import gen_scourge as S  # noqa: E402

FREE_UNTIL = 3000       # chosen with the sim (designs.md 9): never hold

HEADER = """\
; Complacency: Scourge plus early free splitting, for CellHack2.  GENERATED by cells/gen_complacency.py -- do not
; edit by hand.  Written with AI help.
;
; Paste this whole file into the site.  It has no org/bits/section/%%include on purpose: the server
; prepends `bits 64 / org CODE_BASE / default rel / <cellhack.inc>` and runs `nasm -f bin`.
; CPU target: plain qemu64 (SSE2 only used; no VEX).  No memory reads or writes of the cell memory, no loops,
; no stack use.  Relies on: rax = 0 at entry (registers are reset before every call).
; The bite, gate-1 and early-split paths leave with `jnz`/`jae`/`jb EXIT_ADDR` (the address `ret` returns to).
;
; Behaviour: Scourge's (cells/scourge.asm) with one change in rule 3, the prey hold.
;   1. An enemy next to me: bite it.  One enemy: that one.  Two or four: first of DOWN, LEFT, UP, RIGHT.
;      Exactly three: the one opposite the single non-enemy side.
;   2. Refill: an empty neighbour with an enemy beside or beyond it (view squares 6, 8, 10, 14, 16, 18;
;      2 and 22 are not read) is a freed front square: split into it when energy >= %(rmin)d (child >= %(r)d).
;      First freed square of DOWN, RIGHT, UP, LEFT.
;   3. Otherwise split into the first empty neighbour of DOWN, RIGHT, UP, LEFT when energy >= %(smin)d.
%(rule3)s
;   4. No empty neighbour and energy >= %(fd)d: feed the poorest friend neighbour (ties UP, RIGHT, DOWN,
;      LEFT) if its energy <= energy - %(fm)d; from energy %(fmin)d on, if its energy <= %(tmax)d.
;   5. Otherwise rest.
;
; Instruction counts per path (every executed instruction, including taken jumps and ret;
; in brackets the same path with taken jumps not counted):
;   bite (any adjacent enemy)                                      5  (4)    Scourge 5
;   refill (freed front square, e >= %(rmin)d)                          11 (10)    Scourge 11
;   split, e >= %(tmin)d                                                11 (10)    Scourge 11
%(counts)s
;   rest, e < %(smin)d, an empty neighbour                                17 (16)    Scourge 17
;   rest, boxed (no empty neighbour), e < %(fd)d                         17 (15)    Scourge 17
;   feed block, boxed and e >= %(fd)d: Scourge's (21 + sum over UP, RIGHT, DOWN, LEFT of: 2 not a friend / 5 friend,
;     not poorer than the poorest so far / 7 new poorest; then feed +3, rest +4.  Longest: 53).
"""

RULE3_T = """\
;      Scourge holds (rests) at %(smin)d <= energy < %(tmin)d while an enemy is anywhere in the 5x5 view, until tick %(late)d.
;      Complacency does not hold before tick %(free)d; from tick %(free)d to %(late1)d it holds as Scourge does."""
RULE3_NEVER = """\
;      Scourge holds (rests) at %(smin)d <= energy < %(tmin)d while an enemy is anywhere in the 5x5 view, until tick %(late)d.
;      Complacency never holds: the 5x5 enemy check is gone."""
COUNTS_T = """\
;   split, %(smin)d <= e < %(tmin)d, tick < %(free)d (enemy in view or not)          17 (16)    Scourge 24 / 25, or rest 27
;   split, %(smin)d <= e < %(tmin)d, tick >= %(free)d, no enemy in the 5x5                26 (26)    Scourge 24
;   split, %(smin)d <= e < %(tmin)d, enemy in the 5x5, tick >= %(late)d                   27 (25)    Scourge 25
;   hold (rest), %(smin)d <= e < %(tmin)d, enemy in the 5x5, %(free)d <= tick < %(late)d      29 (28)    Scourge 27"""
COUNTS_NEVER = """\
;   split, %(smin)d <= e < %(tmin)d (enemy in view or not, any tick)              16 (16)    Scourge 24 / 25, or rest 27"""


EARLY = """\
	cmp		dword [rdi + VIEW_TICK], %d
	jb		EXIT_ADDR			; early (tick < %d): split, enemy in view or not
"""
CHECK_FROM = '\tmovdqu\t\txmm1, [rdi + VIEW_CELLS]\t'
CHECK_TO = 'rest:\n'


def code(scourge_code, free_until):
    """Scourge's code with the bet: the early tick check before the 5x5 check, or no 5x5 check at all."""
    src = scourge_code
    assert src.count(CHECK_FROM) == 1 and src.count(CHECK_TO) == 1
    if free_until < G.LATE_TICK:
        return src.replace(CHECK_FROM, EARLY % (free_until, free_until) + CHECK_FROM)
    i, j = src.index(CHECK_FROM), src.index(CHECK_TO)
    src = src[:i] + '\tret\t\t\t\t\t; split: no prey hold\n' + src[j:]
    # the 5x5 constants are unused now
    return '\n'.join(l for l in src.split('\n') if not l.startswith(('kTwoLo:', 'kTwoHi:')))


def params(free_until=FREE_UNTIL, refill_min=S.REFILL_MIN, threat_min=S.THREAT_MIN, feed_d=S.FEED_D,
           feed_margin=S.FEED_MARGIN, feed_min=S.FEED_MIN, feed_tmax=S.FEED_TMAX):
    p = {'smin': G.SPLIT_MIN, 'tmin': threat_min, 'late': G.LATE_TICK, 'late1': G.LATE_TICK - 1,
         'free': free_until, 'rmin': refill_min, 'r': refill_min // 2, 'fd': feed_d, 'fm': feed_margin,
         'fmin': feed_min, 'tmax': feed_tmax}
    t = free_until < G.LATE_TICK
    p['rule3'] = (RULE3_T if t else RULE3_NEVER) % p
    p['counts'] = (COUNTS_T if t else COUNTS_NEVER) % p
    return p


def generate(free_until=FREE_UNTIL, **kw):
    """Scourge's generated source with Complacency's header and the bet in the code (tables unchanged)."""
    src = S.generate(**kw)
    k = src.index('\nstart:\n')
    return HEADER % params(free_until, **kw) + code(src[k:], free_until)


if __name__ == '__main__':
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'complacency.asm')
    src = generate()
    with open(out, 'w', newline='\n') as f:
        f.write(src)
    print('wrote %s (%d bytes source)' % (out, len(src.encode())))
