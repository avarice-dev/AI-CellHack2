"""Generate cells/conviction.asm (the "Conviction" cell: Bane v2.2 with a bite queue).  Tables are never written by hand.

    python cells/gen_conviction.py     # writes cells/conviction.asm next to this file

Conviction is Bane v2.2 (cells/gen_bane2.py: dispersal opening, prey hold only with an enemy on a diagonal square)
with a different stored bite.  Bane re-checks the bitten square every tick (4 instructions).  Conviction does not
look: after a bite found by the view scan it writes a queue of the same bite into its memory and plays one entry per
tick in 3 instructions (shift the queue, load the entry, leave).  When the queue is empty it scans the view again.

The queue length comes from the target's energy at the time of the scan (queue_len): nothing if this bite kills it
(energy <= 2); otherwise the bites an unfed target still needs, at least Q_MIN and at most Q_MAX.  The minimum is for
targets that are fed from behind: they stay, and a short queue would mean a slow view scan on most ticks.  A queue
entry that no longer fits (the target moved, or died early) is a wasted action, or a bite on one of our own cells.

Memory: Bane v2.2's [0] bearing, [1] steps, [4..7] position; [8..15] the queue, one action byte per tick, low byte
next (byte 8 is dropped by the first shift).  A cell that reaches any path below the bite has an empty queue, so a
child never copies a queued bite.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_sprint as G  # noqa: E402
import gen_scourge as S  # noqa: E402
import gen_bane2 as B2  # noqa: E402

Q_MAX = 7               # most queued bites (the queue is 8 bytes; one is dropped by the first shift)
Q_MIN = 3               # least queued bites for a target that survives this bite (it may be fed from behind)
MEM_Q = 8
ENERGY_OFF = tuple(64 + i for i in B2.DIR_IDX)   # VIEW_ENERGIES = 64: view offset of the neighbour's energy


def queue_len(energy, q_max=Q_MAX, q_min=Q_MIN):
    """Queued bites for a target with this energy (the asm masks the energy byte with 63).  Energy <= 2: this bite
    kills it, queue nothing.  Otherwise the bites an unfed target still needs, (energy + 1) // 2 - 1, but at least
    q_min: a target that is fed every tick stays, and a short queue would mean a view scan on most ticks."""
    e = energy & 63
    return 0 if e <= 2 else min(q_max, max(q_min, (e + 1) // 2 - 1))


def queue_value(direction, n):
    """The qword written to the memory: n bytes of EAT + direction in bytes 1..n."""
    return sum((G.ACT_EAT + direction) << (8 * i) for i in range(1, n + 1))


HEADER = """\
; Conviction: Bane v2.2 with a bite queue, for CellHack2.  GENERATED by cells/gen_conviction.py -- do not edit by hand.
; Written with AI help.
;
; Paste this whole file into the site.  It has no org/bits/section/%%include on purpose: the server
; prepends `bits 64 / org CODE_BASE / default rel / <cellhack.inc>` and runs `nasm -f bin`.
; CPU target: plain qemu64 (SSE2 only used; no VEX).  No loops, no stack use.  Relies on: rax = 0 at entry
; (registers are reset before every call).  The cell memory is addressed as [abs CELLMEM_BASE + n].
;
; Memory: [0] bearing, [1] steps left, [4..7] x | y << 16 of the square this cell last split from (Bane v2.2);
; [%(q)d..%(q7)d] the bite queue: one action per tick, the low byte is dropped first.
;
; Behaviour
;   0. Bite queue: shift the queue by one byte; a non-zero entry is the action (3 instructions, the view is not read).
;   1. Otherwise an enemy next to me: bite it (Bane's choice) and queue more bites of the same square: none if this
;      bite kills it (energy <= 2), else what an unfed target still needs, at least %(qmin)d, at most %(qmax)d: 19 instructions.
;   2..5: Bane v2.2 (refill, split, prey hold with an enemy on a diagonal square, walkers, boxed block), each path
;      3 instructions longer than without the queue (refill 14).
"""

PREFIX = """\
	shr		qword [abs CELLMEM_BASE + %(q)d], 8	; bite queue: next entry to the low byte
	or		al, [abs CELLMEM_BASE + %(q)d]		; rax = 0 at entry: al = queued action, ZF = queue empty
	jnz		EXIT_ADDR			; queued bite: 3 instructions
"""
BITE = ("\tor\t\tal, [abs bite_tbl + rcx]\t; al = eat action, ZF = no enemy\n"
        "\tjnz\t\tsetq\t\t\t\t; bite, and queue it for the next ticks\n")
SETQ = """\
setq:
	movzx		ecx, al
	and		ecx, 3				; direction of the bite
	movzx		r8d, byte [abs en_off + rcx]	; view offset of that neighbour's energy
	movzx		r8d, byte [rdi + r8]
	and		r8d, 63
	movzx		r8d, byte [abs n_tbl + r8]	; bites to queue for that energy
	shl		ecx, 3
	add		ecx, r8d
	mov		rcx, [abs q_tbl + rcx * 8]	; the queue for (direction, count)
	mov		[abs CELLMEM_BASE + %(q)d], rcx
	ret
"""


def tables(q_max=Q_MAX):
    out = ['en_off:\tdb %s\t; view offset of the energy of the neighbour UP, RIGHT, DOWN, LEFT' % ', '.join(
        '%d' % i for i in ENERGY_OFF)]
    out.append('n_tbl:\tdb %s\t; queued bites by target energy 0..63' % ', '.join(
        '%d' % queue_len(e, q_max) for e in range(64)))
    out.append('\talign 8')
    out.append('q_tbl:\t\t\t; queue qword for (direction * 8 + count)')
    for d in range(4):
        out.append('\tdq %s' % ', '.join('0x%016x' % queue_value(d, n) for n in range(8)))
    return '\n'.join(out) + '\n'


def generate(q_max=Q_MAX):
    src = B2.generate()
    k = src.index('\nstart:\n')
    body = src[k:]
    p = B2.params()
    lock, setlock = B2.LOCK % p, B2.SETLOCK % p
    lockoff = [l for l in body.split('\n') if l.startswith('lock_off:')]
    assert body.count(lock) == 1 and body.count(setlock) == 1 and body.count(B2.BITE_TO) == 1 and len(lockoff) == 1
    q = {'q': MEM_Q, 'q7': MEM_Q + 7, 'qmax': q_max, 'qmin': Q_MIN}
    body = body.replace(lock, PREFIX % q).replace(B2.BITE_TO, BITE).replace(setlock, SETQ % q)
    body = body.replace(lockoff[0] + '\n', tables(q_max))
    body = body.replace('slow:\t\t\t\t\t\t; 10 instructions so far', 'slow:\t\t\t\t\t\t; 8 instructions so far')
    return HEADER % q + body


if __name__ == '__main__':
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'conviction.asm')
    src = generate()
    with open(out, 'w', newline='\n') as f:
        f.write(src)
    print('wrote %s (%d bytes source)' % (out, len(src.encode())))
