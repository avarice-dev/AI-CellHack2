"""Generate cells/bane.asm (the "Bane" cell: Schism's feeding on Scourge's prey hold).  Tables are never written
by hand.

    python cells/gen_bane.py     # writes cells/bane.asm next to this file

Bane is Scourge (cells/gen_scourge.py: F5 bite, refill, prey hold, capped-donor feeding) plus Schism's boxed rule
(cells/gen_schism.py, designs.md 11.1): no enemy in the 5x5, no empty neighbour, energy >= 6: feed the first friend
of UP, RIGHT, DOWN, LEFT that has an empty neighbour.  The one difference from Schism is that the prey hold is back
(designs.md 11.3, 2026-11-10, docs/evidence/contact-study-2026-11-10.md): with an enemy anywhere in the 5x5 view, a cell at
5 <= e < 16 rests instead of splitting a 2-3-energy child next to a faster biter.  No memory.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_sprint as G  # noqa: E402
import gen_scourge as S  # noqa: E402
import gen_schism as H  # noqa: E402

HEADER = """\
; Bane: Schism's feeding on Scourge's prey hold, for CellHack2.  GENERATED by cells/gen_bane.py -- do not
; edit by hand.  Written with AI help.
;
; Paste this whole file into the site.  It has no org/bits/section/%%include on purpose: the server
; prepends `bits 64 / org CODE_BASE / default rel / <cellhack.inc>` and runs `nasm -f bin`.
; CPU target: plain qemu64 (SSE2 only used; no VEX).  No memory reads or writes of the cell memory, no loops,
; no stack use.  Relies on: rax = 0 at entry (registers are reset before every call).
;
; Behaviour: Scourge's (cells/scourge.asm) with Schism's rule on the boxed path.
;   1. An enemy next to me: bite it (5 instructions in every direction).
;   2. Refill: an empty neighbour with an enemy beside or beyond it: split into it when energy >= %(rmin)d.
;   3. Otherwise split into the first empty neighbour of DOWN, RIGHT, UP, LEFT when energy >= %(tmin)d, or when
;      %(smin)d <= energy < %(tmin)d and no enemy is anywhere in the 5x5 view (from tick %(late)d: always).
;      With an enemy in view and %(smin)d <= energy < %(tmin)d: rest (the prey hold; Schism splits here).
;   4. Boxed (no empty neighbour), no enemy in the 5x5, energy >= %(fmin)d: feed the first friend of UP, RIGHT,
;      DOWN, LEFT that has an empty neighbour.  With no such friend, or an enemy in the 5x5: energy >= %(fd)d: feed
;      the poorest friend under its limits (Scourge's rule 4); otherwise rest.
;
; Instruction counts per path (every executed instruction, including taken jumps and ret):
;   bite 5, refill 11, split e >= %(tmin)d 11: Scourge's
;   split, %(smin)d <= e < %(tmin)d, no enemy in the 5x5                          24     Scourge 24, Schism 16
;   split, %(smin)d <= e < %(tmin)d, enemy in the 5x5, tick >= %(late)d                25     Scourge 25
;   hold (rest), %(smin)d <= e < %(tmin)d, enemy in the 5x5, tick < %(late)d           27     Scourge 27, Schism 16
;   rest, e < %(smin)d, an empty neighbour                                17     Scourge 17
;   rest, boxed, e < %(fmin)d                                       17     Scourge 17
;   new feed (no enemy in the 5x5, a candidate friend)         32 to 48   Schism's
;   rest, boxed, %(fmin)d <= e < %(fd)d, enemy in the 5x5                 27     Schism's
;   rest, boxed, %(fmin)d <= e < %(fd)d, no candidate                 up to 50   Schism's
;   Scourge's feed block, e >= %(fd)d, enemy in the 5x5: Scourge's count + 10 (longest 63)
;   Scourge's feed block, e >= %(fd)d, no enemy, no candidate: longest 86 (Scourge 53)
"""


def code(body):
    """Scourge's code with Schism's boxed path and feed stubs; kTwoLo/kTwoHi stay (the hold uses them)."""
    assert body.count(H.BOXED_FROM) == 1 and body.count(H.CONST_MARK) == 1
    body = body.replace(H.BOXED_FROM, H.boxed_code())
    body = body.replace(H.CONST_MARK, H.feed_code() + H.CONST_MARK)
    k = body.index('kRefill:')
    k = body.index('\n', k) + 1
    return body[:k] + 'kZero:\ttimes 16 db 0\n' + body[k:]


def generate():
    src = S.generate()
    k = src.index('\nstart:\n')
    p = {'smin': G.SPLIT_MIN, 'tmin': S.THREAT_MIN, 'fmin': H.FEED_MIN, 'fd': S.FEED_D, 'rmin': S.REFILL_MIN,
         'late': G.LATE_TICK}
    return HEADER % p + code(src[k:])


if __name__ == '__main__':
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'bane.asm')
    src = generate()
    with open(out, 'w', newline='\n') as f:
        f.write(src)
    print('wrote %s (%d bytes source)' % (out, len(src.encode())))
