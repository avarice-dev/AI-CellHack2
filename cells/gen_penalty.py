"""Generate cells/penalty.asm (the "Penalty" cell: Conviction, and the queue ends by taking the square).

    python cells/gen_penalty.py     # writes cells/penalty.asm next to this file

Penalty is Conviction (cells/gen_conviction.py: Bane v2.2 with a bite queue played in 3 instructions) with one
change to what the queue holds.  When the target is expected to die soon, the last queue entry is a SPLIT into the
target's square.  A square freed by a death opens on the next tick, so that split arrives in 3 instructions on the
first tick the square can be taken.  Conviction played bites into the empty square and lost it (data pull 7: it
filled 10% of the enemy squares freed beside it).

Queue for a target with energy e at the view scan (queue_plan):
  e <= 2                    this bite kills it: [SPLIT]
  3 <= e <= KILL_MAX        k = (e + 1) // 2 - 1 more bites kill an unfed target: [EAT] * k + [SPLIT]
  e > KILL_MAX              too far to predict: Conviction's bites, min(Q_MAX, max(Q_MIN, k)), no split
A target that is fed outlives the plan; the split then fails (the square is occupied) and costs one tick.

Memory and all other paths: Conviction's.  The scan bite takes 18 (the table is indexed by direction and energy).
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_sprint as G  # noqa: E402
import gen_conviction as C  # noqa: E402

KILL_MAX = 8            # predict the kill (and queue the split) up to this target energy
Q_MAX, Q_MIN = C.Q_MAX, C.Q_MIN


def queue_plan(direction, energy):
    """The queued actions (first played first) for a target in `direction` with this energy (masked with 63)."""
    e = energy & 63
    eat, split = G.ACT_EAT + direction, G.ACT_SPLIT + direction
    if e <= 2:
        return [split]
    k = (e + 1) // 2 - 1
    if e <= KILL_MAX:
        return [eat] * k + [split]
    return [eat] * min(Q_MAX, max(Q_MIN, k))


def queue_value(direction, energy):
    """The qword written to the memory: the plan in bytes 1.. (byte 0 is dropped by the first shift)."""
    return sum(a << (8 * (i + 1)) for i, a in enumerate(queue_plan(direction, energy)))


HEADER = """\
; Penalty: Conviction, and the bite queue ends by taking the square, for CellHack2.  GENERATED by
; cells/gen_penalty.py -- do not edit by hand.  Written with AI help.
;
; Paste this whole file into the site.  It has no org/bits/section/%%include on purpose: the server
; prepends `bits 64 / org CODE_BASE / default rel / <cellhack.inc>` and runs `nasm -f bin`.
; CPU target: plain qemu64 (SSE2 only used; no VEX).  No loops, no stack use.  Relies on: rax = 0 at entry
; (registers are reset before every call).  The cell memory is addressed as [abs CELLMEM_BASE + n].
;
; Memory: [0] bearing, [1] steps left, [4..7] x | y << 16 of the square this cell last split from (Bane v2.2);
; [%(q)d..%(q7)d] the queue: one action per tick, the low byte is dropped first.
;
; Behaviour
;   0. Queue: shift the queue by one byte; a non-zero entry is the action (3 instructions, the view is not read).
;   1. Otherwise an enemy next to me: bite it (Bane's choice) and queue what comes next for that square, by its
;      energy e: e <= 2: split into the square (this bite kills it, the square opens next tick); e <= %(kmax)d: the
;      bites that kill an unfed target, then the split; above: %(qmin)d to %(qmax)d bites.  18 instructions.
;   2..5: Bane v2.2 (refill, split, prey hold with an enemy on a diagonal square, walkers, boxed block), each path
;      3 instructions longer than without the queue (refill 14).
"""

SETQ = """\
setq:
	movzx		ecx, al
	and		ecx, 3				; direction of the bite
	movzx		r8d, byte [abs en_off + rcx]	; view offset of that neighbour's energy
	movzx		r8d, byte [rdi + r8]
	and		r8d, 63
	shl		ecx, 6
	add		ecx, r8d
	mov		rcx, [abs q_tbl + rcx * 8]	; the queue for (direction, target energy)
	mov		[abs CELLMEM_BASE + %(q)d], rcx
	ret
"""


def tables():
    out = ['en_off:\tdb %s\t; view offset of the energy of the neighbour UP, RIGHT, DOWN, LEFT' % ', '.join(
        '%d' % i for i in C.ENERGY_OFF)]
    out.append('\talign 8')
    out.append('q_tbl:\t\t\t; queue qword for (direction * 64 + target energy)')
    for d in range(4):
        for e0 in range(0, 64, 8):
            out.append('\tdq %s' % ', '.join('0x%016x' % queue_value(d, e) for e in range(e0, e0 + 8)))
    return '\n'.join(out) + '\n'


def generate():
    src = C.generate()
    k = src.index('\nstart:\n')
    body = src[k:]
    q = {'q': C.MEM_Q, 'q7': C.MEM_Q + 7, 'qmax': Q_MAX, 'qmin': Q_MIN, 'kmax': KILL_MAX}
    old_setq, old_tables = C.SETQ % q, C.tables()
    assert body.count(old_setq) == 1 and body.count(old_tables) == 1
    return HEADER % q + body.replace(old_setq, SETQ % q).replace(old_tables, tables())


if __name__ == '__main__':
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'penalty.asm')
    src = generate()
    with open(out, 'w', newline='\n') as f:
        f.write(src)
    print('wrote %s (%d bytes source)' % (out, len(src.encode())))
