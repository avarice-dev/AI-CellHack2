"""Generate cells/misfortune2.asm (Misfortune v2 hotfix: v1 + hold='split' at 10).  No table is written by hand.

    python cells/gen_misfortune2.py     # writes cells/misfortune2.asm next to this file

Built directly on gen_misfortune.generate() (v1, verified) as an emergency ladder fix after AC1 regressed.
Reference: sim/cells_ref.make_misfortune2_split10() = make_misfortune(cap='B', exact=1, hold='split', hold_min=10).
Change from v1:
 - hold='split' from 10: with an enemy on a diagonal and e >= 10, split immediately into gate 1's freed/empty square
   instead of resting idle until tick 2980 (hold_split: cmp tick, 2980 / jb EXIT_ADDR / mov steps, 0 / ret).
   Below e = 10 the safe v2.2 hold still protects against tick-1 newborn losses (+2 on that resting path).
 - Zero slowdown on v1's core timing: armed bite stays 2, first bite (arm) stays 19, gate-1 refill/split stays 15
   (matching Siect-F's ~15-instruction refill race), walker stays 39, cap B stays 80.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_sprint as G  # noqa: E402
import gen_bane2 as B2  # noqa: E402
import gen_misfortune as M  # noqa: E402

HOLD_MIN = 10               # hold = 'split' from this energy

THREAT_FROM = "threat:\n"
THREAT_TO = ("threat:\n"
             "\tcmp\t\tesi, %(hmin)d\n"
             "\tjae\t\thold_split\t\t\t; hold = 'split': e >= %(hmin)d splits at once\n")
HOLD_SPLIT = """\
hold_split:
	cmp		dword [rdi + VIEW_TICK], %(late)d
	jb		EXIT_ADDR			; split now (al = gate 1's split)
	mov		byte [abs CELLMEM_BASE + %(steps)d], 0	; late: as the v2.2 late split
	ret
"""

HEADER_ADD = """\
; Misfortune v2 (hotfix) = v1 (cells/misfortune.asm) + hold = 'split' from energy %(hmin)d.
; GENERATED by cells/gen_misfortune2.py -- do not edit by hand.  Written with AI help.
;   Prey hold split: with an enemy on a diagonal and energy >= %(hmin)d, split immediately instead of holding idle
;   until tick %(late)d; below %(hmin)d the hold still protects against tick-1 bites.
;   v1 fast paths preserved untouched: armed bite 2, first bite (arm) 19, gate-1 refill / split 15, cap rule B 80.
;
"""


def params():
    p = M.params()
    p.update({'hmin': HOLD_MIN, 'late': G.LATE_TICK, 'steps': B2.MEM_STEPS})
    return p


ARMTBL_FROM = M.ARM % {'e0': M.MEM_E0}
ARMTBL_TO = """arm:
	mov		[abs CELLMEM_BASE + %(e0)d], sil	; e0
	jmp		[abs arm_tbl - ACT_EAT * 8 + rax * 8]	; rax = ACT_EAT + d: one stub per direction (FF 24 C5)
""" % {'e0': M.MEM_E0}
STUB = """%(name)s:
	movzx		edx, byte [rdi + %(off)d]		; te: the target's energy
	movzx		edx, byte [abs k16_tbl + rdx]	; k * 16 (te 0..255)
	movdqu		xmm1, [abs pat1_tbl + %(row)d + rdx]	; row (d, k)
	movdqu		[esi + CELLMEM_BASE + 9], xmm1	; slots e0 - 4 .. e0 + 11 (bytes past 63: scratch)
	mov		byte [abs CELLMEM_BASE + 63], 0	; cap B: slot 50 never armed
	ret					; first bite: 17
"""
ARM_STUBS = ('UP', 'RIGHT', 'DOWN', 'LEFT')


def armtbl_tables():
    out = 'arm_tbl:\t\t\t; jump target per direction (rax = ACT_EAT + d)\n'
    out += '\tdq %s\n' % ', '.join('arm_%s' % n.lower() for n in ARM_STUBS)
    out += M._db('k16_tbl', [M.k_of(te) * 16 for te in range(256)], 'pattern row offset k * 16 by te (te 0..255)') + '\n'
    return out


def generate(armtbl=False):
    src = M.generate()
    k = src.index('\nstart:\n')
    head, body = src[:k], src[k:]
    p = params()
    assert body.count(THREAT_FROM) == 1 and body.count('\narm:\n') == 1
    body = body.replace(THREAT_FROM, THREAT_TO % p)
    body = body.replace('\narm:\n', '\n' + HOLD_SPLIT % p + 'arm:\n')
    head = head.replace('; Misfortune (cap B, exact 1): Bane v2.2 with',
                        '; Misfortune v2 (cap B, exact 1, split10): Bane v2.2 with', 1)
    head = head.replace(';\n; Paste this whole file', ';\n' + HEADER_ADD % p + '; Paste this whole file', 1)
    head = head.replace('GENERATED by cells/gen_misfortune.py', 'GENERATED by cells/gen_misfortune2.py', 1)
    if armtbl:
        assert body.count(ARMTBL_FROM) == 1
        stubs = ''.join(STUB % {'name': 'arm_' + n.lower(), 'off': M.ENERGY_OFF[d], 'row': d * (M.K_MAX + 1) * 16}
                        for d, n in enumerate(ARM_STUBS))
        body = body.replace(ARMTBL_FROM, ARMTBL_TO + stubs)
        i = body.index('row_tbl:')
        j = body.index('pat1_tbl:')
        body = body[:i] + armtbl_tables() + body[j:]
        head = head.replace('first bite (arm) 19', 'first bite (arm) 17 [arm_tbl variant]', 1)
    return head + body


if __name__ == '__main__':
    armtbl = '--armtbl' in sys.argv[1:]        # not shipped: writes misfortune2_armtbl.asm instead
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'misfortune2_armtbl.asm' if armtbl else 'misfortune2.asm')
    src = generate(armtbl)
    with open(out, 'w', newline='\n') as f:
        f.write(src)
    print('wrote %s (%d bytes source)' % (out, len(src.encode())))
