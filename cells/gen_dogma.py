"""Generate cells/dogma.asm ("Dogma": C3b counter bite + first 8/2 walker + +2-lane rotate pick).

    python cells/gen_dogma.py            # writes cells/dogma.asm next to this file

Spec: reviews/dogma-clean-sheet-review-2026-11-14.md sections 4, 6, 7 plus the 2026-11-14 10:55 addendum in
reviews/final-round-2026-11-13-14.md (+2-lane picker tables).  Reference policy: sim/cells_ref.make_dogma().

Ablation knobs (generate(k_cap, k12, quiet_cap)): K_CAP 16 (12 / 25), k for enemy energy 1..2 = 1 (0), QUIET_FEED_CAP 24
(28 / 38).  The shipped defaults write dogma.asm; the variants are built by the checker and the Phase 4 runner.

Memory: [0] bearing, [1] steps left, [4..7] (x | y << 16) + 1 of the square the last child was split from,
[8..15] C3b bitmask 1 << k (0 = unarmed), [16] armed eat action, [17..63] 0.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_sprint as G  # noqa: E402
import gen_scourge as S  # noqa: E402
import gen_covetous as C  # noqa: E402
import gen_bane2 as B2  # noqa: E402

K_CAP = 16
K12 = 1
QUIET_FEED_CAP = 24
FRONT_FEED_CAP = 48
K_LONG, K_SHORT = 8, 2
T_FEED_MIN = 100
IDX = B2.DIR_IDX                    # (7, 13, 17, 11)
ENERGY_OFF = tuple(64 + i for i in IDX)
DIRN = ('up', 'right', 'down', 'left')


def kmask(te, k_cap=K_CAP, k12=K12):
    """C3b mask for a target of energy te: te 0 -> 0 (unarmed); te 1..2 -> 1 << k12 (k12 = 0 -> 0); te >= 3 -> 1 << min(k_cap, te // 2 + 2)."""
    if te == 0:
        return 0
    if te <= 2:
        return (1 << k12) if k12 else 0
    return 1 << min(k_cap, te // 2 + 2)


def open_lo(m):
    """Window idx 2..17 byte lanes 0..7 (idx 2..9): UP (idx 7, lane 5) -> bit 0, UP2 (idx 2, lane 0) -> bit 4."""
    return (((m >> 5) & 1) << 0) | (((m >> 0) & 1) << 4)


def open_hi(m):
    """Lanes 8..15 (idx 10..17): R (13, lane 11) -> 1, D (17, lane 15) -> 2, L (11, lane 9) -> 3, R2 (14, lane 12) -> 5, L2 (10, lane 8) -> 7."""
    return ((((m >> 3) & 1) << 1) | (((m >> 7) & 1) << 2) | (((m >> 1) & 1) << 3) | (((m >> 4) & 1) << 5)
            | (((m >> 0) & 1) << 7))


D2_TBL = (1 << 6, 0, 0, 0)          # cell idx 22 (DOWN2): empty (0) -> bit 4 + 2


def dir_pick(idx):
    """Direction 0..3 for idx = start << 8 | plus2 << 4 | ortho: first d from start with ortho and +2 open, else first ortho open, else start."""
    start, ortho, plus2 = (idx >> 8) & 3, idx & 15, (idx >> 4) & 15
    for k in range(4):
        d = (start + k) & 3
        if ortho >> d & 1 and plus2 >> d & 1:
            return d
    for k in range(4):
        d = (start + k) & 3
        if ortho >> d & 1:
            return d
    return start


def _db(label, vals, comment, per=16):
    out = ['%s:\t\t\t; %s' % (label, comment)]
    for i in range(0, len(vals), per):
        out.append('\tdb ' + ', '.join('%d' % v for v in vals[i:i + per]))
    return '\n'.join(out) + '\n'


HEADER = """\
; Dogma: C3b counter bite, first 8/2 walker, +2-lane rotate pick, for CellHack2.
; GENERATED by cells/gen_dogma.py -- do not edit by hand.  Written with AI help.
; Spec: reviews/dogma-clean-sheet-review-2026-11-14.md sections 4, 6, 7 and the 2026-11-14 10:55 addendum (reviews/final-round-2026-11-13-14.md section 5).
;
; Paste this whole file into the site.  It has no org/bits/section/%%include on purpose: the server
; prepends `bits 64 / org CODE_BASE / default rel / <cellhack.inc>` and runs `nasm -f bin`.
; CPU target: plain qemu64 (SSE2 only; no VEX, no popcnt).  No loops, no stack use.
; Relies on: rax = 0 and xmm0 = 0 at entry, esi = own energy, rdx = cell memory.  No esi-indexed memory operand.
; Every pmovmskb outside the bite scan and gate 1 writes r8d, so rdx stays the cell memory pointer.
;
; Memory: [0] bearing, [1] steps left, [4..7] (x | y << 16) + 1 of the last split square, [8..15] bitmask 1 << k
; (0 = unarmed; shr qword [rdx+8], 1 per call: k blind bites), [16] armed eat action, [17..63] 0.
; Parameters: K_CAP %(kcap)d, k for enemy energy 1..2 = %(k12)d, QUIET_FEED_CAP %(qcap)d, FRONT_FEED_CAP 48, REFILL_MIN 12,
; THREAT_MIN 16, T_FEED_MIN 100, K_LONG 8, K_SHORT 2.
;
; Paths (every executed instruction): hot armed bite 3; first bite (arm) 15; gate 1 refill / split 15; diagonal enemy
; split 28 / rest 30; walker move 39; settled rest 33 / 35 / 41; first child forward 43; rotate_pick 54 / 56 / 57 / 65;
; boxed rest 21 / 23, boxed feed 47..68.
;
"""

CODE = """\
start:
	shr		qword [rdx + 8], 1		; ZF = 1 iff the mask is now 0
	mov		al, [rdx + 16]			; mov keeps ZF
	jnz		EXIT_ADDR			; hot armed bite: 3 instructions
	xor		eax, eax			; wipe the stale armed action from al
	movdqu		xmm0, [rdi + VIEW_CELLS + VIEW_UP]	; view idx 7..22
	pcmpeqb		xmm0, [kEnemy]
	pmovmskb	ecx, xmm0			; bits 0 UP, 4 LEFT, 6 RIGHT, 10 DOWN
	or		al, [abs bite_tbl + rcx]	; al = eat action, ZF = no enemy
	jnz		arm

slow:						; 9 instructions so far
	movdqu		xmm1, [rdi + VIEW_CELLS + 6]	; view idx 6..21
	pcmpeqb		xmm1, [kRefill]
	pmovmskb	ecx, xmm1
	mov		al, [abs act_tbl + rcx]		; split to take (0 = boxed)
	cmp		sil, [abs thr_tbl + rcx]	; energy it needs (12 refill, 16 other, 255 boxed)
	jae		EXIT_ADDR			; gate 1: 15
	test		al, al
	jz		boxed
	movdqu		xmm1, [rdi + VIEW_CELLS]	; diagonal enemy stop
	movdqu		xmm2, [rdi + VIEW_CELLS + 9]
	pcmpeqb		xmm1, [kNearLo]
	pcmpeqb		xmm2, [kNearHi]
	por		xmm1, xmm2
	pmovmskb	r8d, xmm1
	test		r8d, r8d
	jnz		threat				; 25 instructions so far
	mov		ecx, [rdi + VIEW_X]		; x | y << 16
	inc		ecx				; + 1: (0, 0) is not 0
	cmp		byte [rdx + 1], 0
	je		settled				; entry at 29
	cmp		ecx, [rdx + 4]
	je		settled				; entry at 31
	movzx		r9d, byte [rdx]
	and		r9d, 3
	movzx		r10d, byte [abs dir_idx + r9]
	cmp		byte [rdi + VIEW_CELLS + r10], CELL_EMPTY
	jne		walk_end			; 36
	dec		byte [rdx + 1]
	lea		eax, [r9 + ACT_MOVE]
	ret					; walker move: 39
walk_end:
	mov		byte [rdx + 1], 0		; entry at 37
settled:
	cmp		esi, 5
	jb		rest
	movzx		r9d, byte [rdx]
	and		r9d, 3
	cmp		ecx, [rdx + 4]
	je		rotate_pick
	movzx		r10d, byte [abs dir_idx + r9]
	cmp		byte [rdi + VIEW_CELLS + r10], CELL_EMPTY
	jne		rotate_pick
	mov		byte [rdx + 1], %(klong)d		; first child, forward: long walk
	mov		[rdx], r9b
	mov		[rdx + 4], ecx
	lea		eax, [r9 + ACT_SPLIT]
	ret					; 43
rotate_pick:
	lea		r10d, [r9 + 1]
	and		r10d, 3
	shl		r10d, 8				; rotation start (bearing + 1) << 8
	movdqu		xmm1, [rdi + VIEW_CELLS + 2]	; view idx 2..17
	pcmpeqb		xmm1, [kOpen7]			; lane = 0 where empty
	pmovmskb	r8d, xmm1
	movzx		r9d, r8b
	movzx		r9d, byte [abs open_lo + r9]
	shr		r8d, 8
	or		r9b, [abs open_hi + r8]
	movzx		r8d, byte [rdi + VIEW_CELLS + 22]
	or		r9b, [abs d2_tbl + r8]		; r9b = plus2_empty4 << 4 | ortho_empty4
	or		r9d, r10d
	movzx		r11d, byte [abs dir_pick_tbl + r9]
	mov		byte [rdx + 1], %(kshort)d
	mov		[rdx], r11b
	mov		[rdx + 4], ecx
	lea		eax, [r11 + ACT_SPLIT]
	ret
threat:
	mov		byte [rdx + 1], 0
	cmp		esi, 5
	jae		EXIT_ADDR			; split now with gate 1's action: 28
rest:
	mov		al, ACT_REST
	ret					; 30 from threat
boxed:
	cmp		dword [rdi + VIEW_TICK], %(tfeed)d
	jb		rest				; t < 100: no feed
	cmp		esi, 16
	jb		rest
	movdqu		xmm1, [rdi + VIEW_CELLS]
	movdqu		xmm2, [rdi + VIEW_CELLS + 9]
	pcmpeqb		xmm1, [kTwoLo]
	pcmpeqb		xmm2, [kTwoHi]
	por		xmm1, xmm2
	pmovmskb	r8d, xmm1
	test		r8d, r8d
	jnz		boxed_front
	lea		r9d, [rsi - 4]			; quiet interior: poorest friend <= e - 4 ...
	mov		r10d, %(qcap)d
	cmp		esi, %(qcap4)d
	cmovae		r9d, r10d			; ... or <= %(qcap)d
	jmp		find_poorest
boxed_front:
	lea		r9d, [rsi - 4]			; 5x5 enemy front
	mov		r10d, 48
	cmp		esi, 49
	cmovae		r9d, r10d
find_poorest:
	mov		r8d, 255			; poorest friend energy so far
	mov		eax, ACT_REST
%(feedblock)s
	cmp		r8d, r9d
	ja		rest				; no friend (255), or the poorest is above the limit
	ret					; al = ACT_FEED + direction
arm:
	jmp		[abs arm_tbl - ACT_EAT * 8 + rax * 8]	; rax = ACT_EAT + d (FF 24 C5)
"""

STUB = """\
arm_%(name)s:
	mov		[rdx + 16], al
	movzx		ecx, byte [rdi + %(off)d]		; te: the target's energy
	mov		r8, [abs kmask_tbl + rcx * 8]
	mov		[rdx + 8], r8
	ret					; first bite: 15
"""


def generate(k_cap=K_CAP, k12=K12, quiet_cap=QUIET_FEED_CAP):
    fb = '\n'.join(C.FEED_DIR % {'idx': i, 'name': G.DIR_NAMES[d], 'uname': G.DIR_NAMES[d].upper()}
                   for d, i in C.FEED_ORDER)
    p = {'kcap': k_cap, 'k12': k12, 'qcap': quiet_cap, 'qcap4': quiet_cap + 4, 'klong': K_LONG, 'kshort': K_SHORT,
         'tfeed': T_FEED_MIN, 'feedblock': fb}
    kref = {'l%d' % (i - S.WIN): 0 for i in S.EMPTY_IDX.values()}
    kref.update({'l%d' % (i - S.WIN): 2 for i in S.ENEMY_IDX})
    out = [HEADER % p, CODE % p]
    for n in ('up', 'right', 'down', 'left'):
        d = DIRN.index(n)
        out.append(STUB % {'name': n, 'off': ENERGY_OFF[d]})
    out.append('\n; ---- constants (legacy-SSE memory operands must be 16-byte aligned)\n\talign 16')
    out.append('kEnemy:\tdb %s\t; 2 at UP / LEFT / RIGHT / DOWN lanes (window idx 7..22)' % G.lanes16(0xFF, l0=2, l4=2, l6=2, l10=2))
    out.append('kRefill:\tdb %s\t; window idx 6..21: 0 at neighbours, 2 at 6 / 8 / 10 / 14 / 16 / 18' % G.lanes16(0xFF, **kref))
    out.append('kNearLo:\tdb %s\t; idx 0..15: 2 at 6 and 8' % G.lanes16(0xFF, l6=2, l8=2))
    out.append('kNearHi:\tdb %s\t; idx 9..24: 2 at 16 and 18' % G.lanes16(0xFF, l7=2, l9=2))
    out.append('kTwoLo:\tdb %s\t; idx 0..15, self (lane 12) excluded' % G.lanes16(2, l12=0xFF))
    out.append('kTwoHi:\tdb %s\t; idx 9..24, self (lane 3) excluded' % G.lanes16(2, l3=0xFF))
    out.append('kOpen7:\tdb %s\t; idx 2..17: 0 = empty' % ', '.join(['0x00'] * 16))
    out.append('dir_idx:\tdb %s\t; view index of the neighbour UP, RIGHT, DOWN, LEFT' % ', '.join('%d' % i for i in IDX))
    out.append('arm_tbl:\t\t\t; jump target per direction (rax = ACT_EAT + d)')
    out.append('\tdq arm_up, arm_right, arm_down, arm_left')
    out.append('d2_tbl:\tdb %s\t; cell type at idx 22 -> bit 6 when empty' % ', '.join('%d' % v for v in D2_TBL))
    out.append('')
    out.append('kmask_tbl:\t\t\t; 1 << k by enemy energy (0 = unarmed), K_CAP %d, k(1..2) = %d' % (k_cap, k12))
    for i in range(0, 256, 4):
        out.append('\tdq ' + ', '.join('0x%x' % kmask(te, k_cap, k12) for te in range(i, i + 4)))
    out.append('')
    out.append(_db('open_lo', [open_lo(m) for m in range(256)], 'by pmovmskb low byte: UP -> 1, UP2 -> 16'))
    out.append(_db('open_hi', [open_hi(m) for m in range(256)], 'by pmovmskb high byte: R 2, D 4, L 8, R2 32, L2 128'))
    out.append(_db('dir_pick_tbl', [dir_pick(i) for i in range(1024)], 'index start << 8 | plus2 << 4 | ortho -> direction',
                   per=32))
    out.append('; ---- bite_tbl: %d bytes, index = adjacent-enemy mask; 0 = no enemy' % G.N_MASKS)
    out.append('bite_tbl:')
    out += G.emit_runs({m: '0x%02x' % a for m, a in C.bite_table().items()}, '0x00', 'db')
    out.append('bite_tbl_end:')
    out.append('')
    act, thr = S.refill_tables()
    out.append('; ---- act_tbl: %d bytes, index = gate-1 mask; split action, 0 = boxed' % S.N_REFILL)
    out.append('act_tbl:')
    out += S.emit_table(act, S.N_REFILL, 0)
    out.append('act_tbl_end:')
    out.append('')
    out.append('; ---- thr_tbl: %d bytes, index = gate-1 mask; energy needed (255 = boxed)' % S.N_REFILL)
    out.append('thr_tbl:')
    out += S.emit_table(thr, S.N_REFILL, 255)
    out.append('thr_tbl_end:')
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'dogma.asm')
    src = generate()
    with open(out, 'w', newline='\n') as f:
        f.write(src)
    print('wrote %s (%d bytes source)' % (out, len(src.encode())))
