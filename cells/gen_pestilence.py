"""Generate cells/pestilence.asm (the "Pestilence" cell: Schism plus move refills).  Tables are never written by hand.

    python cells/gen_pestilence.py     # writes cells/pestilence.asm next to this file

Pestilence is Schism (cells/gen_schism.py) plus one rule (designs.md 11.2, change 1 only): on gate 1's refill path
(an empty neighbour with an enemy beside or beyond it), energy >= MOVE_MIN: MOVE into that square, do not split.
The cell carries its energy forward; a refill child gets floor(e/2).  Move = split - 0x10 in the action encoding.
Before gate 1 loads its action, `cmp sil, [mv_tbl + rcx]` / `jae move` (MOVE_MIN on refill masks, 255
elsewhere).  The move takes 13; every other path after the bite costs 2 more than Schism's (split 13).  No memory.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_scourge as S  # noqa: E402
import gen_schism as H  # noqa: E402

MOVE_MIN = 20           # designs.md 11.2
ACT_LOAD = '\tmov\t\tal, [abs act_tbl + rcx]\t\t; split to take (0 = no empty neighbour)\n'
MOVE_CHECK = ('\tcmp\t\tsil, [abs mv_tbl + rcx]\t\t; %d on refill masks, 255 elsewhere\n'
              '\tjae\t\tmove\t\t\t\t; move refill: 13 instructions\n')
MOVE = ('move:\n'
        '\tmov\t\tal, [abs act_tbl + rcx]\t\t; the refill split\n'
        '\tsub\t\tal, 0x10\t\t\t; split -> move, same direction\n'
        '\tret\n')
HEAD_FROM = '; Schism: Complacency plus feeding the growing edge, for CellHack2.  GENERATED by cells/gen_schism.py'
HEAD_TO = ('; Pestilence: Schism plus move refills (e >= %d), for CellHack2.  GENERATED by cells/gen_pestilence.py'
           % MOVE_MIN)
COUNTS_FROM = ';   bite 5, refill 11, split e >= '
COUNTS_TO = ";   Pestilence: move refill e >= %d 13; every path below except the bite is Schism's + 2:\n" % MOVE_MIN


def move_table():
    """{mask: energy needed to move} for refill masks (Scourge's refill threshold, below its threat threshold)."""
    act, thr = S.refill_tables()
    rmin = min(S.REFILL_MIN, S.THREAT_MIN)
    assert rmin < S.THREAT_MIN
    return {m: MOVE_MIN for m, a in act.items() if a and thr[m] == rmin}


def generate():
    src = H.generate()
    assert src.count(ACT_LOAD) == 1 and src.count(HEAD_FROM) == 1 and src.count(COUNTS_FROM) == 1
    src = src.replace(HEAD_FROM, HEAD_TO).replace(COUNTS_FROM, COUNTS_TO + COUNTS_FROM)
    src = src.replace(ACT_LOAD, MOVE_CHECK % MOVE_MIN + ACT_LOAD)
    gate1 = '; refill / split: 11 instructions'
    assert src.count(gate1) == 1
    src = src.replace(gate1, '; refill / split: 13 instructions')
    k = src.index('rest:\n')
    src = src[:k] + MOVE + src[k:]
    lines = ['', '; ---- mv_tbl: %d bytes, index = gate-1 mask; energy needed to move (non-refill entries 255)'
             % S.N_REFILL, 'mv_tbl:']
    lines += S.emit_table(move_table(), S.N_REFILL, 255)
    lines.append('mv_tbl_end:')
    return src.rstrip('\n') + '\n' + '\n'.join(lines) + '\n'


if __name__ == '__main__':
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'pestilence.asm')
    src = generate()
    with open(out, 'w', newline='\n') as f:
        f.write(src)
    print('wrote %s (%d bytes source)' % (out, len(src.encode())))
