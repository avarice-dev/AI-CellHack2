"""Generate cells/schism.asm (the "Schism" cell: Complacency plus feeding the growing edge).  Tables are never written
by hand.

    python cells/gen_schism.py     # writes cells/schism.asm next to this file

Schism is Complacency (cells/gen_complacency.py, never hold) plus one rule (designs.md 11.1, policy a+f6x in
sim/growth.py): no enemy in the 5x5, no empty neighbour, energy >= 6: feed the first friend of UP, RIGHT, DOWN, LEFT
that has an empty neighbour.  The candidate overrides Complacency's feed.  With no candidate, or an enemy in the 5x5,
the boxed path ends as Complacency's does.  Split order, bite, gate 1 and the middle split are Complacency's.  No memory.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_sprint as G  # noqa: E402
import gen_scourge as S  # noqa: E402
import gen_complacency as C  # noqa: E402

FEED_MIN = 6            # designs.md 11.1
# bit (view index - 6) of the empty mask of view 6..21; 2 and 22 are outside that load and are read on their own
RING = (('up', 7, 'UP', 0x0005, 2), ('right', 13, 'RIGHT', 0x1104, None),
        ('down', 17, 'DOWN', 0x1400, 22), ('left', 11, 'LEFT', 0x0411, None))

BOXED_FROM = 'boxed:\n\tcmp\t\tesi, %d\n\tjb\t\trest\n' % S.FEED_D
CONST_MARK = '\n; ---- constants'

HEADER = """\
; Schism: Complacency plus feeding the growing edge, for CellHack2.  GENERATED by cells/gen_schism.py -- do not
; edit by hand.  Written with AI help.
;
; Paste this whole file into the site.  It has no org/bits/section/%%include on purpose: the server
; prepends `bits 64 / org CODE_BASE / default rel / <cellhack.inc>` and runs `nasm -f bin`.
; CPU target: plain qemu64 (SSE2 only used; no VEX).  No memory reads or writes of the cell memory, no loops,
; no stack use.  Relies on: rax = 0 at entry (registers are reset before every call).
;
; Behaviour: Complacency's (cells/complacency.asm) with one new rule on the boxed path.
;   New rule: no enemy in the 5x5, no empty neighbour, energy >= %(fmin)d: feed the first friend of UP, RIGHT, DOWN,
;   LEFT that has an empty neighbour.  With no such friend, or an enemy in the 5x5: Complacency's boxed path
;   (energy >= %(fd)d: feed the poorest friend under its limits; otherwise rest).
;
; Instruction counts per path (every executed instruction, including taken jumps and ret):
;   bite 5, refill 11, split e >= %(tmin)d 11, split %(smin)d <= e < %(tmin)d 16, rest e < %(smin)d 17: Complacency's
;   rest, boxed, e < %(fmin)d                                       17     Complacency 17
;   new feed (no enemy in the 5x5, a candidate friend)         32 to 48
;   rest, boxed, %(fmin)d <= e < %(fd)d, enemy in the 5x5                 27     Complacency 17
;   rest, boxed, %(fmin)d <= e < %(fd)d, no candidate                 up to 50   Complacency 17
;   Complacency's feed block, e >= %(fd)d, enemy in the 5x5: Complacency's count + 10 (longest 63)
;   Complacency's feed block, e >= %(fd)d, no enemy, no candidate: longest 86 (Complacency 53)
"""


def boxed_code():
    s = ['boxed:', '\tcmp\t\tesi, %d' % FEED_MIN, '\tjb\t\trest',
         '\tmovdqu\t\txmm1, [rdi + VIEW_CELLS]\t; view idx 0..15',
         '\tmovdqu\t\txmm2, [rdi + VIEW_CELLS + 9]\t; view idx 9..24',
         '\tpcmpeqb\t\txmm1, [kTwoLo]', '\tpcmpeqb\t\txmm2, [kTwoHi]', '\tpor\t\txmm1, xmm2',
         '\tpmovmskb\tedx, xmm1', '\ttest\t\tedx, edx', '\tjnz\t\tfallback\t\t\t; enemy in the 5x5',
         '\tmovdqu\t\txmm1, [rdi + VIEW_CELLS + 6]\t; view idx 6..21',
         '\tpcmpeqb\t\txmm1, [kZero]', '\tpmovmskb\tedx, xmm1\t\t\t; bit (idx - 6): empty']
    for name, i, _, mask, far in RING:
        s += ['\tcmp\t\tbyte [rdi + VIEW_CELLS + %d], CELL_FRIEND' % i, '\tjne\t\t.s_%s' % name,
              '\ttest\t\tedx, 0x%04x' % mask, '\tjnz\t\tfeed_%s' % name]
        if far is not None:
            s += ['\tcmp\t\tbyte [rdi + VIEW_CELLS + %d], CELL_EMPTY' % far, '\tje\t\tfeed_%s' % name]
        s += ['.s_%s:' % name]
    s += ['fallback:', '\tcmp\t\tesi, %d' % S.FEED_D, '\tjb\t\trest', '']
    return '\n'.join(s)


def feed_code():
    s = ['']
    for name, _, d, _, _ in RING:
        s += ['feed_%s:' % name, '\tmov\t\tal, ACT_FEED + DIR_%s' % d, '\tret']
    return '\n'.join(s) + '\n'


def code(body, two_lines):
    assert body.count(BOXED_FROM) == 1 and body.count(CONST_MARK) == 1
    body = body.replace(BOXED_FROM, boxed_code())
    body = body.replace(CONST_MARK, feed_code() + CONST_MARK)
    k = body.index('kRefill:')
    k = body.index('\n', k) + 1
    return body[:k] + two_lines + 'kZero:\ttimes 16 db 0\n' + body[k:]


def generate():
    src = S.generate()
    k = src.index('\nstart:\n')
    two = ''.join(l + '\n' for l in src.split('\n') if l.startswith(('kTwoLo:', 'kTwoHi:')))
    assert two.count('\n') == 2
    p = {'smin': G.SPLIT_MIN, 'tmin': S.THREAT_MIN, 'fmin': FEED_MIN, 'fd': S.FEED_D}
    return HEADER % p + code(C.code(src[k:], C.FREE_UNTIL), two)


if __name__ == '__main__':
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'schism.asm')
    src = generate()
    with open(out, 'w', newline='\n') as f:
        f.write(src)
    print('wrote %s (%d bytes source)' % (out, len(src.encode())))
