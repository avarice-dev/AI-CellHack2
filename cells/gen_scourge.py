"""Generate cells/scourge.asm (the "Scourge" ladder cell).  Tables are never written by hand.

    python cells/gen_scourge.py         # writes cells/scourge.asm next to this file

Scourge = Covetous (cells/gen_covetous.py) plus a stateless refill of freed front squares (designs.md
round 4, 2.1-2.5 and 3):
  1. Bite: Covetous's F5 (5 instructions in every direction, no memory).
  2. Gate 1, right after the F5 miss: ONE unaligned 16-byte window of view idx 6..21 compared against
     kRefill (0 = empty at the four neighbour lanes, 2 = enemy at the six squares 6, 8, 10, 14, 16, 18)
     gives a mask of 10 lanes (bits 0, 1, 2, 4, 5, 7, 8, 10, 11, 12: 13 bits wide, max 7607).
     act_tbl[mask] is the split to take, thr_tbl[mask] the energy it
     needs, and `cmp sil, [thr_tbl+rcx]` / `jae EXIT_ADDR` takes it: 11 instructions for
       - a refill: an empty neighbour with an enemy beside or beyond it (freed front square) when the
         child gets >= R = 6 (e >= REFILL_MIN = 12); first freed square of DOWN, RIGHT, UP, LEFT;
       - any other split when e >= THREAT_MIN = 16 (the prey rule's child >= 8 holds whatever is in view).
     Squares 2 and 22 (beyond UP and beyond DOWN) do not fit in the window (idx 2..22 spans 21 bytes)
     and are not read: an enemy there alone does not make a refill.
  3. Below gate 1: 5 <= e < 16 with an empty neighbour splits only if no enemy is anywhere in the 5x5
     (Covetous's two-window check) or from tick LATE_TICK on; otherwise rest.
  4. Boxed cells (no empty neighbour; act_tbl = 0) with e >= FEED_D = 16 feed the poorest friend
     neighbour if it is <= e - 4 (capped donors e >= 47: if it is <= 46).  Front cells (adjacent enemy
     or a refill) never get here.
No memory use.  refill_mask()/refill_tables() are imported by sim/tests/test_scourge.py and checked
against sim/cells_ref.scourge; cells/check_cells.py diffs the assembled cell against it in Unicorn.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_sprint as G  # noqa: E402
import gen_covetous as C  # noqa: E402

REFILL_MIN = 12         # parent energy for a refill: child floor(e/2) >= R = 6
THREAT_MIN = 16         # prey rule: a normal split near an enemy only if the child gets >= 8
FEED_D = 16             # donor floor
FEED_MARGIN = 4         # donors below the cap feed a friend <= e - 4
FEED_MIN, FEED_TMAX = C.FEED_MIN, C.FEED_TMAX   # capped donors (Covetous): e >= 47 feed a friend <= 46
ACT_NOP = 0x00

WIN = 6                 # refill window: view idx 6..21
EMPTY_IDX = {G.DIR_UP: 7, G.DIR_RIGHT: 13, G.DIR_DOWN: 17, G.DIR_LEFT: 11}
ENEMY_IDX = (6, 8, 10, 14, 16, 18)
FREED_BY = {G.DIR_UP: (6, 8), G.DIR_RIGHT: (8, 14, 18), G.DIR_DOWN: (16, 18), G.DIR_LEFT: (6, 10, 16)}
N_REFILL = sum(1 << (i - WIN) for i in list(EMPTY_IDX.values()) + list(ENEMY_IDX)) + 1   # 7608


def refill_mask(cells):
    """The pmovmskb result of gate 1 for a 25-entry cell-type list."""
    m = 0
    for i in EMPTY_IDX.values():
        if cells[i] == 0:
            m |= 1 << (i - WIN)
    for i in ENEMY_IDX:
        if cells[i] == 2:
            m |= 1 << (i - WIN)
    return m


def refill_tables(refill_min=REFILL_MIN, threat_min=THREAT_MIN):
    """({mask: action byte}, {mask: energy needed}) for every reachable mask.  Boxed masks: action 0
    (ACT_NOP, never returned below e 255) and threshold 255."""
    act, thr = {}, {}
    for bits in range(1 << 10):
        cells = [0] * 25
        cells[12] = 1
        for k, i in enumerate(EMPTY_IDX.values()):
            cells[i] = 0 if bits >> k & 1 else 1
        for k, i in enumerate(ENEMY_IDX):
            cells[i] = 2 if bits >> (4 + k) & 1 else 0
        m = refill_mask(cells)
        empty = [d for d in G.SPLIT_PRIO if cells[EMPTY_IDX[d]] == 0]
        freed = [d for d in empty if any(cells[i] == 2 for i in FREED_BY[d])]
        if freed:
            act[m], thr[m] = G.ACT_SPLIT + freed[0], min(refill_min, threat_min)
        elif empty:
            act[m], thr[m] = G.ACT_SPLIT + empty[0], threat_min
        else:
            act[m], thr[m] = ACT_NOP, 255
    return act, thr


def emit_table(entries, n, filler):
    """db lines for an n-entry table: runs of explicit entries on one line, gaps as `times`."""
    out, pos, run = [], 0, []
    for m in sorted(entries):
        if m > pos:
            if run:
                out.append('\tdb ' + ','.join(run))
                run = []
            out.append('\ttimes %d db %d' % (m - pos, filler))
        run.append('%d' % entries[m])
        if len(run) == 32:
            out.append('\tdb ' + ','.join(run))
            run = []
        pos = m + 1
    if run:
        out.append('\tdb ' + ','.join(run))
    if pos < n:
        out.append('\ttimes %d db %d' % (n - pos, filler))
    return out


HEADER = """\
; Scourge: a ladder cell for CellHack2.  GENERATED by cells/gen_scourge.py -- do not edit by hand.
; Written with AI help.
;
; Paste this whole file into the site.  It has no org/bits/section/%%include on purpose: the server
; prepends `bits 64 / org CODE_BASE / default rel / <cellhack.inc>` and runs `nasm -f bin`.
; CPU target: plain qemu64 (SSE2 only used).  No memory reads or writes of the cell memory, no loops,
; no stack use.  Relies on: rax = 0 at entry (registers are reset before every call).  The bite and
; gate-1 paths leave with `jnz`/`jae EXIT_ADDR` (a jump to the address `ret` would return to).
;
; Behaviour
;   1. An enemy next to me: bite it.  One enemy: that one.  Two or four: first of DOWN, LEFT, UP, RIGHT.
;      Exactly three: the one opposite the single non-enemy side.  (Same choices as Sprint/Covetous.)
;   2. Refill: an empty neighbour with an enemy beside or beyond it (view squares 6, 8, 10, 14, 16, 18;
;      2 and 22 are not read) is a freed front square: split into it when energy >= %(rmin)d (child >= %(r)d).
;      First freed square of DOWN, RIGHT, UP, LEFT.
;   3. Otherwise split into the first empty neighbour of DOWN, RIGHT, UP, LEFT when energy >= %(tmin)d, or
;      when %(smin)d <= energy < %(tmin)d and no enemy is anywhere in the 5x5 view (from tick %(late)d: always).
;   4. No empty neighbour and energy >= %(fd)d: feed the poorest friend neighbour (ties UP, RIGHT, DOWN,
;      LEFT) if its energy <= energy - %(fm)d; from energy %(fmin)d on, if its energy <= %(tmax)d.
;   5. Otherwise rest.
;
; Instruction counts per path (every executed instruction, including taken jumps and ret;
; in brackets the same path with taken jumps not counted):
;   bite (any adjacent enemy)                                      5  (4)
;   refill (freed front square, e >= %(rmin)d)                          11 (10)
;   split, e >= %(tmin)d                                                11 (10)
;   split, %(smin)d <= e < %(tmin)d, no enemy in the 5x5                          24 (24)
;   split, %(smin)d <= e < %(tmin)d, enemy in the 5x5, tick >= %(late)d                25 (23)
;   hold (rest), %(smin)d <= e < %(tmin)d, enemy in the 5x5, tick < %(late)d           27 (26)
;   rest, e < %(smin)d, an empty neighbour                                17 (16)
;   rest, boxed (no empty neighbour), e < %(fd)d                         17 (15)
;   feed block, boxed and e >= %(fd)d: 21 + sum over UP, RIGHT, DOWN, LEFT of: 2 not a friend / 5 friend,
;     not poorer than the poorest so far / 7 new poorest; then feed +3, rest (no friend, or the
;     poorest above the limit) +4.  Longest: 21 + 28 + 4 = 53, far below INSN_BUDGET.
"""

CODE = """\

start:
	movdqu		xmm0, [rdi + VIEW_CELLS + VIEW_UP]	; view idx 7..22
	pcmpeqb		xmm0, [kEnemy]
	pmovmskb	ecx, xmm0			; bits 0 UP, 4 LEFT, 6 RIGHT, 10 DOWN
	or		al, [abs bite_tbl + rcx]	; rax = 0 at entry: al = eat action, ZF = no enemy
	jnz		EXIT_ADDR			; bite: leave through the return address

slow:						; 5 instructions so far
	movdqu		xmm1, [rdi + VIEW_CELLS + %(win)d]	; view idx %(win)d..%(winend)d
	pcmpeqb		xmm1, [kRefill]			; empty neighbours, enemies beside/beyond them
	pmovmskb	ecx, xmm1			; mask 0..%(nmax)d
	mov		al, [abs act_tbl + rcx]		; split to take (0 = no empty neighbour)
	cmp		sil, [abs thr_tbl + rcx]	; energy it needs (%(rmin)d refill, %(tmin)d other, 255 boxed)
	jae		EXIT_ADDR			; refill / split: 11 instructions
	test		al, al
	jz		boxed
	cmp		esi, %(smin)d
	jb		rest
	movdqu		xmm1, [rdi + VIEW_CELLS]	; view idx 0..15
	movdqu		xmm2, [rdi + VIEW_CELLS + 9]	; view idx 9..24
	pcmpeqb		xmm1, [kTwoLo]			; lane 12 (self) never matches
	pcmpeqb		xmm2, [kTwoHi]			; lane 3 (self) never matches
	por		xmm1, xmm2
	pmovmskb	edx, xmm1
	test		edx, edx
	jnz		threat
	ret					; split: no enemy in the 5x5
threat:
	cmp		dword [rdi + VIEW_TICK], %(late)d
	jae		EXIT_ADDR			; late: split anyway
rest:
	mov		al, ACT_REST
	ret
boxed:
	cmp		esi, %(fd)d
	jb		rest
	lea		r9d, [rsi - %(fm)d]		; limit: poorest friend <= e - %(fm)d ...
	mov		r10d, %(tmax)d
	cmp		esi, %(fmin)d
	cmovae		r9d, r10d			; ... or <= %(tmax)d for a capped donor
	mov		r8d, 255			; poorest friend energy so far
	mov		eax, ACT_REST
%(feedblock)s
	cmp		r8d, r9d
	ja		rest				; no friend (255), or the poorest is above the limit
	ret					; al = ACT_FEED + direction

; ---- constants (legacy-SSE memory operands must be 16-byte aligned)
	align 16
kEnemy:	db %(kenemy)s	; 2 at UP/LEFT/RIGHT/DOWN lanes (window idx 7..22)
kRefill:	db %(krefill)s	; window idx %(win)d..%(winend)d: 0 at neighbours, 2 at 6/8/10/14/16/18
kTwoLo:	db %(ktwolo)s	; idx 0..15, self (lane 12) excluded
kTwoHi:	db %(ktwohi)s	; idx 9..24, self (lane 3) excluded

; ---- bite_tbl: %(nb)d bytes, index = adjacent-enemy mask; 0 = no enemy (falls to slow)
bite_tbl:
"""


def generate(refill_min=REFILL_MIN, threat_min=THREAT_MIN, feed_d=FEED_D, feed_margin=FEED_MARGIN,
             feed_min=FEED_MIN, feed_tmax=FEED_TMAX):
    fb = '\n'.join(C.FEED_DIR % {'idx': i, 'name': G.DIR_NAMES[d], 'uname': G.DIR_NAMES[d].upper()}
                   for d, i in C.FEED_ORDER)
    kref = {'l%d' % (i - WIN): 0 for i in EMPTY_IDX.values()}
    kref.update({'l%d' % (i - WIN): 2 for i in ENEMY_IDX})
    p = {'smin': G.SPLIT_MIN, 'tmin': threat_min, 'late': G.LATE_TICK, 'nb': G.N_MASKS,
         'rmin': refill_min, 'r': refill_min // 2, 'fd': feed_d, 'fm': feed_margin,
         'fmin': feed_min, 'tmax': feed_tmax, 'feedblock': fb, 'win': WIN, 'winend': WIN + 15,
         'nmax': N_REFILL - 1,
         'kenemy': G.lanes16(0xFF, l0=2, l4=2, l6=2, l10=2),
         'krefill': G.lanes16(0xFF, **kref),
         'ktwolo': G.lanes16(2, l12=0xFF),
         'ktwohi': G.lanes16(2, l3=0xFF)}
    act, thr = refill_tables(refill_min, threat_min)
    lines = [HEADER % p + CODE % p]
    lines += G.emit_runs({m: '0x%02x' % a for m, a in C.bite_table().items()}, '0x00', 'db')
    lines.append('bite_tbl_end:')
    lines.append('')
    lines.append('; ---- act_tbl: %d bytes, index = gate-1 mask; split action, 0 = boxed (unreachable entries 0)'
                 % N_REFILL)
    lines.append('act_tbl:')
    lines += emit_table(act, N_REFILL, ACT_NOP)
    lines.append('act_tbl_end:')
    lines.append('')
    lines.append('; ---- thr_tbl: %d bytes, index = gate-1 mask; energy needed (unreachable entries 255)' % N_REFILL)
    lines.append('thr_tbl:')
    lines += emit_table(thr, N_REFILL, 255)
    lines.append('thr_tbl_end:')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'scourge.asm')
    src = generate()
    with open(out, 'w', newline='\n') as f:
        f.write(src)
    print('wrote %s (%d bytes source)' % (out, len(src.encode())))
