"""Generate cells/bane3.asm (Bane v2.3a: Bane v2.2 with a cheaper first bite).  Tables are never written by hand.

    python cells/gen_bane3.py     # writes cells/bane3.asm next to this file

Bane v2.3a is Bane v2.2 (cells/gen_bane2.py) with one change: the first bite (no stored bite, an enemy beside the
cell) costs 12 instructions, not 16.  The stored-bite bytes swap places: [2] = the eat action, [3] = view index + 8
of the bitten square (the offset LOCK reads, as in v2.2; 0 = none).  lock2_tbl holds, per adjacent-enemy mask, the word
action | square << 8, so one 16-bit load gives the action in al and one 16-bit store keeps both bytes:

    v2.2:  mov al, [bite_tbl + rcx] / test al, al / jnz setlock;  setlock: 5 stores and lookups, ret   (16)
    v2.3a: mov ax, [lock2_tbl + rcx*2] / test al, al / jnz setlock;  setlock: mov [mem + 2], ax / ret   (12)

No behaviour change: same action on every path, same memory except the two stored-bite bytes trade places, every other
path the same instruction count (the slow path still starts at instruction 10; the stored bite is still 4).
A further -1 on the first bite and on every slow path needs `cmove` (not yet seen running on the site): kept out.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_sprint as G  # noqa: E402
import gen_covetous as C  # noqa: E402
import gen_bane2 as B2  # noqa: E402

MEM_LOCKACT, MEM_LOCK = 2, 3        # stored bite: [2] the action, [3] the square's view offset - LOCK_BASE

BITE3 = ("\tmov\t\tax, [abs lock2_tbl + rcx*2]\t; al = eat action (0 = no enemy), ah = its stored-bite square\n"
         "\ttest\t\tal, al\n"
         "\tjnz\t\tsetlock\t\t\t\t; bite, and store it for the next tick\n")
SETLOCK3 = ("setlock:\n"
            "\tmov\t\t[abs CELLMEM_BASE + %d], ax\t; [%d] action, [%d] square: first bite 12\n"
            "\tret\n" % (MEM_LOCKACT, MEM_LOCKACT, MEM_LOCK))


def lock2_table():
    """{mask: eat action | stored-bite square << 8} for every mask with an adjacent enemy; every other word is 0."""
    return {m: a | B2.LOCK_OFF[a & 3] << 8 for m, a in C.bite_table().items()}


def _sub(src, old, new):
    assert src.count(old) == 1, old
    return src.replace(old, new)


def generate():
    p2 = B2.params()
    p3 = dict(p2, lock=MEM_LOCK, lockact=MEM_LOCKACT)
    src = B2.generate()
    k = src.index('\nstart:\n')
    head, body = src[:k], src[k:]
    head = _sub(head, '; Bane v2: Bane with a dispersal opening, for CellHack2.  GENERATED by cells/gen_bane2.py',
                '; Bane v2.3a: Bane v2.2 with a cheaper first bite, for CellHack2.  GENERATED by cells/gen_bane3.py')
    head = _sub(head, '[%d] and [%d] the stored bite,' % (B2.MEM_LOCK, B2.MEM_LOCKACT),
                '[%d] the stored bite\'s action and [%d] its square,' % (MEM_LOCKACT, MEM_LOCK))
    head = _sub(head, 'bite it and store the bite (memory [%d] square, [%d] action): 16.' % (B2.MEM_LOCK,
                                                                                               B2.MEM_LOCKACT),
                'bite it and store the bite (memory [%d] action, [%d] square): 12.' % (MEM_LOCKACT, MEM_LOCK))
    head = _sub(head, ';   stored bite 4, first bite 16,', ';   stored bite 4, first bite 12,')
    body = _sub(body, B2.LOCK % p2, B2.LOCK % p3)
    body = _sub(body, B2.BITE_TO, BITE3)
    body = _sub(body, B2.SETLOCK % p2, SETLOCK3)
    body = _sub(body, 'lock_off:\tdb %s\t; stored-bite offset for UP, RIGHT, DOWN, LEFT\n'
                % ', '.join('%d' % i for i in B2.LOCK_OFF), '')
    assert 'lock_off' not in body and 'bite_tbl + rcx' not in body
    tbl = ['', '; ---- lock2_tbl: %d words, index = adjacent-enemy mask; eat action | stored-bite square << 8, '
               '0 = no enemy' % G.N_MASKS, 'lock2_tbl:']
    tbl += G.emit_runs({m: '0x%04x' % w for m, w in lock2_table().items()}, '0x0000', 'dw')
    tbl += ['lock2_tbl_end:', '']
    body = _sub(body, 'bite_tbl_end:\n', 'bite_tbl_end:\n' + '\n'.join(tbl))
    return head + body


if __name__ == '__main__':
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'bane3.asm')
    src = generate()
    with open(out, 'w', newline='\n') as f:
        f.write(src)
    print('wrote %s (%d bytes source)' % (out, len(src.encode())))
