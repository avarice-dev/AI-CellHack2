"""Generate cells/conceit.asm (the "Conceit" cell: VEX variant of Covetous).  Tables are never written by hand.

    python cells/gen_conceit.py         # writes cells/conceit.asm next to this file

Conceit makes exactly Covetous's decisions (cells/gen_covetous.py) with one instruction less on every path
through the split check.  Site calibration (data/site-observations-2026-11-08.md, "VEX"): AVX-128 VEX forms of
SSE2 ops run and their memory operand may be unaligned.  The bite loads the raw window of view idx 7..22 into
xmm3 and compares it with the non-destructive `vpcmpeqb xmm0, xmm3, [kEnemy]` (still 5 instructions); the split
check compares xmm3 again (`vpcmpeqb xmm0, xmm3, [kEmpty]`) instead of movdqu + pcmpeqb.  The 5x5 check uses
vpcmpeqb with memory constants, so no legacy-SSE memory operand is left and `align 16` is gone.  Same masks and
tables as Covetous (bite_table, split_table).
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_sprint as G  # noqa: E402
import gen_covetous as C  # noqa: E402
from gen_covetous import FEED_MIN, FEED_TMAX, FEED_DIR, FEED_ORDER, bite_table  # noqa: E402,F401

HEADER = """\
; Conceit: VEX variant of Covetous for CellHack2.  GENERATED by cells/gen_conceit.py -- do not edit by hand.
; Written with AI help.
;
; Paste this whole file into the site.  It has no org/bits/section/%%include on purpose: the server
; prepends `bits 64 / org CODE_BASE / default rel / <cellhack.inc>` and runs `nasm -f bin`.
; CPU target: the site's qemu CPU: SSE2 plus AVX-128 VEX forms of SSE2 ops (vpcmpeqb, site-verified with an
; unaligned memory operand).  No SSSE3/SSE4/BMI/popcnt/ymm.  No legacy-SSE memory operand, so no alignment
; rule.  No memory writes, no loops, no stack use.
; Relies on: rax = 0 at entry (registers are reset before every call).  The bite path leaves with
; `jnz EXIT_ADDR` (a jump to the address `ret` would return to) instead of `ret`.
;
; Behaviour: exactly Covetous's (cells/covetous.asm).
;   1. An enemy next to me: bite it.  One enemy: that one.  Two or four: first of DOWN, LEFT, UP, RIGHT.
;      Exactly three: the one opposite the single non-enemy side.  (Same choices as Sprint.)
;   2. Otherwise split when energy >= threshold.  Threshold = %(smin)d, but %(tmin)d while an enemy is anywhere
;      in the 5x5 view, and %(smin)d again from tick %(late)d on.  The split goes to the first empty adjacent
;      square of DOWN, RIGHT, UP, LEFT.
;   3. When not splitting (no empty neighbour, or holding for the threshold) and energy >= %(fmin)d: feed the
;      poorest friend neighbour (ties UP, RIGHT, DOWN, LEFT) if its energy <= %(tmax)d.
;   4. Otherwise rest.
;
; Instruction counts per path (every executed instruction, including taken jumps and ret;
; in brackets the same path with taken jumps not counted); Covetous's minus 1 on every path through the
; split check (the bite's raw window is compared again instead of reloaded):
;   bite (any adjacent enemy)                                     5  (4)
;   rest, e < %(smin)d                                                9  (8)
;   split, no enemy in view, e >= %(smin)d                              21 (21)
;   split, enemy in view, e >= %(tmin)d                                 23 (21)
;   split, enemy in view, %(smin)d <= e < %(tmin)d, tick >= %(late)d               25 (23)
;   feed block entered at F (F = 19 no enemy in view / no empty; 19 holding in view, tick < %(late)d;
;     21 enemy in view, e >= %(tmin)d, no empty; 23 same but late with e < %(tmin)d):
;     rest, e < %(fmin)d                                               F + 4
;     otherwise F + 4 + sum over UP, RIGHT, DOWN, LEFT of: 2 not a friend / 5 friend, not poorer than
;     the poorest so far / 7 new poorest; then feed +3, rest (no friend, or poorest > %(tmax)d) +4.
;     Longest: 23 + 4 + 28 + 4 = 59, far below INSN_BUDGET.
"""

CODE = """\

start:
	movdqu		xmm3, [rdi + VIEW_CELLS + VIEW_UP]	; raw view idx 7..22, kept for the split check
	vpcmpeqb	xmm0, xmm3, [kEnemy]
	pmovmskb	ecx, xmm0			; bits 0 UP, 4 LEFT, 6 RIGHT, 10 DOWN
	or		al, [abs bite_tbl + rcx]	; rax = 0 at entry: al = eat action, ZF = no enemy
	jnz		EXIT_ADDR			; bite: leave through the return address

slow:						; 5 instructions so far
	cmp		esi, SPLIT_MIN
	jb		rest
	movdqu		xmm1, [rdi + VIEW_CELLS]	; view idx 0..15
	movdqu		xmm2, [rdi + VIEW_CELLS + 9]	; view idx 9..24
	vpcmpeqb	xmm1, xmm1, [kTwoLo]		; lane 12 (self) never matches
	vpcmpeqb	xmm2, xmm2, [kTwoHi]		; lane 3 (self) never matches
	por		xmm1, xmm2
	pmovmskb	eax, xmm1
	test		eax, eax
	jnz		threat
split:
	vpcmpeqb	xmm0, xmm3, [kEmpty]		; the bite's raw window again
	pmovmskb	eax, xmm0			; bits set = empty adjacent squares
	test		eax, eax
	jz		feed
	mov		al, [abs split_tbl + rax]	; non-zero mask -> a split
	ret
threat:
	cmp		esi, %(tmin)d
	jae		split
	cmp		dword [rdi + VIEW_TICK], %(late)d
	jae		split
feed:
	cmp		esi, %(fmin)d
	jb		rest
	mov		r8d, 255			; poorest friend energy so far
	mov		eax, ACT_REST
%(feedblock)s
	cmp		r8d, %(tmax)d
	ja		rest				; no friend (255), or the poorest is near the cap too
	ret					; al = ACT_FEED + direction
rest:
	mov		al, ACT_REST
	ret

; ---- constants (VEX memory operands: no alignment needed)
kEnemy:	db %(kenemy)s	; 2 at UP/LEFT/RIGHT/DOWN lanes
kEmpty:	db %(kempty)s	; 0 at UP/LEFT/RIGHT/DOWN lanes
kTwoLo:	db %(ktwolo)s	; idx 0..15, self (lane 12) excluded
kTwoHi:	db %(ktwohi)s	; idx 9..24, self (lane 3) excluded

; ---- bite_tbl: %(n)d bytes, index = adjacent-enemy mask; 0 = no enemy (falls to slow)
bite_tbl:
"""


def generate(feed_min=FEED_MIN, feed_tmax=FEED_TMAX):
    fb = '\n'.join(FEED_DIR % {'idx': i, 'name': G.DIR_NAMES[d], 'uname': G.DIR_NAMES[d].upper()}
                   for d, i in FEED_ORDER)
    p = {'smin': G.SPLIT_MIN, 'tmin': G.THREAT_MIN, 'late': G.LATE_TICK, 'n': G.N_MASKS,
         'fmin': feed_min, 'tmax': feed_tmax, 'feedblock': fb,
         'kenemy': G.lanes16(0xFF, l0=2, l4=2, l6=2, l10=2),
         'kempty': G.lanes16(0xFF, l0=0, l4=0, l6=0, l10=0),
         'ktwolo': G.lanes16(2, l12=0xFF),
         'ktwohi': G.lanes16(2, l3=0xFF)}
    lines = [HEADER % p + CODE % p]
    lines += G.emit_runs({m: '0x%02x' % a for m, a in bite_table().items()}, '0x00', 'db')
    lines.append('bite_tbl_end:')
    lines.append('')
    lines.append('; ---- split_tbl: %d bytes, index = empty-adjacent mask (mask 0 never looked up)' % G.N_MASKS)
    lines.append('split_tbl:')
    lines += G.emit_runs({m: '0x%02x' % a for m, a in G.split_table().items()}, '0x%02x' % G.ACT_REST, 'db')
    lines.append('split_tbl_end:')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'conceit.asm')
    src = generate()
    with open(out, 'w', newline='\n') as f:
        f.write(src)
    print('wrote %s (%d bytes source)' % (out, len(src.encode())))
