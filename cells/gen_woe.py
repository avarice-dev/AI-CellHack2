"""Generate cells/woe.asm (the "Woe" cell: VEX variant of Scourge).  Tables are never written by hand.

    python cells/gen_woe.py             # writes cells/woe.asm next to this file

Woe makes exactly Scourge's decisions (cells/gen_scourge.py, designs.md rounds 4-5) with one instruction less on
every path after the bite.  Site calibration (data/site-observations-2026-11-08.md, "VEX"): AVX-128 VEX forms
of SSE2 ops run and their memory operand may be unaligned.  A VEX compare is non-destructive
(`vpcmpeqb xmm0, xmm3, [mem]`), so:
  1. The bite loads the raw window of view idx 6..21 once into xmm3 (movdqu, unaligned is fine) and compares it
     against kEnemy (2 at lanes 1 UP, 5 LEFT, 7 RIGHT, 11 DOWN).  The bite mask is Covetous's shifted one lane
     (max 0x8a2, table 2211 bytes); still 5 instructions.
  2. Gate 1 compares the same register against kRefill (Scourge's constant, unchanged): one vpcmpeqb instead of
     movdqu + pcmpeqb, so a refill or split takes 10 instructions (Scourge 11).  Same mask, same act/thr tables.
  3. The 5x5 check uses vpcmpeqb with the constants as memory operands: no legacy-SSE memory operand is left, so
     the constants need no alignment and `align 16` is gone.
Instructions used: movdqu, vpcmpeqb, pmovmskb, por and plain integer ops (cells/check_cells.py ALLOWED).
Squares 2 and 22 stay unread, as in Scourge: no 16-byte window holds idx 2..22, and reading them costs a second
window plus a merge (>= 3 instructions on the refill path).
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_sprint as G  # noqa: E402
import gen_covetous as C  # noqa: E402
import gen_scourge as S  # noqa: E402

WIN = S.WIN                     # view idx 6..21, read once by the bite
LANE = {G.DIR_UP: 7 - WIN, G.DIR_LEFT: 11 - WIN, G.DIR_RIGHT: 13 - WIN, G.DIR_DOWN: 17 - WIN}   # 1, 5, 7, 11
N_BITE = (max(C.bite_table()) << 1) + 1                    # 0x451 << 1 = 0x8a2 -> 2211 bytes
refill_tables = S.refill_tables
refill_mask = S.refill_mask
N_REFILL = S.N_REFILL


def bite_table():
    """{mask: eat action} for the window-6 bite mask: Covetous's table, every mask shifted one lane."""
    return {m << 1: a for m, a in C.bite_table().items()}


HEADER = """\
; Woe: VEX variant of Scourge for CellHack2.  GENERATED by cells/gen_woe.py -- do not edit by hand.
; Written with AI help.
;
; Paste this whole file into the site.  It has no org/bits/section/%%include on purpose: the server
; prepends `bits 64 / org CODE_BASE / default rel / <cellhack.inc>` and runs `nasm -f bin`.
; CPU target: the site's qemu CPU: SSE2 plus AVX-128 VEX forms of SSE2 ops (vpcmpeqb, site-verified with an
; unaligned memory operand).  No SSSE3/SSE4/BMI/popcnt/ymm.  No legacy-SSE memory operand, so no alignment
; rule.  No memory reads or writes of the cell memory, no loops, no stack use.  Relies on: rax = 0 at entry.
; The bite and gate-1 paths leave with `jnz`/`jae EXIT_ADDR` (a jump to the address `ret` would return to).
;
; Behaviour: exactly Scourge's (cells/scourge.asm).
;   1. An enemy next to me: bite it.  One enemy: that one.  Two or four: first of DOWN, LEFT, UP, RIGHT.
;      Exactly three: the one opposite the single non-enemy side.
;   2. Refill: an empty neighbour with an enemy beside or beyond it (view squares 6, 8, 10, 14, 16, 18;
;      2 and 22 are not read) is a freed front square: split into it when energy >= %(rmin)d (child >= %(r)d).
;      First freed square of DOWN, RIGHT, UP, LEFT.
;   3. Otherwise split into the first empty neighbour of DOWN, RIGHT, UP, LEFT when energy >= %(tmin)d, or
;      when %(smin)d <= energy < %(tmin)d and no enemy is anywhere in the 5x5 view (from tick %(late)d: always).
;   4. No empty neighbour and energy >= %(fd)d: feed the poorest friend neighbour (ties UP, RIGHT, DOWN,
;      LEFT) if its energy <= energy - %(fm)d; from energy %(fmin)d on, if its energy <= %(tmax)d.
;   5. Otherwise rest.
;
; Instruction counts per path (every executed instruction, including taken jumps and ret;
; in brackets the same path with taken jumps not counted); Scourge's minus 1 after the bite:
;   bite (any adjacent enemy)                                      5  (4)
;   refill (freed front square, e >= %(rmin)d)                          10  (9)
;   split, e >= %(tmin)d                                                10  (9)
;   split, %(smin)d <= e < %(tmin)d, no enemy in the 5x5                          23 (23)
;   split, %(smin)d <= e < %(tmin)d, enemy in the 5x5, tick >= %(late)d                24 (22)
;   hold (rest), %(smin)d <= e < %(tmin)d, enemy in the 5x5, tick < %(late)d           26 (25)
;   rest, e < %(smin)d, an empty neighbour                                16 (15)
;   rest, boxed (no empty neighbour), e < %(fd)d                         16 (14)
;   feed block, boxed and e >= %(fd)d: 20 + sum over UP, RIGHT, DOWN, LEFT of: 2 not a friend / 5 friend,
;     not poorer than the poorest so far / 7 new poorest; then feed +3, rest +4.  Longest: 52.
"""

CODE = """\

start:
	movdqu		xmm3, [rdi + VIEW_CELLS + %(win)d]	; raw view idx %(win)d..%(winend)d, kept for gate 1
	vpcmpeqb	xmm0, xmm3, [kEnemy]
	pmovmskb	ecx, xmm0			; bits 1 UP, 5 LEFT, 7 RIGHT, 11 DOWN
	or		al, [abs bite_tbl + rcx]	; rax = 0 at entry: al = eat action, ZF = no enemy
	jnz		EXIT_ADDR			; bite: leave through the return address

slow:						; 5 instructions so far
	vpcmpeqb	xmm1, xmm3, [kRefill]		; empty neighbours, enemies beside/beyond them
	pmovmskb	ecx, xmm1			; mask 0..%(nmax)d
	mov		al, [abs act_tbl + rcx]		; split to take (0 = no empty neighbour)
	cmp		sil, [abs thr_tbl + rcx]	; energy it needs (%(rmin)d refill, %(tmin)d other, 255 boxed)
	jae		EXIT_ADDR			; refill / split: 10 instructions
	test		al, al
	jz		boxed
	cmp		esi, %(smin)d
	jb		rest
	movdqu		xmm1, [rdi + VIEW_CELLS]	; view idx 0..15
	movdqu		xmm2, [rdi + VIEW_CELLS + 9]	; view idx 9..24
	vpcmpeqb	xmm1, xmm1, [kTwoLo]		; lane 12 (self) never matches
	vpcmpeqb	xmm2, xmm2, [kTwoHi]		; lane 3 (self) never matches
	por		xmm1, xmm2
	pmovmskb	edx, xmm1
	test		edx, edx
	jnz		threat
	ret					; split: no enemy in the 5x5
threat:
	cmp		dword [rdi + VIEW_TICK], %(late)d
	jae		EXIT_ADDR			; late: split anyway
rest:
	mov		al, ACT_REST
	ret
boxed:
	cmp		esi, %(fd)d
	jb		rest
	lea		r9d, [rsi - %(fm)d]		; limit: poorest friend <= e - %(fm)d ...
	mov		r10d, %(tmax)d
	cmp		esi, %(fmin)d
	cmovae		r9d, r10d			; ... or <= %(tmax)d for a capped donor
	mov		r8d, 255			; poorest friend energy so far
	mov		eax, ACT_REST
%(feedblock)s
	cmp		r8d, r9d
	ja		rest				; no friend (255), or the poorest is above the limit
	ret					; al = ACT_FEED + direction

; ---- constants (VEX memory operands: no alignment needed)
kEnemy:	db %(kenemy)s	; 2 at UP/LEFT/RIGHT/DOWN lanes (window idx %(win)d..%(winend)d)
kRefill:	db %(krefill)s	; window idx %(win)d..%(winend)d: 0 at neighbours, 2 at 6/8/10/14/16/18
kTwoLo:	db %(ktwolo)s	; idx 0..15, self (lane 12) excluded
kTwoHi:	db %(ktwohi)s	; idx 9..24, self (lane 3) excluded

; ---- bite_tbl: %(nb)d bytes, index = adjacent-enemy mask (window %(win)d); 0 = no enemy (falls to slow)
bite_tbl:
"""


def params(refill_min=S.REFILL_MIN, threat_min=S.THREAT_MIN, feed_d=S.FEED_D, feed_margin=S.FEED_MARGIN,
           feed_min=S.FEED_MIN, feed_tmax=S.FEED_TMAX):
    fb = '\n'.join(C.FEED_DIR % {'idx': i, 'name': G.DIR_NAMES[d], 'uname': G.DIR_NAMES[d].upper()}
                   for d, i in C.FEED_ORDER)
    kref = {'l%d' % (i - WIN): 0 for i in S.EMPTY_IDX.values()}
    kref.update({'l%d' % (i - WIN): 2 for i in S.ENEMY_IDX})
    return {'smin': G.SPLIT_MIN, 'tmin': threat_min, 'late': G.LATE_TICK, 'nb': N_BITE,
            'rmin': refill_min, 'r': refill_min // 2, 'fd': feed_d, 'fm': feed_margin,
            'fmin': feed_min, 'tmax': feed_tmax, 'feedblock': fb, 'win': WIN, 'winend': WIN + 15,
            'nmax': N_REFILL - 1,
            'kenemy': G.lanes16(0xFF, **{'l%d' % l: 2 for l in LANE.values()}),
            'krefill': G.lanes16(0xFF, **kref),
            'ktwolo': G.lanes16(2, l12=0xFF),
            'ktwohi': G.lanes16(2, l3=0xFF)}


def tables(refill_min=S.REFILL_MIN, threat_min=S.THREAT_MIN):
    """The bite / act / thr table lines (shared with gen_endemic.py)."""
    act, thr = refill_tables(refill_min, threat_min)
    lines = G.emit_runs({m: '0x%02x' % a for m, a in bite_table().items()}, '0x00', 'db')
    last = max(bite_table())
    if last + 1 < N_BITE:
        lines.append('\ttimes %d db 0x00' % (N_BITE - last - 1))
    lines.append('bite_tbl_end:')
    lines.append('')
    lines.append('; ---- act_tbl: %d bytes, index = gate-1 mask; split action, 0 = boxed (unreachable entries 0)'
                 % N_REFILL)
    lines.append('act_tbl:')
    lines += S.emit_table(act, N_REFILL, S.ACT_NOP)
    lines.append('act_tbl_end:')
    lines.append('')
    lines.append('; ---- thr_tbl: %d bytes, index = gate-1 mask; energy needed (unreachable entries 255)' % N_REFILL)
    lines.append('thr_tbl:')
    lines += S.emit_table(thr, N_REFILL, 255)
    lines.append('thr_tbl_end:')
    return lines


def generate(**kw):
    p = params(**kw)
    lines = [HEADER % p + CODE % p]
    lines += tables(kw.get('refill_min', S.REFILL_MIN), kw.get('threat_min', S.THREAT_MIN))
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'woe.asm')
    src = generate()
    with open(out, 'w', newline='\n') as f:
        f.write(src)
    print('wrote %s (%d bytes source)' % (out, len(src.encode())))
