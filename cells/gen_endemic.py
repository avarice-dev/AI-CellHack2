"""Generate cells/endemic.asm (the "Endemic" cell: VEX variant of Contagion).  Tables are never written by hand.

    python cells/gen_endemic.py         # writes cells/endemic.asm next to this file

Endemic makes exactly Contagion's decisions (cells/gen_contagion.py: scout, grab assist, feeding floor 12, same
memory layout) with the VEX changes of Woe (cells/gen_woe.py, VEX variant of Scourge):
  1. The bite reads the raw window of view idx 6..21 into xmm3 (Woe's shifted bite table, 5 instructions); gate 1
     compares xmm3 again with `vpcmpeqb xmm1, xmm3, [kRefill]`: refill / split in 10 (Contagion 11), and -1 on
     every later path.
  2. The boxed block builds its two empty masks with `vpcmpeqb xmmN, xmmView, [kZero]` instead of pxor + pcmpeqb:
     -2 more from the grab gate on (boxed, e >= 8).
  3. No legacy-SSE memory operand is left, so `align 16` is gone.
Nothing on the bite / gate-1 path touches the cell memory.  Site probes q/r (2026-11-08) found xmm0..15 and the
GPRs zero at entry; Endemic does not rely on that (kZero is a constant; same count either way).
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_sprint as G  # noqa: E402
import gen_covetous as C  # noqa: E402
import gen_scourge as S  # noqa: E402
import gen_woe as W  # noqa: E402
from gen_woe import bite_table, refill_tables  # noqa: E402,F401

REFILL_MIN, THREAT_MIN = S.REFILL_MIN, S.THREAT_MIN
FEED_D = 12
FEED_MARGIN = S.FEED_MARGIN
FEED_MIN, FEED_TMAX = S.FEED_MIN, S.FEED_TMAX
GRAB_G = 8              # grab-assist donor floor
GRAB_TMAX = 4           # grab-assist target energy < 5
EDGE = 10               # scout only if the start is within this many squares of an edge
STEPS = 10              # scout moves
# ring squares that are the neighbours of each neighbour (self excluded)
RING = {G.DIR_UP: (2, 6, 8), G.DIR_RIGHT: (8, 14, 18), G.DIR_DOWN: (16, 18, 22), G.DIR_LEFT: (6, 10, 16)}
GRAB_ORDER = ((G.DIR_UP, 7), (G.DIR_RIGHT, 13), (G.DIR_DOWN, 17), (G.DIR_LEFT, 11))

HEADER = """\
; Endemic: VEX variant of Contagion for CellHack2.  GENERATED by cells/gen_endemic.py -- do not edit by hand.
; Written with AI help.
;
; Paste this whole file into the site.  It has no org/bits/section/%%include on purpose: the server
; prepends `bits 64 / org CODE_BASE / default rel / <cellhack.inc>` and runs `nasm -f bin`.
; CPU target: the site's qemu CPU: SSE2 plus AVX-128 VEX forms of SSE2 ops (vpcmpeqb, site-verified with an
; unaligned memory operand).  No SSSE3/SSE4/BMI/popcnt/ymm.  No legacy-SSE memory operand, so no alignment
; rule.  No loops, no stack use.  Relies on: rax = 0 at entry
; (registers are reset before every call).  The bite and gate-1 paths leave with `jnz`/`jae EXIT_ADDR`
; and never touch the cell memory.
;
; Behaviour: exactly Contagion's (cells/contagion.asm); 1-3 and 6-7 are Scourge's, feeding floor %(fd)d
;   1. An enemy next to me: bite it.  One enemy: that one.  Two or four: first of DOWN, LEFT, UP, RIGHT.
;      Exactly three: the one opposite the single non-enemy side.
;   2. Refill: an empty neighbour with an enemy beside or beyond it (view squares 6, 8, 10, 14, 16, 18)
;      is a freed front square: split into it when energy >= %(rmin)d.  First of DOWN, RIGHT, UP, LEFT.
;   3. Otherwise split into the first empty neighbour of DOWN, RIGHT, UP, LEFT when energy >= %(tmin)d, or
;      when %(smin)d <= energy < %(tmin)d and no enemy is anywhere in the 5x5 view (from tick %(late)d: always);
;      with an enemy in view (before tick %(late)d) hold: rest, and stop being a scout.
;   4. Scout: at tick 0 the start cell, if within %(edge)d squares of an edge, splits toward the side with the
;      most room and marks the child a scout (memory [1] bit 1, origin [2],[3], bearing [4], steps [5]).
;      Instead of a plain split (3, no enemy in view) a scout MOVEs along its bearing, at most %(steps)d times;
;      blocked, out of steps, or at the origin square: it clears the bit and splits as usual.
;   5. Grab assist: no empty neighbour, energy >= %(g)d, no enemy in the 5x5: feed the first friend
;      neighbour (UP, RIGHT, DOWN, LEFT) with energy <= %(gt)d that has an empty neighbour.
;   6. No empty neighbour and energy >= %(fd)d: feed the poorest friend neighbour (ties UP, RIGHT, DOWN,
;      LEFT) if its energy <= energy - %(fm)d; from energy %(fmin)d on, if its energy <= %(tmax)d.
;   7. Otherwise rest.
;
; Instruction counts per path (every executed instruction, including taken jumps and ret;
; in brackets the same path with taken jumps not counted); Contagion's minus 1 after the bite, minus 3 on
; the boxed block from the grab gate on (gate 1 reuses the bite's window; empties via vpcmpeqb, no pxor):
;   bite (any adjacent enemy)                                      5  (4)
;   refill (freed front square, e >= %(rmin)d)                          10  (9)
;   split, e >= %(tmin)d                                                10  (9)
;   split, %(smin)d <= e < %(tmin)d, no enemy in the 5x5                          25 (25)
;   scout move                                                     39 (37)
;   split, %(smin)d <= e < %(tmin)d, enemy in the 5x5, tick >= %(late)d                24 (22)
;   hold (rest), %(smin)d <= e < %(tmin)d, enemy in the 5x5, tick < %(late)d           27 (26)
;   rest, e < %(smin)d, an empty neighbour                                16 (15)
;   rest, boxed, e < %(g)d                                               16 (14)
;   grab assist / feed block: Contagion's minus 3 (sim/cells_ref.py make_endemic; longest well under 100).
"""

CODE = """\

start:
	movdqu		xmm3, [rdi + VIEW_CELLS + %(win)d]	; raw view idx %(win)d..%(winend)d, kept for gate 1
	vpcmpeqb	xmm0, xmm3, [kEnemy]
	pmovmskb	ecx, xmm0			; bits 1 UP, 5 LEFT, 7 RIGHT, 11 DOWN
	or		al, [abs bite_tbl + rcx]	; rax = 0 at entry: al = eat action, ZF = no enemy
	jnz		EXIT_ADDR			; bite: leave through the return address

slow:						; 5 instructions so far
	vpcmpeqb	xmm1, xmm3, [kRefill]		; empty neighbours, enemies beside/beyond them
	pmovmskb	ecx, xmm1			; mask 0..%(nmax)d
	mov		al, [abs act_tbl + rcx]		; split to take (0 = no empty neighbour)
	cmp		sil, [abs thr_tbl + rcx]	; energy it needs (%(rmin)d refill, %(tmin)d other, 255 boxed)
	jae		EXIT_ADDR			; refill / split: 10 instructions
	test		al, al
	jz		boxed
	cmp		esi, %(smin)d
	jb		rest
	movdqu		xmm1, [rdi + VIEW_CELLS]	; view idx 0..15
	movdqu		xmm2, [rdi + VIEW_CELLS + 9]	; view idx 9..24
	vpcmpeqb	xmm1, xmm1, [kTwoLo]		; lane 12 (self) never matches
	vpcmpeqb	xmm2, xmm2, [kTwoHi]		; lane 3 (self) never matches
	por		xmm1, xmm2
	pmovmskb	r8d, xmm1
	test		r8d, r8d
	jnz		threat
	cmp		byte [rdx + 1], 1		; flags: 1 = plain cell
	jne		special
	ret					; split: no enemy in the 5x5
threat:
	cmp		dword [rdi + VIEW_TICK], %(late)d
	jae		EXIT_ADDR			; late: split anyway
	and		byte [rdx + 1], 0xFD		; hold: a scout stops here
rest:
	mov		al, ACT_REST
	ret

special:					; flags 0 (start cell, tick 0) or scout bit set
	test		byte [rdx + 1], 2
	jnz		scout
	mov		byte [rdx + 1], 1		; initialised
	cmp		dword [rdi + VIEW_TICK], 0
	jne		.plain				; only the start cell (tick 0) may send a scout
	movzx		ecx, word [rdi + VIEW_X]	; room LEFT
	movzx		r8d, word [rdi + VIEW_W]
	sub		r8d, ecx
	dec		r8d				; room RIGHT
	movzx		r9d, word [rdi + VIEW_Y]	; room UP
	movzx		r10d, word [rdi + VIEW_H]
	sub		r10d, r9d
	dec		r10d				; room DOWN
	mov		esi, ecx			; esi = least room
	cmp		esi, r8d
	cmova		esi, r8d
	cmp		esi, r9d
	cmova		esi, r9d
	cmp		esi, r10d
	cmova		esi, r10d
	cmp		esi, %(edge)d
	ja		.plain				; far from every edge: no scout
	mov		r11d, r9d			; most room so far (UP)
	xor		esi, esi			; bearing UP
	cmp		r8d, r11d
	jbe		.b1
	mov		r11d, r8d
	mov		esi, DIR_RIGHT
.b1:
	cmp		r10d, r11d
	jbe		.b2
	mov		r11d, r10d
	mov		esi, DIR_DOWN
.b2:
	cmp		ecx, r11d
	jbe		.b3
	mov		esi, DIR_LEFT
.b3:
	mov		byte [rdx + 1], 3		; initialised + scout (copied to the child)
	mov		[rdx + 2], cl			; origin x
	mov		[rdx + 3], r9b			; origin y
	mov		[rdx + 4], sil			; bearing
	mov		byte [rdx + 5], %(steps)d		; steps left
	lea		eax, [rsi + ACT_SPLIT]		; the scout is born on the bearing side
.plain:
	ret

scout:
	mov		cl, [rdi + VIEW_X]
	mov		ch, [rdi + VIEW_Y]
	cmp		cx, [rdx + 2]
	je		scout_end			; the origin cell itself
	cmp		byte [rdx + 5], 0
	je		scout_end			; out of steps
	movzx		ecx, byte [rdx + 4]		; bearing
	movzx		r8d, byte [abs dir_idx + rcx]
	cmp		byte [rdi + VIEW_CELLS + r8], CELL_EMPTY
	jne		scout_end			; blocked
	dec		byte [rdx + 5]
	lea		eax, [rcx + ACT_MOVE]
	ret
scout_end:
	mov		byte [rdx + 1], 1
	ret					; al = the plain split

boxed:
	cmp		esi, %(g)d
	jb		rest
	movdqu		xmm1, [rdi + VIEW_CELLS]	; view idx 0..15
	movdqu		xmm2, [rdi + VIEW_CELLS + 9]	; view idx 9..24
	vpcmpeqb	xmm3, xmm1, [kZero]		; empty squares, idx 0..15
	vpcmpeqb	xmm4, xmm2, [kZero]		; empty squares, idx 9..24
	vpcmpeqb	xmm1, xmm1, [kTwoLo]
	vpcmpeqb	xmm2, xmm2, [kTwoHi]
	por		xmm1, xmm2
	pmovmskb	r8d, xmm1
	test		r8d, r8d
	jnz		feed_d				; enemy in the 5x5: no grab assist
	pmovmskb	r9d, xmm3
	pmovmskb	r10d, xmm4
	shl		r10d, 9
	or		r9d, r10d			; bit i = view square i empty
%(grabblock)s
feed_d:
	cmp		esi, %(fd)d
	jb		rest
	lea		r9d, [rsi - %(fm)d]		; limit: poorest friend <= e - %(fm)d ...
	mov		r10d, %(tmax)d
	cmp		esi, %(fmin)d
	cmovae		r9d, r10d			; ... or <= %(tmax)d for a capped donor
	mov		r8d, 255			; poorest friend energy so far
	mov		eax, ACT_REST
%(feedblock)s
	cmp		r8d, r9d
	ja		rest				; no friend (255), or the poorest is above the limit
	ret					; al = ACT_FEED + direction

; ---- constants (VEX memory operands: no alignment needed)
kEnemy:	db %(kenemy)s	; 2 at UP/LEFT/RIGHT/DOWN lanes (window idx %(win)d..%(winend)d)
kZero:	times 16 db 0		; empty = 0
kRefill:	db %(krefill)s	; window idx %(win)d..%(winend)d: 0 at neighbours, 2 at 6/8/10/14/16/18
kTwoLo:	db %(ktwolo)s	; idx 0..15, self (lane 12) excluded
kTwoHi:	db %(ktwohi)s	; idx 9..24, self (lane 3) excluded
dir_idx:	db VIEW_UP, VIEW_RIGHT, VIEW_DOWN, VIEW_LEFT

; ---- bite_tbl: %(nb)d bytes, index = adjacent-enemy mask (window %(win)d); 0 = no enemy (falls to slow)
bite_tbl:
"""

GRAB_DIR = """\
	cmp		byte [rdi + VIEW_CELLS + %(idx)d], CELL_FRIEND	; grab: %(name)s
	jne		.g_%(name)s
	cmp		byte [rdi + VIEW_ENERGIES + %(idx)d], %(gt)d
	ja		.g_%(name)s
	test		r9d, 0x%(ring)x			; an empty neighbour of it
	jz		.g_%(name)s
	mov		al, ACT_FEED + DIR_%(uname)s
	ret
.g_%(name)s:"""


def generate(feed_d=FEED_D, grab_g=GRAB_G, edge=EDGE, steps=STEPS):
    fb = '\n'.join(C.FEED_DIR % {'idx': i, 'name': G.DIR_NAMES[d], 'uname': G.DIR_NAMES[d].upper()}
                   for d, i in C.FEED_ORDER)
    gb = '\n'.join(GRAB_DIR % {'idx': i, 'name': G.DIR_NAMES[d], 'uname': G.DIR_NAMES[d].upper(),
                               'gt': GRAB_TMAX, 'ring': sum(1 << q for q in RING[d])}
                   for d, i in GRAB_ORDER)
    kref = {'l%d' % (i - S.WIN): 0 for i in S.EMPTY_IDX.values()}
    kref.update({'l%d' % (i - S.WIN): 2 for i in S.ENEMY_IDX})
    p = {'smin': G.SPLIT_MIN, 'tmin': THREAT_MIN, 'late': G.LATE_TICK, 'nb': W.N_BITE,
         'rmin': REFILL_MIN, 'fd': feed_d, 'fm': FEED_MARGIN, 'fmin': FEED_MIN, 'tmax': FEED_TMAX,
         'g': grab_g, 'gt': GRAB_TMAX, 'edge': edge, 'steps': steps,
         'feedblock': fb, 'grabblock': gb, 'win': S.WIN, 'winend': S.WIN + 15, 'nmax': S.N_REFILL - 1,
         'kenemy': G.lanes16(0xFF, **{'l%d' % l: 2 for l in W.LANE.values()}),
         'krefill': G.lanes16(0xFF, **kref),
         'ktwolo': G.lanes16(2, l12=0xFF),
         'ktwohi': G.lanes16(2, l3=0xFF)}
    lines = [HEADER % p + CODE % p]
    lines += W.tables(REFILL_MIN, THREAT_MIN)
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'endemic.asm')
    src = generate()
    with open(out, 'w', newline='\n') as f:
        f.write(src)
    print('wrote %s (%d bytes source)' % (out, len(src.encode())))
